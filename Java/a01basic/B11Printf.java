package a01basic;

public class B11Printf {

    public static void main(String[] args) {

        // ========================================================
        // printf()
        // ========================================================
        // printf = Print Formatted
        //
        // เป็น Method สำหรับแสดงผลข้อมูล โดยเราสามารถ "กำหนดรูปแบบ (Format)"
        // ของข้อมูลที่ต้องการแสดงได้
        //
        //
        // ตัวอย่าง
        //
        // System.out.printf("Score = %d", score);
        //
        // %d = ตำแหน่งที่ต้องการแสดงจำนวนเต็ม
        //
        // score = ค่าที่นำมาใส่ใน %d
        //
        // printf มีประโยชน์มากเมื่อ
        //
        // - ต้องการจัดรูปแบบข้อความ
        // - ต้องการกำหนดจำนวนทศนิยม
        // - ต้องการจัดตำแหน่งข้อมูล
        // - ต้องการแสดงข้อมูลหลายชนิดในบรรทัดเดียว


        // ========================================================
        // 1. %d
        // ========================================================
        // %d = ใช้สำหรับจำนวนเต็ม (Integer)
        //
        // เช่น
        //
        // int
        //
        // byte
        // short
        // int
        // long
        //
        // ตัวอย่าง


        int score = 95;

        System.out.printf("Score = %d%n", score);

        /*
         *   %d
         *    ↓
         * Score = 95
         *
         * %d จะถูกแทนด้วยค่าของ score
         */


        // ========================================================
        // 2. %s
        // ========================================================
        // %s = ใช้สำหรับ String
        //
        // ตัวอย่าง


        String name = "Alice";

        System.out.printf("Hello %s%n", name);

        /*
         * ผลลัพธ์
         *
         * Hello Alice
         *
         *   %s
         *    ↓
         * รับค่าจาก name
         */


        // ========================================================
        // 3. %f
        // ========================================================
        // %f = ใช้สำหรับเลขทศนิยม
        //
        // เช่น
        //
        // float
        // double
        //
        // ตัวอย่าง


        double price = 99.99;

        System.out.printf("Price = %f%n", price);

        /*
         * ผลลัพธ์ประมาณ
         *
         * Price = 99.990000
         *
         *
         * สังเกตว่า
         *
         * %f
         * จะแสดงทศนิยม 6 ตำแหน่ง เป็นค่า Default
         */


        // ========================================================
        // 4. %.2f
        // ========================================================
        // เราสามารถกำหนดจำนวนตำแหน่งทศนิยมได้
        //
        //
        // %.2f
        //
        // . = เริ่มกำหนดจำนวนทศนิยม
        //
        // 2 = แสดงทศนิยม 2 ตำแหน่ง
        //
        // f = Floating Point


        System.out.printf("Price = %.2f%n", price);

        /*
         * ผลลัพธ์
         *
         * Price = 99.99
         *
         *
         * ตัวอย่างเพิ่มเติม
         *
         * %.1f -> ทศนิยม 1 ตำแหน่ง
         *
         * %.2f -> ทศนิยม 2 ตำแหน่ง
         *
         * %.3f -> ทศนิยม 3 ตำแหน่ง
         */


        double number = 12.3456789;

        System.out.printf("%.1f%n", number); // 12.3

        System.out.printf("%.2f%n", number); // 12.35

        System.out.printf("%.3f%n", number); // 12.346


        // ========================================================
        // 5. %c
        // ========================================================
        // %c = ใช้สำหรับ Character 1 ตัว
        //
        // เช่น
        //
        // char


        char grade = 'A';

        System.out.printf("Grade = %c%n", grade);

        /*
         * ผลลัพธ์
         *
         * Grade = A
         */


        // ========================================================
        // 6. %b
        // ========================================================
        // %b = ใช้สำหรับ boolean
        //
        // boolean
        //
        // มีค่าได้ 2 ค่า
        //
        // true
        // false


        boolean isPass = true;

        System.out.printf("Pass = %b%n", isPass);

        /*
         * ผลลัพธ์
         *
         * Pass = true
         */


        // ========================================================
        // 7. %n
        // ========================================================
        // %n = ขึ้นบรรทัดใหม่
        //
        // คล้ายกับ
        //
        // System.out.println()
        //
        //
        // ตัวอย่าง


        System.out.printf("Hello%nWorld%n");

        /*
         * ผลลัพธ์
         *
         * Hello
         * World
         *
         *
         * %n มีข้อดีคือเป็น New Line
         * ที่เหมาะกับระบบปฏิบัติการต่าง ๆ
         */


        // ========================================================
        // 8. printf หลาย Format ในบรรทัดเดียว
        // ========================================================
        // เราสามารถใช้ Format Specifier
        // หลายตัวใน printf() ได้
        //
        //
        // ตัวอย่าง


        String studentName = "Nattawat";
        int age = 21;
        double height = 175.8;
        char studentGrade = 'A';

        System.out.printf(
                "Name: %s | Age: %d | Height: %.1f | Grade: %c%n",
                studentName,
                age,
                height,
                studentGrade
        );

        /*
         * ผลลัพธ์
         *
         * Name: Nattawat | Age: 21 | Height: 175.8 | Grade: A
         *
         *
         * ลำดับต้องตรงกัน
         *
         * %s -> studentName
         * %d -> age
         * %.1f -> height
         * %c -> studentGrade
         */


        // ========================================================
        // 9. การจัดความกว้างของข้อมูล
        // ========================================================
        // เราสามารถกำหนด "ความกว้าง" ของพื้นที่ที่ใช้แสดงข้อมูลได้
        //
        // ตัวอย่าง
        //
        // %10s
        //
        // 10 = จองพื้นที่ 10 ตัวอักษร
        //
        // s = String


        System.out.printf("|%10s|%n", "Java");

        /*
         * ผลลัพธ์
         *
         * |      Java|
         *
         *
         * เพราะ Java มี 4 ตัวอักษร
         * แต่กำหนดพื้นที่ไว้ 10 ช่อง
         *
         * จึงมีช่องว่างด้านหน้า
         */


        // ========================================================
        // 10. จัดชิดซ้าย
        // ========================================================
        // %10s = ชิดขวาเป็น Default
        //
        //
        // %-10s = ชิดซ้าย
        //
        // เครื่องหมาย - = จัดชิดซ้าย


        System.out.printf("|%-10s|%n", "Java");

        /*
         * ผลลัพธ์
         *
         * |Java      |
         */


        // ========================================================
        // 11. จัดตารางด้วย printf
        // ========================================================
        // printf เหมาะมากสำหรับ
        // การจัดข้อมูลให้อยู่ในรูปแบบตาราง


        System.out.printf("%-10s %5s %10s%n",
                "Name",
                "Age",
                "Score"
        );

        System.out.printf("%-10s %5d %10.2f%n",
                "Alice",
                20,
                95.50
        );

        System.out.printf("%-10s %5d %10.2f%n",
                "Bob",
                21,
                88.75
        );

        /*
         * ผลลัพธ์
         *
         * Name         Age      Score
         * Alice         20      95.50
         * Bob           21      88.75
         *
         *
         * %-10s = String กว้าง 10 ช่อง และชิดซ้าย
         *
         * %5d = Integer กว้าง 5 ช่อง และชิดขวา
         *
         * %10.2f = ทศนิยมกว้าง 10 ช่อง และแสดง 2 ตำแหน่ง
         */


        // ========================================================
        // 12. %d กับจำนวนเต็ม
        // ========================================================
        // %d ใช้กับ Integer
        //
        // ตัวอย่าง


        int number1 = 100;
        int number2 = -50;

        System.out.printf("Number 1 = %d%n", number1);
        System.out.printf("Number 2 = %d%n", number2);


        // ========================================================
        // 13. %% 
        // ========================================================
        // ถ้าต้องการแสดงเครื่องหมาย %
        // ใน printf
        //
        // ต้องใช้
        //
        // %%
        //
        // เพราะ %
        // เป็นสัญลักษณ์ที่ใช้เริ่ม Format Specifier


        double discount = 20.0;

        System.out.printf("Discount = %.0f%%%n", discount);

        /*
         * ผลลัพธ์
         *
         * Discount = 20%
         *
         *
         * %.0f = แสดงตัวเลข
         *
         * %% = แสดงเครื่องหมาย %
         */


        // ========================================================
        // 14. printf กับการคำนวณ
        // ========================================================
        // สามารถใส่ Expression
        // เข้าไปเป็น Argument ได้


        int x = 10;
        int y = 3;

        System.out.printf(
                "%d + %d = %d%n",
                x,
                y,
                x + y
        );

        System.out.printf(
                "%d * %d = %d%n",
                x,
                y,
                x * y
        );

        /*
         * ผลลัพธ์
         *
         * 10 + 3 = 13
         * 10 * 3 = 30
         */


        // ========================================================
        // 15. printf vs print vs println
        // ========================================================
        /*
         * ========================================================
         * print()
         * ========================================================
         *
         * แสดงข้อความ
         * และไม่ขึ้นบรรทัดใหม่
         *
         *
         * System.out.print("Hello");
         * System.out.print("World");
         *
         * ผลลัพธ์
         *
         * HelloWorld
         *
         *
         * ========================================================
         * println()
         * ========================================================
         *
         * แสดงข้อความ
         * แล้วขึ้นบรรทัดใหม่
         *
         *
         * System.out.println("Hello");
         * System.out.println("World");
         *
         * ผลลัพธ์
         *
         * Hello
         * World
         *
         *
         * ========================================================
         * printf()
         * ========================================================
         *
         * แสดงข้อความแบบกำหนด Format ได้
         *
         *
         * System.out.printf("Score = %d", score);
         *
         *
         * ========================================================
         */


        // ========================================================
        // 16. ตัวอย่างเปรียบเทียบ
        // ========================================================

        System.out.print("A");
        System.out.print("B");
        System.out.print("C");

        System.out.println();

        System.out.println("A");
        System.out.println("B");
        System.out.println("C");

        System.out.printf("%s %d %.2f%n",
                "Score",
                95,
                99.50
        );


        // ========================================================
        // 17. Format Specifier ที่ควรรู้
        // ========================================================
        /*
         * ========================================================
         * Format Specifier
         * ========================================================
         *
         * %d -> จำนวนเต็ม
         *
         * %f -> เลขทศนิยม
         *
         * %.2f -> เลขทศนิยม 2 ตำแหน่ง
         *
         * %s -> String
         *
         * %c -> char
         *
         * %b -> boolean
         *
         * %n -> ขึ้นบรรทัดใหม่
         *
         * %% -> แสดง %
         *
         * ========================================================
         */


        // ========================================================
        // 18. รูปแบบของ Format
        // ========================================================
        /*
         * รูปแบบพื้นฐาน
         *
         * %[flags][width][.precision]conversion
         *
         *
         * ตัวอย่าง
         *
         * %-10.2f
         *
         *   -      = ชิดซ้าย
         *   10     = ความกว้าง 10 ช่อง
         *   .2     = ทศนิยม 2 ตำแหน่ง
         *   f      = Floating Point
         *
         *
         * ตัวอย่างที่ใช้บ่อย
         *
         * %d
         * %.2f
         * %10d
         * %-10s
         * %10.2f
         */


        // ========================================================
        // 19. ตัวอย่างจริง
        // ========================================================
        // สมมติว่าเราต้องการแสดงข้อมูลนักเรียน
        // ให้ดูสวยและเป็นระเบียบ


        String name2 = "Nattawat";
        int score2 = 95;
        double gpa = 3.75;
        char grade2 = 'A';
        boolean pass = true;

        System.out.println();
        System.out.println("========== Student Information ==========");

        System.out.printf("Name   : %s%n", name2);
        System.out.printf("Score  : %d%n", score2);
        System.out.printf("GPA    : %.2f%n", gpa);
        System.out.printf("Grade  : %c%n", grade2);
        System.out.printf("Pass   : %b%n", pass);

        System.out.println("==========================================");


        // ========================================================
        // Summary
        // ========================================================
        /*
         * ========================================================
         * สรุป printf
         * ========================================================
         *
         * printf() = แสดงผลแบบกำหนด Format ได้
         *
         * ========================================================
         * Format ที่ต้องจำ
         * ========================================================
         *
         * %d = int / จำนวนเต็ม
         *
         *
         * %f = float / double
         *
         *
         * %.2f = ทศนิยม 2 ตำแหน่ง
         *
         *
         * %s = String
         *
         *
         * %c = char
         *
         *
         * %b = boolean
         *
         *
         * %n = ขึ้นบรรทัดใหม่
         *
         *
         * %% = เครื่องหมาย %
         *
         *
         * ========================================================
         * การจัดตำแหน่ง
         * ========================================================
         *
         * %10s = กว้าง 10 ช่อง ชิดขวา
         *
         *
         * %-10s = กว้าง 10 ช่อง ชิดซ้าย
         *
         *
         * %10.2f = กว้าง 10 ช่องทศนิยม 2 ตำแหน่ง
         */
    }
}