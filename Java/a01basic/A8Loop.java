package a01basic;

public class A8Loop {

    public static void main(String[] args) {

        // ========================================================
        // Loop
        // ========================================================
        // Loop = โครงสร้างควบคุมการทำงาน (Control Flow)
        //        ที่ใช้สำหรับทำคำสั่งเดิมซ้ำ ๆ
        //        จนกว่าจะเป็นไปตามเงื่อนไขที่กำหนด
        //
        // ตัวอย่างในชีวิตประจำวัน
        //
        // "พิมพ์เลข 1 ถึง 100"
        //
        // ถ้าไม่มี Loop
        //
        // System.out.println(1);
        // System.out.println(2);
        // System.out.println(3);
        // ...
        // System.out.println(100);
        //
        // จะต้องเขียน 100 บรรทัด
        //
        // แต่ใช้ Loop
        //
        // for (int i = 1; i <= 100; i++) {
        //     System.out.println(i);
        // }
        //
        // เขียนไม่กี่บรรทัดก็ทำงาน 100 รอบได้
        //
        //
        // Loop หลัก ๆ ที่ควรรู้
        //
        // 1. for
        // 2. while
        // 3. do-while
        // 4. Nested Loop
        //
        // และคำสั่งควบคุม Loop
        //
        // 5. break
        // 6. continue


        // ========================================================
        // 1. for Loop
        // ========================================================
        // for Loop = ใช้เมื่อ "รู้จำนวนรอบ" ที่ต้องการวน
        //
        // รูปแบบ
        //
        // for (initialization; condition; update) {
        //     // คำสั่งที่ต้องการให้ทำซ้ำ
        // }
        //
        // เช่น
        //
        // for (int i = 1; i <= 5; i++)
        //
        // int i = 1
        //     = กำหนดค่าเริ่มต้น
        //
        // i <= 5
        //     = เงื่อนไขในการวน
        //
        // i++
        //     = เพิ่มค่า i ทีละ 1


        for (int i = 1; i <= 5; i++) {

            System.out.println(i);
        }

        /*
         * การทำงาน
         *
         * รอบที่ 1
         * i = 1
         * 1 <= 5 -> true
         * พิมพ์ 1
         *
         * รอบที่ 2
         * i = 2
         * 2 <= 5 -> true
         * พิมพ์ 2
         *
         * รอบที่ 3
         * i = 3
         * 3 <= 5 -> true
         * พิมพ์ 3
         *
         * รอบที่ 4
         * i = 4
         * 4 <= 5 -> true
         * พิมพ์ 4
         *
         * รอบที่ 5
         * i = 5
         * 5 <= 5 -> true
         * พิมพ์ 5
         *
         * รอบต่อไป
         * i = 6
         * 6 <= 5 -> false
         *
         * จบ Loop
         */


        // ========================================================
        // 2. while Loop
        // ========================================================
        // while Loop = ใช้เมื่อ "ไม่รู้จำนวนรอบที่แน่นอน"
        //              แต่รู้ว่า "ต้องทำไปเรื่อย ๆ จนกว่าเงื่อนไขจะเป็น false"
        //
        // รูปแบบ
        //
        // while (condition) {
        //     // คำสั่ง
        // }
        //
        //
        // ⚠️ ต้องระวัง
        //
        // อย่าลืมเปลี่ยนค่าตัวแปรที่ใช้ตรวจสอบ
        //
        // ไม่อย่างนั้นอาจเกิด Infinite Loop
        // = Loop ที่ทำงานไม่รู้จบ


        int i = 1;

        while (i <= 5) {

            System.out.println(i);

            i++;
        }

        /*
         * การทำงาน
         *
         * i = 1
         *   ↓
         * ตรวจ i <= 5
         *   ↓
         * true
         *   ↓
         * ทำงาน
         *   ↓
         * i++
         *   ↓
         * กลับไปตรวจใหม่
         *
         *
         * เมื่อ i = 6
         *
         * 6 <= 5
         *     ↓
         *   false
         *
         * Loop จบ
         */


        // ========================================================
        // 3. do-while Loop
        // ========================================================
        // do-while
        // = ทำงานก่อน 1 ครั้ง
        //   แล้วค่อยตรวจสอบเงื่อนไข
        //
        // ต่างจาก while
        //
        // while
        //     -> ตรวจเงื่อนไขก่อน
        //     -> แล้วค่อยทำงาน
        //
        // do-while
        //     -> ทำงานก่อน
        //     -> แล้วค่อยตรวจเงื่อนไข
        //
        //
        // รูปแบบ
        //
        // do {
        //     // คำสั่ง
        // } while (condition);


        int j = 1;

        do {

            System.out.println(j);

            j++;

        } while (j <= 5);


        // ========================================================
        // 4. while vs do-while
        // ========================================================
        /*
         * ตัวอย่างนี้สำคัญมาก
         *
         * int number = 10;
         *
         * while (number < 5) {
         *
         *     System.out.println(number);
         * }
         *
         * ผลลัพธ์:
         *
         * ไม่มีอะไรออกมา
         *
         * เพราะ
         *
         * 10 < 5
         *     ↓
         *   false
         *
         * จึงไม่เข้า Loop เลย
         *
         *
         * แต่ถ้าเป็น do-while
         *
         * int number = 10;
         *
         * do {
         *
         *     System.out.println(number);
         *
         * } while (number < 5);
         *
         * จะพิมพ์ 10 ออกมา 1 ครั้ง
         *
         * เพราะ do-while "ทำก่อนตรวจ"
         */


        // ========================================================
        // 5. Nested Loop
        // ========================================================
        // Nested Loop
        // = การนำ Loop ไปไว้ข้างในอีก Loop หนึ่ง
        //
        // Loop ด้านนอก
        //     ↓
        // ทำงาน 1 รอบ
        //     ↓
        // Loop ด้านในทำงานครบทุกครั้ง
        //
        //
        // ตัวอย่าง
        //
        // Outer Loop 3 รอบ
        // Inner Loop 2 รอบ
        //
        // จำนวนครั้งที่ทำงานทั้งหมด
        //
        // 3 x 2 = 6 ครั้ง


        for (int t = 1; t <= 3; t++) {

            for (int k = 1; k <= 2; k++) {

                System.out.println(t + " " + k);
            }
        }

        /*
         * ผลลัพธ์
         *
         * 1 1
         * 1 2
         * 2 1
         * 2 2
         * 3 1
         * 3 2
         *
         *
         * ให้สังเกตว่า
         *
         * เมื่อ t = 1
         * k จะวิ่ง 1 -> 2
         *
         * เมื่อ t = 2
         * k จะวิ่ง 1 -> 2 ใหม่
         *
         * เมื่อ t = 3
         * k จะวิ่ง 1 -> 2 ใหม่
         */


        // ========================================================
        // 6. break
        // ========================================================
        // break = หยุด Loop ทันที
        //
        // เมื่อโปรแกรมเจอ break จะออกจาก Loop ทันที
        //
        // ไม่สนใจว่าเหลืออีกกี่รอบ
        //
        // ตัวอย่าง
        //
        // Loop 1 ถึง 10
        //
        // แต่ถ้าเจอ 5
        // ให้หยุดทันที


        for (int l = 1; l <= 10; l++) {

            if (l == 5) {

                break;
            }

            System.out.println(l);
        }

        /*
         * การทำงาน
         *
         * l = 1 -> พิมพ์ 1
         * l = 2 -> พิมพ์ 2
         * l = 3 -> พิมพ์ 3
         * l = 4 -> พิมพ์ 4
         * l = 5 -> break
         *
         * Loop จบทันที
         *
         * ดังนั้นผลลัพธ์คือ
         *
         * 1
         * 2
         * 3
         * 4
         *
         * ⚠️ ตรงนี้ในโค้ตเดิมของคุณใช้
         *
         * System.out.println(i);
         *
         * แต่ควรเป็น
         *
         * System.out.println(l);
         *
         * เพราะตัวแปรของ Loop นี้คือ l
         */


        // ========================================================
        // 7. continue
        // ========================================================
        // continue = ข้ามคำสั่งที่เหลือใน "รอบปัจจุบัน"
        //            แล้วไปเริ่มรอบถัดไป
        //
        // ต่างจาก break
        //
        // break
        //     -> ออกจาก Loop
        //
        // continue
        //     -> ข้ามแค่รอบปัจจุบัน
        //        แล้ว Loop ยังทำต่อ
        //
        //
        // ตัวอย่าง
        //
        // ต้องการพิมพ์ 1 ถึง 5
        // แต่ไม่ต้องการพิมพ์ 3


        for (int p = 1; p <= 5; p++) {

            if (p == 3) {

                continue;
            }

            System.out.println(p);
        }

        /*
         * การทำงาน
         *
         * p = 1
         *     ↓
         * ไม่ใช่ 3
         *     ↓
         * พิมพ์ 1
         *
         * p = 2
         *     ↓
         * ไม่ใช่ 3
         *     ↓
         * พิมพ์ 2
         *
         * p = 3
         *     ↓
         * เป็น 3
         *     ↓
         * continue
         *     ↓
         * ข้าม System.out.println(p)
         *
         * p = 4
         *     ↓
         * พิมพ์ 4
         *
         * p = 5
         *     ↓
         * พิมพ์ 5
         *
         *
         * ผลลัพธ์
         *
         * 1
         * 2
         * 4
         * 5
         *
         *
         * ⚠️ ในโค้ตเดิมของคุณเขียน
         *
         * if (i == 3)
         *
         * System.out.println(i);
         *
         * ซึ่งผิดตัวแปร
         *
         * ต้องใช้ p
         *
         * if (p == 3)
         *
         * System.out.println(p);
         */


        // ========================================================
        // 8. Loop แบบนับถอยหลัง
        // ========================================================
        // Loop ไม่จำเป็นต้องเพิ่มค่าอย่างเดียว
        //
        // สามารถลดค่าได้เช่นกัน
        //
        // i--
        // = ลดค่าทีละ 1


        for (int n = 5; n >= 1; n--) {

            System.out.println(n);
        }


        // ========================================================
        // 9. Loop เพิ่มทีละ 2
        // ========================================================
        // เราสามารถกำหนดการเปลี่ยนแปลงของตัวแปรเองได้
        //
        // i += 2
        // = เพิ่มทีละ 2


        for (int n = 1; n <= 10; n += 2) {

            System.out.println(n);
        }

        /*
         * ผลลัพธ์
         *
         * 1
         * 3
         * 5
         * 7
         * 9
         */


        // ========================================================
        // 10. Infinite Loop
        // ========================================================
        /*
         * Infinite Loop = Loop ที่ไม่มีวันจบ
         *
         * ตัวอย่าง
         *
         * while (true) {
         *
         *     System.out.println("Hello");
         * }
         *
         * เพราะ true เป็นจริงตลอดเวลา
         *
         * Loop จึงไม่หยุด
         *
         *
         * แต่เราสามารถใช้ break
         * เพื่อหยุด Infinite Loop ได้
         *
         * เช่น
         *
         * while (true) {
         *
         *     if (condition) {
         *         break;
         *     }
         * }
         */


        // ========================================================
        // Summary
        // ========================================================
        /*
         * ========================================================
         * สรุป Loop
         * ========================================================
         *
         * Loop = ทำคำสั่งเดิมซ้ำ ๆ
         *
         *
         * for = เหมาะเมื่อรู้จำนวนรอบ
         *
         *
         * while = ตรวจเงื่อนไขก่อนทำงาน
         *
         *
         * do-while = ทำงานก่อน 1 ครั้ง แล้วค่อยตรวจเงื่อนไข
         *
         *
         * Nested Loop = Loop ซ้อน Loop
         *
         *
         * break = ออกจาก Loop ทันที
         *
         *
         * continue = ข้ามรอบปัจจุบันแล้วไปต่อรอบถัดไป
         *
         *
         * ========================================================
         * สิ่งที่ต้องระวัง
         * ========================================================
         *
         * 1. อย่าลืมเปลี่ยนค่าตัวแปรใน while
         *
         *    ไม่อย่างนั้นอาจเกิด Infinite Loop
         *
         *
         * 2. ตรวจสอบตัวแปรของ Loop ให้ถูกต้อง
         *
         *    for (int i = ...)
         *
         *    ต้องใช้ i
         *
         *
         * 3. break กับ continue ไม่เหมือนกัน
         *
         *    break -> จบ Loop
         *
         *    continue -> ข้ามแค่รอบนี้
         *
         * ========================================================
         */
    }
}

