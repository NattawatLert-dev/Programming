package a01basic;

import java.util.Timer;
import java.util.TimerTask;

public class B15Timertasks {

    public static void main(String[] args) {

        // ========================================================
        // Timer และ TimerTask
        // ========================================================
        // Timer = คลาสที่ใช้สำหรับ "กำหนดเวลา" ว่างาน (Task) จะถูกเรียกให้ทำงานเมื่อไหร่
        //
        // TimerTask = คลาสที่ใช้แทน "งานที่ต้องการให้ทำ"
        //
        //
        // จำง่าย ๆ
        //
        // Timer = คนตั้งเวลา
        //
        // TimerTask = งานที่ต้องทำ
        //
        //
        // ตัวอย่างการใช้งาน
        //
        // - Countdown
        // - Notification
        // - Scheduled Update
        // - ทำงานซ้ำทุก ๆ ช่วงเวลา
        // - งานที่ต้องทำหลังจากรอเวลาที่กำหนด
        //
        //
        // หน่วยเวลาใน Timer
        //
        // ใช้ "มิลลิวินาที (milliseconds)"
        //
        // 1 วินาที = 1000 milliseconds
        //
        // 2 วินาที = 2000 milliseconds
        //
        // 0.5 วินาที = 500 milliseconds


        // ========================================================
        // 1. สร้าง Timer
        // ========================================================
        // Timer จะเป็นตัวควบคุมเวลา
        //
        // เมื่อสร้างแล้ว
        // เราสามารถสั่งให้ Timer
        // เรียก TimerTask ตามเวลาที่กำหนดได้


        Timer timer = new Timer();


        // ========================================================
        // 2. สร้าง TimerTask
        // ========================================================
        // TimerTask เป็น Class ที่มี Method
        //
        // run()
        //
        // เราต้อง Override run()
        // เพื่อบอกว่า
        //
        // "เมื่อถึงเวลา ให้ทำอะไร"
        //
        //
        // ในตัวอย่างนี้
        // เราสร้าง TimerTask แบบ Anonymous Class
        //
        //
        // Anonymous Class = Class ที่ไม่มีชื่อ
        //
        // เราสร้างขึ้นมาใช้งานทันที
        //
        //
        // รูปแบบ
        //
        // TimerTask task = new TimerTask() {
        //
        //     @Override
        //     public void run() {
        //
        //         // งานที่ต้องการให้ทำ
        //
        //     }
        // };


        TimerTask task = new TimerTask() {

            // ====================================================
            // ตัวแปร count
            // ====================================================
            // ใช้สำหรับนับถอยหลัง
            //
            // เริ่มต้นที่ 3


            int count = 3;


            // ====================================================
            // run()
            // ====================================================
            // run() คือ Method ที่ Timer
            // จะเรียกให้ทำงานตามเวลาที่เรากำหนด
            //
            //
            // @Override
            // หมายถึง
            // เรากำลังเขียนทับ Method run()
            // ที่มาจาก TimerTask


            @Override
            public void run() {

                // แสดงค่าปัจจุบันของ count

                System.out.println(count);


                // ลดค่า count ลง 1

                count--;


                // =================================================
                // ตรวจสอบว่าการนับเสร็จหรือยัง
                // =================================================
                // ถ้า count <= 0
                //
                // แสดง
                //
                // Task complete
                //
                // แล้วหยุด Timer


                if (count <= 0) {

                    System.out.println("Task complete");


                    // =================================================
                    // cancel()
                    // =================================================
                    // cancel() = ยกเลิก Timer
                    //
                    // เมื่อเรียก timer.cancel() Timer จะหยุดการทำงาน
                    //
                    // ดังนั้น Task จะไม่ถูกเรียกต่อ


                    timer.cancel();
                }
            }
        };


        // ========================================================
        // 3. schedule()
        // ========================================================
        // schedule(task, delay, period)
        //
        //
        // task = งานที่ต้องการให้ Timer เรียก
        //
        //
        // delay = รอกี่ milliseconds ก่อนเริ่มทำงานครั้งแรก
        //
        //
        // period = ให้ทำงานซ้ำทุกกี่ milliseconds
        //
        //
        // ในตัวอย่างนี้
        //
        // delay = 0
        // period = 1000
        //
        //
        // หมายความว่า
        //
        // เริ่มทำงานทันที
        //
        // แล้วทำซ้ำทุก 1 วินาที


        timer.schedule(task, 0, 1000);


        // ========================================================
        // ผลลัพธ์
        // ========================================================
        //
        // 3
        // 2
        // 1
        // Task complete
        //
        //
        // แต่ละบรรทัดจะห่างกันประมาณ 1 วินาที
        //
        //
        // ทำไมถึงหยุด?
        //
        // เพราะเมื่อ count ลดจาก 1
        //
        // count--
        //
        // จะกลายเป็น 0
        //
        // จากนั้น
        //
        // if (count <= 0)
        //
        // เป็นจริง
        //
        // แล้วเรียก
        //
        // timer.cancel();
        //
        // Timer จึงหยุดทำงาน

        // scheduleAtFixedRate() = ทำงานตามอัตราคงที่ที่กำหนด

    }
}
