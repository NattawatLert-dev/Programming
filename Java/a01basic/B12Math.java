package a01basic;

public class B12Math {

    public static void main(String[] args) {

        // ========================================================
        // Math
        // ========================================================
        // Math = Class ที่ Java เตรียมไว้ให้ สำหรับคำนวณทางคณิตศาสตร์
        //
        // ข้อดี
        //
        // เราสามารถเรียกใช้ Method ของ Math ได้เลย ไม่จำเป็นต้องสร้าง Object
        //
        //
        // ตัวอย่าง
        //
        // Math.abs(-10)
        // Math.max(5, 8)
        // Math.sqrt(64)
        //
        //
        // รูปแบบ
        //
        // Math.ชื่อMethod(ข้อมูล)
        //
        // Math เป็น Class ที่อยู่ใน java.lang ดังนั้นไม่ต้อง import


        // ========================================================
        // 1. Math.PI
        // ========================================================
        // PI (π)
        //
        // ค่าประมาณ
        //
        // 3.141592653589793
        //
        // มักใช้เกี่ยวกับวงกลม
        //
        // เช่น
        //
        // เส้นรอบวง = 2πr
        //
        // พื้นที่วงกลม = πr²


        System.out.println("PI = " + Math.PI);


        // ========================================================
        // 2. Math.E
        // ========================================================
        // E = ค่าคงที่ทางคณิตศาสตร์
        //
        // ประมาณ
        //
        // 2.718281828459045
        //
        // พบได้บ่อยในการคำนวณ Exponential และ Logarithm


        System.out.println("E = " + Math.E);


        // ========================================================
        // 3. Math.abs()
        // ========================================================
        // abs = Absolute Value 
        //     = ค่าสัมบูรณ์
        //
        //
        // หลักการ
        //
        // -10 -> 10
        //  10 -> 10
        //  -5 -> 5
        //
        // พูดง่าย ๆ
        //
        // "เอาเครื่องหมายลบออก"

        System.out.println("abs(-10) = " + Math.abs(-10)); // 10

        System.out.println("abs(10) = " + Math.abs(10)); // 10


        // ========================================================
        // 4. Math.max()
        // ========================================================
        // max = Maximum
        //     = หาค่าที่มากกว่า
        //
        // Math.max(a, b)
        //
        // จะคืนค่าที่มีค่ามากกว่า


        System.out.println("max(5, 8) = " + Math.max(5, 8)); // 8


        // ========================================================
        // 5. Math.min()
        // ========================================================
        // min = Minimum
        //     = หาค่าที่น้อยกว่า
        //
        //
        // Math.min(a, b)
        //
        // จะคืนค่าที่มีค่าน้อยกว่า


        System.out.println("min(5, 8) = " + Math.min(5, 8)); // 5


        // ========================================================
        // 6. Math.pow()
        // ========================================================
        // pow = Power
        //     = ยกกำลัง
        //
        //
        // Math.pow(base, exponent)
        //
        //
        // ตัวอย่าง
        //
        // Math.pow(2, 3)
        //
        // = 2³
        // = 2 x 2 x 2
        // = 8
        //
        //
        // ⚠️ ผลลัพธ์ของ Math.pow() เป็น double


        System.out.println("2^3 = " + Math.pow(2, 3)); // 8.0


        // ถ้าต้องการ int
        // สามารถ Cast ได้

        int power = (int) Math.pow(2, 3);

        System.out.println("2^3 as int = " + power); // 8


        // ========================================================
        // 7. Math.sqrt()
        // ========================================================
        // sqrt = Square Root
        //      = รากที่สอง
        //
        // √64 = 8


        System.out.println("sqrt(64) = " + Math.sqrt(64)); // 8.0


        // ========================================================
        // 8. Math.round()
        // ========================================================
        // round = ปัดเศษตามหลักการปัดเศษ
        //
        //
        // 4.4 -> 4
        // 4.5 -> 5
        // 4.6 -> 5
        //
        //
        // ตัวอย่าง


        System.out.println("round(4.4) = " + Math.round(4.4)); // 4


        System.out.println("round(4.6) = " + Math.round(4.6)); // 5


        System.out.println("round(4.5) = " + Math.round(4.5)); // 5


        // ========================================================
        // 9. Math.ceil()
        // ========================================================
        // ceil = Ceiling
        //      = ปัดขึ้น
        //
        //
        // ถ้ามีเศษ จะไปยังจำนวนเต็มที่มากกว่า
        //
        //
        // 4.1 -> 5
        // 4.9 -> 5
        //
        //
        // ⚠️ ceil ไม่ได้หมายความว่า "ตัดทศนิยมแล้วบวก 1"
        //
        // แต่มันคือ "หาจำนวนเต็มที่มากกว่าหรือเท่ากับค่าปัจจุบัน"


        System.out.println("ceil(4.1) = " + Math.ceil(4.1)); // 5.0


        System.out.println("ceil(4.9) = " + Math.ceil(4.9)); // 5.0


        // ========================================================
        // 10. Math.floor()
        // ========================================================
        // floor = ปัดลง
        //
        //
        // 4.1 -> 4
        // 4.9 -> 4
        //
        //
        // คือเลือกจำนวนเต็ม
        // ที่น้อยกว่าหรือเท่ากับค่าปัจจุบัน


        System.out.println("floor(4.1) = " + Math.floor(4.1)); // 4.0


        System.out.println("floor(4.9) = " + Math.floor(4.9)); // 4.0


        // ========================================================
        // 11. round vs ceil vs floor
        // ========================================================
        /*
         * ========================================================
         *
         * round = ปัดตามหลักการปัดเศษ
         *
         *
         * ceil = ปัดขึ้น
         *
         *
         * floor = ปัดลง
         *
         * ========================================================
         *
         * ตัวอย่าง 4.6
         *
         * round(4.6) = 5
         * ceil(4.6)  = 5
         * floor(4.6) = 4
         *
         *
         * ตัวอย่าง 4.2
         *
         * round(4.2) = 4
         * ceil(4.2)  = 5
         * floor(4.2) = 4
         *
         * ========================================================
         */


        // ========================================================
        // 12. Trigonometry
        // ========================================================
        // Math มี Method สำหรับตรีโกณมิติ
        //
        // เช่น
        //
        // Math.sin()
        // Math.cos()
        // Math.tan()
        //
        //
        // ⚠️ สำคัญมาก
        //
        // Math.sin()
        // Math.cos()
        // Math.tan()
        //
        // รับค่าเป็น "เรเดียน"
        //
        // ไม่ใช่องศา


        System.out.println(
                "sin(π/2) = " + Math.sin(Math.PI / 2)
        );

        // ได้ประมาณ 1.0


        System.out.println(
                "cos(0) = " + Math.cos(0)
        );

        // 1.0


        System.out.println(
                "tan(π/4) = " + Math.tan(Math.PI / 4)
        );

        // ประมาณ 1.0


        // ========================================================
        // 13. องศา -> เรเดียน
        // ========================================================
        // Math.toRadians()
        //
        // ใช้แปลง
        //
        // Degree
        //     ↓
        // Radian
        //
        //
        // ตัวอย่าง
        //
        // 180° = π radians
        // 90°  = π/2 radians


        double r = Math.toRadians(180);

        System.out.println("180 degrees = " + r + " radians");


        // ========================================================
        // 14. เรเดียน -> องศา
        // ========================================================
        // Math.toDegrees()
        //
        // ใช้แปลง
        //
        // Radian
        //     ↓
        // Degree


        double d = Math.toDegrees(Math.PI);

        System.out.println("π radians = " + d + " degrees");
        // 180.0


        // ========================================================
        // 15. Logarithm
        // ========================================================
        // Math.log() = Natural Logarithm
        //            = ln
        //
        //
        // ln(e) = 1
        //
        // ดังนั้น
        //
        // Math.log(Math.E)
        //
        // จะได้ประมาณ 1


        System.out.println(
                "ln(e) = " + Math.log(Math.E)
        );
        // 1.0


        // ========================================================
        // 16. Math.log10()
        // ========================================================
        // log10() = Logarithm ฐาน 10
        //
        //
        // log10(100) = 2
        //
        // เพราะ
        //
        // 10² = 100


        System.out.println(
                "log10(100) = " + Math.log10(100)
        );
        // 2.0


        // ========================================================
        // 17. Math.exp()
        // ========================================================
        // exp(x) = e ยกกำลัง x
        //
        //
        // Math.exp(1)
        //
        // = e¹
        // = e
        // ≈ 2.71828


        System.out.println(
                "exp(1) = " + Math.exp(1)
        );


        // ========================================================
        // 18. Math.random()
        // ========================================================
        // random() = สุ่มเลขทศนิยม
        //
        // ค่าที่ได้จะอยู่ในช่วง
        //
        // 0.0 <= random < 1.0
        //
        //
        // เช่น
        //
        // 0.123
        // 0.567
        // 0.891
        //
        // ทุกครั้งที่ Run
        // มีโอกาสได้ค่าต่างกัน


        double random = Math.random();

        System.out.println("Random = " + random);


        // ========================================================
        // 19. สุ่มเลขจำนวนเต็ม
        // ========================================================
        // Math.random() คืนค่าเป็น double
        //
        // ถ้าต้องการสุ่มเลขจำนวนเต็ม
        // ต้องนำมาคูณและ Cast
        //
        //
        // ตัวอย่าง
        //
        // ต้องการเลข 1 ถึง 10
        //
        // (int)(Math.random() * 10) + 1
        //
        //
        // Math.random() -> 0.0 ถึงน้อยกว่า 1.0
        //
        // * 10 -> 0.0 ถึงน้อยกว่า 10.0
        //
        // (int) -> 0 ถึง 9
        //
        // + 1 -> 1 ถึง 10


        int randomNumber = (int) (Math.random() * 10) + 1;

        System.out.println("Random 1-10 = " + randomNumber);


        // ========================================================
        // 20. ตัวอย่างการคำนวณพื้นที่วงกลม
        // ========================================================
        // สูตร
        //
        // Area = πr²
        //
        // สมมติ r = 5


        double radius = 5;

        double area = Math.PI * Math.pow(radius, 2);

        System.out.println("Circle Area = " + area);


        // ========================================================
        // 21. ตัวอย่างหาระยะห่าง
        // ========================================================
        // สมมติจุด 2 จุด
        //
        // จุด A = (x1, y1)
        // จุด B = (x2, y2)
        //
        //
        // สูตรระยะห่าง
        //
        // √((x2-x1)² + (y2-y1)²)


        double x1 = 0;
        double y1 = 0;

        double x2 = 3;
        double y2 = 4;

        double distance = Math.sqrt(
                Math.pow(x2 - x1, 2)
                +
                Math.pow(y2 - y1, 2)
        );

        System.out.println("Distance = " + distance);

        /*
         * ผลลัพธ์
         *
         * Distance = 5.0
         *
         * เพราะ
         *
         * √(3² + 4²)
         *
         * = √(9 + 16)
         *
         * = √25
         *
         * = 5
         */


        // ========================================================
        // 22. ตัวอย่างเปรียบเทียบคะแนน
        // ========================================================
        // Math.max()
        // สามารถนำไปใช้กับโปรแกรมจริงได้
        //
        // เช่น
        // หาคะแนนที่มากกว่า


        int score1 = 75;
        int score2 = 92;

        int highestScore = Math.max(score1, score2);

        System.out.println(
                "Highest Score = " + highestScore
        );


        // ========================================================
        // 23. ตัวอย่างหาค่าต่ำสุด
        // ========================================================

        int temperature1 = 30;
        int temperature2 = 25;

        int lowestTemperature =
                Math.min(temperature1, temperature2);

        System.out.println(
                "Lowest Temperature = "
                + lowestTemperature
        );


        // ========================================================
        // Summary
        // ========================================================
        /*
         * ========================================================
         * สรุป Math Methods ที่ควรรู้
         * ========================================================
         *
         *
         * Math.PI
         *     = ค่า π
         *
         *
         * Math.E
         *     = ค่าคงที่ e
         *
         *
         * Math.abs(x)
         *     = ค่าสัมบูรณ์
         *
         *
         * Math.max(a, b)
         *     = ค่าที่มากกว่า
         *
         *
         * Math.min(a, b)
         *     = ค่าที่น้อยกว่า
         *
         *
         * Math.pow(a, b)
         *     = a ยกกำลัง b
         *
         *
         * Math.sqrt(x)
         *     = รากที่สอง
         *
         *
         * Math.round(x)
         *     = ปัดเศษ
         *
         *
         * Math.ceil(x)
         *     = ปัดขึ้น
         *
         *
         * Math.floor(x)
         *     = ปัดลง
         *
         *
         * Math.sin(x)
         *     = sine
         *
         *
         * Math.cos(x)
         *     = cosine
         *
         *
         * Math.tan(x)
         *     = tangent
         *
         *
         * Math.toRadians(x)
         *     = องศา -> เรเดียน
         *
         *
         * Math.toDegrees(x)
         *     = เรเดียน -> องศา
         *
         *
         * Math.log(x)
         *     = Natural Logarithm (ln)
         *
         *
         * Math.log10(x)
         *     = Logarithm ฐาน 10
         *
         *
         * Math.exp(x)
         *     = e^x
         *
         *
         * Math.random()
         *     = สุ่มเลข 0.0 ถึงน้อยกว่า 1.0
         *
         *
         * ========================================================
         * เรื่องที่ต้องจำเป็นพิเศษ
         * ========================================================
         *
         * 1. Math ไม่ต้องสร้าง Object
         *
         *    Math.max(5, 10);
         *
         *
         * 2. sin / cos / tan ใช้ "เรเดียน"
         *
         *    Math.sin(Math.PI / 2)
         *
         *
         * 3. Math.pow() และ Math.sqrt()
         *    คืนค่าเป็น double
         *
         *
         * 4. Math.random()
         *    ได้ค่าเป็น double
         *    ตั้งแต่ 0.0 ถึงน้อยกว่า 1.0
         *
         *
         * 5. การปัดเศษ
         *
         *    round -> ปัดตามหลัก
         *    ceil  -> ปัดขึ้น
         *    floor -> ปัดลง
         *
         *
         * ========================================================
         *
         * จำง่าย ๆ
         *
         * abs   = เอาค่าสัมบูรณ์
         * max   = เอาค่ามาก
         * min   = เอาค่าน้อย
         * pow   = ยกกำลัง
         * sqrt  = รากที่สอง
         * round = ปัด
         * ceil  = ขึ้น
         * floor = ลง
         * random = สุ่ม
         *
         * ========================================================
         */
    }
}