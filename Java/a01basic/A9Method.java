package a01basic;

public class A9Method {

    public static void main(String[] args) {

        // ========================================================
        // Method
        // ========================================================
        // Method = กลุ่มของคำสั่งที่รวมกันเพื่อทำงานอย่างใดอย่างหนึ่ง
        //
        // เปรียบเทียบง่าย ๆ
        // Method เหมือน "เครื่องจักร"
        //
        // เราสามารถ
        // 1. เรียกใช้ Method
        // 2. ส่งข้อมูลเข้าไปให้ Method
        // 3. ให้ Method ทำงาน
        // 4. รับค่าที่ Method ส่งกลับมา
        //
        // ข้อดีของ Method
        //
        // - ลดการเขียน Code ซ้ำ
        // - แบ่งโปรแกรมออกเป็นส่วน ๆ
        // - ทำให้ Code อ่านง่าย
        // - แก้ไข Code ได้ง่าย
        // - สามารถนำ Method กลับมาใช้ซ้ำได้


        // ========================================================
        // 1. Method แบบไม่มี Parameter และไม่มี Return
        // ========================================================
        // Parameter = ข้อมูลที่ Method รับเข้ามา
        //
        // Return = ค่าที่ Method ส่งกลับออกมา
        //
        //
        // Method นี้
        //
        // hello()
        //
        // ไม่มี Parameter
        // ไม่มี Return
        //
        // จึงเป็น
        //
        // public static void hello()
        //
        // void = Method นี้ไม่มีค่าที่ส่งกลับ


        hello();

        /*
         * ผลลัพธ์
         *
         * Hello World
         */


        // ========================================================
        // 2. Method ที่มี Parameter
        // ========================================================
            // Parameter = ตัวแปรที่ประกาศไว้ใน Method เพื่อรับข้อมูลที่ส่งเข้ามา
        //
        // Argument = "ค่าจริง" ที่ส่งเข้าไปตอนเรียก Method
        //
        //
        // ตัวอย่าง
        //
        // user("Nattawat", 21);
        //
        //  "Nattawat"
        //      ↓
        //   Argument
        //
        //     21
        //      ↓
        //   Argument
        //
        //
        // ส่วนใน Method
        //
        // user(String name, int age)
        //
        // name = Parameter
        // age = Parameter


        user("Nattawat", 21);

        /*
         * ผลลัพธ์
         *
         * Hello Nattawat 21
         */


        // ========================================================
        // 3. Method ที่มี Return Type
        // ========================================================
        // Return Type = ชนิดข้อมูลที่ Method จะส่งกลับ
        //
        //
        // ตัวอย่าง
        //
        // public static int sum(int a, int b)
        //
        // int
        //     ↑
        //     Return Type
        //
        //
        // Method นี้ต้องส่งค่า int กลับมา
        //
        //
        // return = คำสั่งที่ใช้ส่งค่ากลับจาก Method
        //
        //
        // return a + b;
        //
        // หมายถึง
        //
        // คำนวณ a + b
        // แล้วส่งผลลัพธ์กลับไปยังจุดที่เรียก Method


        System.out.println(sum(10, 3));

        /*
         * การทำงาน
         *
         * sum(10, 3)
         *      ↓
         * a = 10
         * b = 3
         *      ↓
         * a + b
         *      ↓
         * 13
         *      ↓
         * return 13
         *
         * ผลลัพธ์
         *
         * 13
         */


        // สามารถเก็บค่าที่ Method return ได้

        int sumResult = sum(20, 30);

        System.out.println("Sum = " + sumResult);

        /*
         * ผลลัพธ์
         *
         * Sum = 50
         */


        // ========================================================
        // 4. Recursion
        // ========================================================
        // Recursion = Method เรียกตัวเอง
        //
        //
        // Recursion ต้องมี 2 ส่วนสำคัญ
        //
        // 1. Base Case
        // 2. Recursive Case
        //
        //
        // Base Case = เงื่อนไขที่ใช้หยุด Recursion
        //
        // Recursive Case = ส่วนที่ Method เรียกตัวเองโดยต้องทำให้ปัญหาเล็กลง
        //
        //
        // ⚠️ ถ้าไม่มี Base Case
        //    Method จะเรียกตัวเองไปเรื่อย ๆ
        //    และอาจเกิด StackOverflowError


        int result = factorial(5);

        System.out.println("5! = " + result);

        /*
         * Factorial
         *
         * 5!
         *
         * = 5 x 4 x 3 x 2 x 1
         * = 120
         *
         *
         * การทำงานของ Recursion
         *
         * factorial(5)
         *      ↓
         * 5 * factorial(4)
         *      ↓
         * 4 * factorial(3)
         *      ↓
         * 3 * factorial(2)
         *      ↓
         * 2 * factorial(1)
         *      ↓
         * factorial(1) = 1
         *
         * จากนั้นค่อยย้อนกลับ
         *
         * 2 x 1 = 2
         * 3 x 2 = 6
         * 4 x 6 = 24
         * 5 x 24 = 120
         *
         * ดังนั้น
         *
         * 5! = 120
         */


        // ========================================================
        // 5. Method ที่มี Parameter และ Return Type
        // ========================================================
        // Method สามารถ
        //
        // - รับข้อมูลเข้ามา
        // - ประมวลผล
        // - ส่งข้อมูลกลับ
        //
        // ได้พร้อมกัน
        //
        //
        // linearSearch() = การค้นหาแบบ Linear Search
        //
        // หลักการ
        //
        // ตรวจข้อมูลทีละตัว ตั้งแต่ตัวแรกไปจนถึงตัวสุดท้าย
        //
        //
        // Array
        //
        // {10, 20, 30, 40}
        //
        // Index
        //   0   1   2   3
        //
        // ถ้าหา 30
        //
        // 10 == 30 ❌
        // 20 == 30 ❌
        // 30 == 30 ✅
        //
        // return index
        //
        // = 2


        int[] arr = {10, 20, 30, 40};

        System.out.println(linearSearch(arr, 30));

        /*
         * ผลลัพธ์
         *
         * 2
         *
         * เพราะ 30 อยู่ที่ Index 2
         */


        // ========================================================
        // 6. Method สามารถเรียกได้หลายครั้ง
        // ========================================================
        // ข้อดีสำคัญของ Method คือ
        // เราเขียนครั้งเดียว
        // แล้วเรียกใช้กี่ครั้งก็ได้


        hello();
        hello();
        hello();

        /*
         * ผลลัพธ์
         *
         * Hello World
         * Hello World
         * Hello World
         */


        // ========================================================
        // 7. Method สามารถรับ Parameter หลายตัว
        // ========================================================
        // Method สามารถรับ Parameter ได้มากกว่า 1 ตัว
        //
        // ตัวอย่าง
        //
        // user(String name, int age)
        // มี 2 Parameter
        //
        // name
        // age


        user("Alice", 20);
        user("Bob", 25);


        // ========================================================
        // 8. void
        // ========================================================
        // void = Method ไม่มีค่าที่ส่งกลับ
        //
        //
        // ตัวอย่าง
        //
        // public static void hello()
        //
        // Method ทำงาน
        // แต่ไม่ได้ส่งค่ากลับ
        //
        //
        // เราจึงไม่สามารถเขียนแบบนี้ได้
        //
        // int x = hello();
        //
        // เพราะ hello() ไม่มีค่ากลับมา


        // ========================================================
        // 9. return
        // ========================================================
        // return มีหน้าที่ 2 อย่าง
        //
        // 1. ส่งค่ากลับ
        // 2. จบการทำงานของ Method ทันที
        //
        //
        // ตัวอย่าง
        //
        // if (arr[i] == target) {
        //     return i;
        // }
        //
        // เมื่อเจอ target
        // return จะส่ง index กลับทันที
        //
        // และ Method จะจบทันที
        //
        // จึงไม่ต้องค้นหาต่อ


        // ========================================================
        // 10. Method ที่ Return หลายแบบ
        // ========================================================
        // Return Type ไม่จำเป็นต้องเป็น int
        //
        // สามารถเป็น
        //
        // String
        // double
        // boolean
        // char
        // int
        // ฯลฯ
        //
        //
        // ตัวอย่าง


        System.out.println(getName());
        System.out.println(isAdult(20));


        // ========================================================
        // 11. Scope ของ Parameter
        // ========================================================
        // Parameter จะสามารถใช้งานได้เฉพาะภายใน Method นั้น
        //
        //
        // เช่น
        //
        // public static void user(String name, int age)
        //
        // name และ age
        // เป็น Local Variable ของ Method user()
        //
        // Method อื่นไม่สามารถใช้ name ของ user() โดยตรงได้
        //
        //
        // เหมือนกับเรื่อง Local Variable
        // ที่เรียนมาก่อนหน้านี้


        // ========================================================
        // 12. Array เป็น Parameter
        // ========================================================
        // เราสามารถส่ง Array เข้า Method ได้
        //
        // เช่น
        //
        // linearSearch(arr, 30)
        //
        // arr = Argument
        //
        // int[] arr = Parameter


        int[] numbers = {5, 10, 15, 20};

        int index = linearSearch(numbers, 15);

        System.out.println("Index = " + index);


        // ========================================================
        // 13. ถ้าหาข้อมูลไม่เจอ
        // ========================================================
        // linearSearch() จะ return -1 เมื่อไม่พบข้อมูล
        //
        // เพราะ Index ที่ถูกต้องของ Array
        // จะเริ่มจาก 0
        //
        // ดังนั้น -1 จึงสามารถใช้แทน
        // "ไม่พบข้อมูล"
        //
        //
        // ตัวอย่าง


        int notFound = linearSearch(numbers, 100);

        System.out.println("Search 100 = " + notFound);

        /*
         * ผลลัพธ์
         *
         * Search 100 = -1
         */


        // ========================================================
        // 14. Method Overloading
        // ========================================================
        // Method Overloading = การมี Method ชื่อเดียวกัน แต่ Parameter แตกต่างกัน
        //
        // เช่น
        //
        // add(int, int)
        //
        // add(double, double)
        //
        //
        // Java จะเลือก Method
        // ตามชนิดและจำนวน Argument


        System.out.println(add(10, 20));

        System.out.println(add(10.5, 20.5));


        // ========================================================
        // 15. Local Variable ใน Method
        // ========================================================
        // Variable ที่ประกาศภายใน Method เป็น Local Variable
        //
        // สามารถใช้งานได้เฉพาะ Method นั้น
        //
        // เช่น
        //
        // int result = ...
        //
        // ตัวแปร result ใน main()
        // เป็นของ main()
        //
        // ไม่เกี่ยวกับตัวแปร result
        //
        // ใน Method อื่น

        /*
         * ========================================================
         * สรุป Method
         * ========================================================
         *
         * Method = กลุ่มคำสั่งที่รวมกันเพื่อทำงานบางอย่าง
         *
         *
         * void = ไม่มีค่าที่ส่งกลับ
         *
         *
         * Parameter = ตัวแปรที่ Method รับเข้ามา
         *
         *
         * Argument = ค่าจริงที่ส่งเข้า Method
         *
         *
         * Return Type = ชนิดข้อมูลที่ Method ส่งกลับ
         *
         *
         * return = ส่งค่ากลับ + จบ Method
         *
         *
         * Recursion = Method เรียกตัวเอง
         *
         *
         * Base Case = เงื่อนไขหยุด Recursion
         *
         *
         * Recursive Case = ส่วนที่เรียกตัวเอง
         *
         *
         * Method Overloading = Method ชื่อเดียวกันแต่ Parameter แตกต่างกัน
         *
         *
         * ========================================================
         * จำง่าย ๆ
         * ========================================================
         *
         * Method
         *
         *       Argument
         *           ↓
         *       ┌─────────┐
         *       │ Method  │
         *       │         │
         *       │ Process │
         *       └─────────┘
         *           ↓
         *        return
         *
         *
         * ========================================================
         * ตัวอย่าง
         * ========================================================
         *
         * sum(10, 3)
         *
         * 10, 3
         *   = Argument
         *
         * a, b
         *   = Parameter
         *
         * int
         *   = Return Type
         *
         * return a + b
         *   = ส่งค่ากลับ
         *
         *
         * ========================================================
         */
    }


    // ============================================================
    // 1. Method ไม่มี Parameter และไม่มี Return
    // ============================================================

    public static void hello() {

        System.out.println("Hello World");
    }


    // ============================================================
    // 2. Method มี Parameter
    // ============================================================

    public static void user(String name, int age) {

        System.out.println("Hello " + name + " " + age);
    }


    // ============================================================
    // 3. Method มี Return Type
    // ============================================================

    public static int sum(int a, int b) {

        return a + b;
    }


    // ============================================================
    // 4. Recursion
    // ============================================================

    public static int factorial(int n) {

        // --------------------------------------------------------
        // Base Case
        // --------------------------------------------------------
        // ถ้า n = 1
        // ให้หยุด Recursion
        //
        // เพราะถ้าไม่มีจุดหยุด
        // Method จะเรียกตัวเองไม่รู้จบ


        if (n == 1) {

            return 1;
        }


        // --------------------------------------------------------
        // Recursive Case
        // --------------------------------------------------------
        // เรียก factorial() ตัวเอง
        // โดยลด n ลงทีละ 1
        //
        // factorial(5)
        // factorial(4)
        // factorial(3)
        // factorial(2)
        // factorial(1)
        //
        // เมื่อถึง factorial(1)
        // จะหยุด


        return n * factorial(n - 1);
    }


    // ============================================================
    // 5. Linear Search
    // ============================================================
    // Parameter
    //
    // int[] arr
    //     = Array ที่ต้องการค้นหา
    //
    // int target
    //     = ค่าที่ต้องการค้นหา


    public static int linearSearch(int[] arr, int target) {

        // วนดู Array ตั้งแต่ Index 0
        // ไปจนถึง Index สุดท้าย

        for (int i = 0; i < arr.length; i++) {

            // ตรวจว่าค่าปัจจุบัน
            // เท่ากับค่าที่เราต้องการหรือไม่

            if (arr[i] == target) {

                // ถ้าเจอ
                // ส่ง Index กลับทันที

                return i;
            }
        }


        // ถ้าวนจนจบแล้วยังไม่เจอ
        //
        // return -1
        //
        // หมายถึง "ไม่พบข้อมูล"

        return -1;
    }


    // ============================================================
    // 6. Method Return String
    // ============================================================

    public static String getName() {

        return "Nattawat";
    }


    // ============================================================
    // 7. Method Return boolean
    // ============================================================

    public static boolean isAdult(int age) {

        return age >= 18;
    }


    // ============================================================
    // 8. Method Overloading
    // ============================================================
    // ชื่อ Method เหมือนกัน
    // แต่ Parameter แตกต่างกัน
    //
    // add(int, int)
    // add(double, double)


    public static int add(int a, int b) {

        return a + b;
    }


    public static double add(double a, double b) {

        return a + b;
    }
}
