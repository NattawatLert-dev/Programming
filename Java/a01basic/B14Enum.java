package a01basic;

// ================================================================
// ENUM
// ================================================================
// enum = Enumeration
//
// เป็นชนิดข้อมูล (Data Type) ที่ใช้กำหนด
// "ค่าที่สามารถเลือกได้แบบจำกัด"
//
// ตัวอย่างเช่น
//
// สีมีแค่
//
// RED
// GREEN
// BLUE
//
// แทนที่จะใช้ String:
//
// String color = "RED";
//
// เราสามารถสร้าง enum:
//
// Color color = Color.RED;
//
// ข้อดีคือ
//
// - ป้องกันการพิมพ์ค่าที่ไม่ถูกต้อง
// - อ่านโค้ดง่าย
// - กำหนดค่าที่อนุญาตได้ชัดเจน
// - สามารถมี Attribute และ Method ของตัวเองได้
//


// ================================================================
// สร้าง Enum ชื่อ Color
// ================================================================

enum Color {

    // ============================================================
    // สมาชิก (Enum Constants)
    // ============================================================
    // เรากำหนดสมาชิกที่สามารถใช้ได้
    //
    // RED
    // GREEN
    // BLUE
    //
    // นอกจากนี้เรายังส่งค่า String
    // เข้าไปใน Constructor ด้วย
    //
    //
    // RED("#FF0000")
    //     ↓
    // ส่ง "#FF0000" เข้า Constructor
    //
    //
    // GREEN("#00FF00")
    //     ↓
    // ส่ง "#00FF00" เข้า Constructor
    //
    //
    // BLUE("#0000FF")
    //     ↓
    // ส่ง "#0000FF" เข้า Constructor
    //
    //
    // ; ต้องใส่หลังสมาชิกตัวสุดท้าย
    // ถ้าหลังจากนั้นมี Attribute / Method


    RED("#FF0000"),
    GREEN("#00FF00"),
    BLUE("#0000FF");


    // ============================================================
    // Attribute
    // ============================================================
    // enum สามารถมี Attribute ได้เหมือน Class
    //
    // ในตัวอย่างนี้
    //
    // hex = ใช้เก็บรหัสสีแบบ Hexadecimal
    //
    //
    // private = ไม่ให้ Class อื่นเข้าถึงโดยตรง
    //
    // เราจะเข้าถึงผ่าน Getter


    private String hex;


    // ============================================================
    // Constructor
    // ============================================================
    // Constructor จะทำงานตอนสร้าง Enum Constant
    //
    //
    // เช่น
    //
    // RED("#FF0000")
    //
    // จะส่ง "#FF0000"
    // เข้ามาที่ parameter hex
    //
    // แล้วนำไปเก็บไว้ใน Attribute
    //
    // this.hex = hex;
    //
    //
    // Constructor ของ enum
    // ไม่สามารถเรียกจากข้างนอกแบบ
    //
    // new Color(...)
    //
    // ได้
    //
    // เพราะ enum มีสมาชิกที่ถูกกำหนดไว้แล้ว


    private Color(String hex) {

        this.hex = hex;
    }


    // ============================================================
    // Getter
    // ============================================================
    // Method สำหรับอ่านค่า hex
    //
    // เนื่องจาก hex เป็น private
    // จึงไม่สามารถเขียน
    //
    // color.hex
    //
    // จากข้างนอกได้
    //
    // ต้องใช้ Getter
    //
    // color.getHex()


    public String getHex() {

        return hex;
    }


    // ============================================================
    // Method
    // ============================================================
    // enum สามารถสร้าง Method ได้ เหมือน Class ทั่วไป
    //
    //
    // showInfo() จะแสดง
    //
    // ชื่อของสี + Hex Code


    public void showInfo() {

        System.out.println(
                name() + " Color = " + hex
        );
    }

}


// ================================================================
// Main Class
// ================================================================

public class B14Enum {

    public static void main(String[] args) {


        // ========================================================
        // 1. การสร้างตัวแปร Enum
        // ========================================================
        // Color = Data Type
        //
        // Color.RED = ค่าที่เลือกจาก enum
        //
        //
        // ดังนั้น
        //
        // Color color = Color.RED;
        //
        // หมายถึง
        //
        // ตัวแปร color
        // สามารถเก็บค่าจาก Color enum
        // และตอนนี้มีค่าเป็น RED


        Color color = Color.RED;


        // แสดง enum
        //
        // ถ้า println enum โดยตรง
        // จะได้ชื่อของสมาชิก


        System.out.println(color);

        // RED


        // ========================================================
        // 2. เรียก Getter
        // ========================================================
        // เนื่องจาก hex เป็น private
        // เราจึงใช้ getHex()
        //
        //
        // color.getHex()
        //     ↓
        // "#FF0000"


        System.out.println(color.getHex());

        // #FF0000


        // ========================================================
        // 3. เรียก Method ของ Enum
        // ========================================================
        // เราสามารถเรียก Method
        // จาก Enum Constant ได้โดยตรง
        //
        //
        // Color.BLUE
        //     ↓
        // สมาชิก BLUE
        //
        //
        // .showInfo()
        //     ↓
        // เรียก Method showInfo()


        Color.BLUE.showInfo();

        // BLUE Color = #0000FF


        // ========================================================
        // 4. values()
        // ========================================================
        // values() = ดึงสมาชิกของ enum ทั้งหมด
        //
        //
        // Color.values()
        //
        // จะคืนค่าเป็น Array
        //
        //
        // Color[]
        //
        //
        // ดังนั้นสามารถนำมาเก็บได้ว่า
        //
        // Color[] colors


        Color[] colors = Color.values();


        // ========================================================
        // 5. ใช้ Loop กับ values()
        // ========================================================
        // เมื่อ values() ได้ Array มาแล้ว
        // เราสามารถใช้ Loop ได้
        //
        //
        // Enhanced for loop
        //
        // for (Color list : colors)
        //
        // หมายถึง
        //
        // เอาสมาชิกแต่ละตัวใน colors
        // มาเก็บไว้ในตัวแปร list
        //
        //
        // รอบที่ 1
        // list = RED
        //
        // รอบที่ 2
        // list = GREEN
        //
        // รอบที่ 3
        // list = BLUE


        System.out.println();
        System.out.println("All Colors:");

        for (Color list : colors) {

            System.out.println(list);
        }


        // ผลลัพธ์
        //
        // All Colors:
        // RED
        // GREEN
        // BLUE


        // ========================================================
        // 6. name()
        // ========================================================
        // name() = คืนชื่อของ Enum Constant
        //
        //
        // Color.RED.name()
        //     ↓
        //   "RED"
        //
        //
        // Return Type = String


        System.out.println(Color.RED.name());

        // RED


        // ========================================================
        // 7. ordinal()
        // ========================================================
        // ordinal() = คืนลำดับของ Enum Constant
        //
        //
        // สำคัญมาก!
        //
        // ลำดับเริ่มจาก 0
        //
        //
        // RED = 0
        //
        // GREEN = 1
        //
        // BLUE = 2


        System.out.println(Color.RED.ordinal()); // 0

        System.out.println(Color.GREEN.ordinal()); // 1

        System.out.println(Color.BLUE.ordinal()); // 2


        // ========================================================
        // ⚠️ ข้อควรระวัง ordinal()
        // ========================================================
        // ไม่ควรนำ ordinal()
        // ไปใช้เป็น ID สำคัญของข้อมูล
        //
        //
        // เพราะถ้าเราเปลี่ยนลำดับ
        //
        // จาก
        //
        // RED
        // GREEN
        // BLUE
        //
        //
        // เป็น
        //
        // BLUE
        // RED
        // GREEN
        //
        //
        // ordinal() ก็จะเปลี่ยนทันที
        //
        //
        // ดังนั้น
        //
        // ordinal()
        // เหมาะสำหรับรู้ "ตำแหน่ง"
        // มากกว่าการใช้เป็น ID ถาวร


        // ========================================================
        // 8. valueOf()
        // ========================================================
        // valueOf()
        // = แปลง String
        //     ↓
        //    Enum
        //
        //
        // ตัวอย่าง
        //
        //   "RED"
        //     ↓
        // Color.RED
        //
        //
        // รูปแบบ
        //
        // Color.valueOf("RED")


        Color color2 = Color.valueOf("RED");

        System.out.println(color2); // RED


        // ========================================================
        // ⚠️ valueOf() ต้องตรงกับชื่อ
        // ========================================================
        // Enum เป็น Case-Sensitive
        //
        //
        // "RED" = ถูก
        //
        //
        // "red" = ไม่ถูก
        //
        //
        // เพราะชื่อ Enum Constant ต้องตรงกัน


        // Color.valueOf("red");
        //
        // จะเกิด IllegalArgumentException


        // ========================================================
        // 9. values() + getHex()
        // ========================================================
        // เราสามารถนำ values()
        // มาใช้เพื่อแสดงข้อมูลของ Enum ทุกตัว
        //
        // ทั้งชื่อ และ Hex Color


        System.out.println();
        System.out.println("Color Information:");

        for (Color c : Color.values()) {

            System.out.println(
                    c.name() + " -> " + c.getHex()
            );
        }


        // ผลลัพธ์
        //
        // Color Information:
        // RED -> #FF0000
        // GREEN -> #00FF00
        // BLUE -> #0000FF


        // ========================================================
        // 10. Enum กับ switch
        // ========================================================
        // enum สามารถนำมาใช้กับ switch ได้
        //
        // เหมาะมากเมื่อเราต้องการ
        // ตรวจสอบค่าที่มีตัวเลือกจำกัด


        Color selectedColor = Color.GREEN;


        switch (selectedColor) {

            case RED:
                System.out.println("Stop");
                break;

            case GREEN:
                System.out.println("Go");
                break;

            case BLUE:
                System.out.println("Blue");
                break;
        }


        // ผลลัพธ์
        //
        // Go


        // ========================================================
        // 11. Enum กับ if
        // ========================================================
        // เราสามารถเปรียบเทียบ Enum ได้
        // ด้วย ==
        //
        //
        // เพราะ Enum แต่ละ Constant
        // เป็นค่าที่มีอยู่แน่นอน


        Color myColor = Color.RED;


        if (myColor == Color.RED) {

            System.out.println("Color is Red");
        }


        // ========================================================
        // 12. Enum สามารถมีข้อมูลหลายอย่าง
        // ========================================================
        // Enum ไม่ได้จำกัดแค่ String
        //
        // สามารถมี Attribute หลายตัวได้
        //
        // เช่น
        //
        // RED("#FF0000", 1)
        //
        // GREEN("#00FF00", 2)
        //
        // BLUE("#0000FF", 3)
        //
        //
        // แล้วสร้าง Constructor เพื่อรับค่าทั้งหมดได้
        //
        //
        // ดังนั้น Enum สามารถทำหน้าที่ คล้าย Object ที่มีข้อมูลประจำตัวได้


        // ========================================================
        // Summary
        // ========================================================
        /*
         * ========================================================
         * ENUM
         * ========================================================
         *
         * enum = Data Type ที่กำหนดค่าที่เป็นไปได้แบบจำกัด
         *
         *
         * ตัวอย่าง
         *
         * enum Color {
         *     RED,
         *     GREEN,
         *     BLUE
         * }
         *
         * สามารถใช้
         *
         * Color color = Color.RED;
         *
         *
         * ========================================================
         * Method สำคัญ
         * ========================================================
         *
         * values()
         * --------------------------------
         * คืนสมาชิกทั้งหมดเป็น Array
         *
         * Color.values()
         *
         *
         * valueOf()
         * --------------------------------
         * แปลง String -> Enum
         *
         * Color.valueOf("RED")
         *
         *
         * name()
         * --------------------------------
         * คืนชื่อของ Enum Constant
         *
         * Color.RED.name() -> "RED"
         *
         *
         * ordinal()
         * --------------------------------
         * คืนลำดับของ Enum
         *
         * RED   -> 0
         * GREEN -> 1
         * BLUE  -> 2
         *
         * ⚠️ ไม่ควรใช้เป็น ID ถาวร
         *
         * ========================================================
         * Enum สามารถมี
         * ========================================================
         *
         * - Attribute
         * - Constructor
         * - Method
         *
         *
         * เหมือน Class แต่ Enum มีค่าที่กำหนดไว้ล่วงหน้า
         *
         *
         * ========================================================
         * จำง่าย ๆ
         * ========================================================
         *
         * values() -> เอาทุกตัว
         *
         * valueOf() -> String -> Enum
         *
         * name() -> เอาชื่อ
         *
         * ordinal() -> เอาลำดับ
         *
         * ========================================================
         */
    }
}
