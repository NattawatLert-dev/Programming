package a01basic;

public class A6If_Statement {

    public static void main(String[] args) {

        // ========================================================
        // Condition
        // ========================================================
        // Condition = การเขียนโปรแกรมให้ "ตัดสินใจ" ว่าจะทำอะไรต่อไป
        //
        // โดยอาศัยผลลัพธ์ที่เป็น
        //
        // true  = จริง
        // false = เท็จ
        //
        // ตัวอย่างชีวิตประจำวัน
        //
        // ถ้าอายุ >= 18
        //     -> เป็นผู้ใหญ่
        // ถ้าไม่ใช่
        //     -> เป็นเด็ก
        //
        //
        // รูปแบบพื้นฐาน
        //
        // if (condition) {
        //     // ทำเมื่อ condition เป็น true
        // }
        //
        //
        // ภาพรวม
        //
        // Condition
        //     ↓
        //  ┌───────┐
        //  │ true? │
        //  └───────┘
        //    ↓   ↓
        //   Yes  No
        //    ↓   ↓
        //   ทำ   ไม่ทำ


        // ========================================================
        // 1. if-else
        // ========================================================
        // if-else = ใช้เมื่อมี 2 ทางเลือก
        //
        // ถ้าเงื่อนไขเป็น true
        //     -> ทำใน if
        //
        // ถ้าเงื่อนไขเป็น false
        //     -> ทำใน else


        int age = 15;

        if (age >= 18) {

            System.out.println("Adult");

        } else {

            System.out.println("Child");
        }

        /*
         * age = 15
         *
         * ตรวจสอบ
         *
         * age >= 18
         *
         * 15 >= 18
         *
         * false
         *
         * ดังนั้นไม่เข้า if
         * แต่เข้า else
         *
         * Output:
         *
         * Child
         */


        // ========================================================
        // 2. if อย่างเดียว
        // ========================================================
        // เราสามารถใช้ if โดยไม่มี else ได้
        //
        // ถ้า condition เป็น true
        //     -> ทำงาน
        //
        // ถ้า false
        //     -> ข้ามไปเลย


        int number = 10;

        if (number > 0) {

            System.out.println("Positive Number");
        }


        // ========================================================
        // 3. หลายเงื่อนไข (if-else if-else)
        // ========================================================
        // ใช้เมื่อเรามีหลายเงื่อนไข
        //
        // รูปแบบ
        //
        // if (condition1) {
        //
        // }
        // else if (condition2) {
        //
        // }
        // else {
        //
        // }
        //
        // Java จะตรวจสอบจากบนลงล่าง
        //
        // และเมื่อเจอเงื่อนไขที่เป็น true
        // จะทำงานใน block นั้น
        // แล้วข้ามเงื่อนไขที่เหลือ


        int score = 82;

        if (score >= 80) {

            System.out.println("Grade A");

        }
        else if (score >= 70) {

            System.out.println("Grade B");

        }
        else if (score >= 60) {

            System.out.println("Grade C");

        }
        else {

            System.out.println("Fail");
        }


        /*
         * score = 82
         *
         * ตรวจจากบนลงล่าง
         *
         * 82 >= 80
         *     ↓
         *   true
         *
         * จึงได้
         *
         * Grade A
         *
         * และจะไม่ตรวจ
         *
         * 82 >= 70
         * 82 >= 60
         *
         * ต่อแล้ว
         */


        // ========================================================
        // 4. Nested if
        // ========================================================
        // Nested if = การนำ if ไปใส่ไว้ใน if อีกที
        //
        // ใช้เมื่อมี "เงื่อนไขย่อย"
        //
        // ตัวอย่าง
        //
        // ต้องอายุ >= 18 ก่อน
        // แล้วจึงตรวจสอบว่าเป็นสมาชิกหรือไม่


        int a = 20;
        boolean member = false;

        if (a >= 18) {

            /*
             * เงื่อนไขแรก
             *
             * อายุ >= 18
             *
             * 20 >= 18
             *
             * true
             *
             * ดังนั้นเข้าไปตรวจสอบ if ข้างใน
             */

            if (member) {

                System.out.println("Discount");

            } else {

                System.out.println("DON'T HAVE DISCOUNT");
            }
        }


        // ========================================================
        // 5. Nested if + else
        // ========================================================
        /*
         * โครงสร้างจะเป็นแบบนี้
         *
         * if (condition1) {
         *
         *     if (condition2) {
         *
         *     } else {
         *
         *     }
         *
         * } else {
         *
         * }
         *
         *
         * ให้คิดเหมือนการถามคำถามทีละชั้น
         *
         * "อายุถึง 18 หรือยัง?"
         *          ↓
         *        Yes
         *          ↓
         * "เป็นสมาชิกไหม?"
         *       ↓       ↓
         *     Yes       No
         *      ↓         ↓
         *   Discount    No Discount
         */


        // ========================================================
        // 6. ใช้ Logical Operators กับ if
        // ========================================================
        // เราสามารถใช้ &&, ||, ! ร่วมกับ if ได้
        //
        // && = AND
        //     ทุกเงื่อนไขต้องเป็น true
        //
        // || = OR
        //     อย่างน้อย 1 เงื่อนไขต้องเป็น true
        //
        // ! = NOT
        //     กลับค่าจาก true -> false
        //                    false -> true


        int studentAge = 20;
        boolean hasStudentCard = true;

        if (studentAge >= 18 && hasStudentCard) {

            System.out.println("Student Discount");
        }


        // ========================================================
        // 7. ตัวอย่าง OR
        // ========================================================

        boolean isWeekend = true;
        boolean isHoliday = false;

        if (isWeekend || isHoliday) {

            System.out.println("No School");
        }


        // ========================================================
        // 8. ตัวอย่าง NOT
        // ========================================================

        boolean login = false;

        if (!login) {

            System.out.println("Please Login");
        }


        // ========================================================
        // 9. if กับ String
        // ========================================================
        /*
         * ⚠️ จุดสำคัญมาก
         *
         * เวลาเปรียบเทียบ String
         *
         * ไม่ควรใช้
         *
         * ==
         *
         * เช่น
         *
         * if (name == "Tle")
         *
         * เพราะ == ใช้เปรียบเทียบ Reference
         *
         * สำหรับ String ควรใช้
         *
         * .equals()
         */


        String name = "Tle";

        if (name.equals("Tle")) {

            System.out.println("Hello Tle");
        }


        // ========================================================
        // 10. ตรวจสอบหลาย String
        // ========================================================

        String role = "admin";

        if (role.equals("admin")) {

            System.out.println("Admin Access");

        }
        else if (role.equals("user")) {

            System.out.println("User Access");

        }
        else {

            System.out.println("Unknown Role");
        }


        // ========================================================
        // 11. Braces {}
        // ========================================================
        /*
         * แนะนำให้ใช้ {}
         * แม้ว่าจะมีคำสั่งแค่บรรทัดเดียว
         *
         * ตัวอย่างที่อ่านง่าย
         *
         * if (age >= 18) {
         *     System.out.println("Adult");
         * }
         *
         * ถึงแม้ Java จะอนุญาตให้เขียน
         *
         * if (age >= 18)
         *     System.out.println("Adult");
         *
         * แต่การใช้ {} ช่วยให้ Code
         * อ่านง่ายและลดความผิดพลาด
         */


        // ========================================================
        // 12. Ternary Operator
        // ========================================================
        // Ternary Operator
        // = การเขียน if-else แบบสั้น
        //
        // รูปแบบ
        //
        // condition ? valueIfTrue : valueIfFalse;
        //
        // ตัวอย่าง
        //
        // ถ้า x >= 18
        //     -> "Adult"
        //
        // ถ้าไม่ใช่
        //     -> "Child"


        int x = 20;

        String result = x >= 18 ? "Adult" : "Child";

        System.out.println(result);


        // ========================================================
        // 13. if ซ้อนหลายระดับ
        // ========================================================
        /*
         * สามารถซ้อน if ได้หลายระดับ
         *
         * แต่ไม่ควรซ้อนเยอะเกินไป
         *
         * เพราะจะทำให้ Code อ่านยาก
         *
         * ถ้าเงื่อนไขเริ่มซับซ้อนมาก
         * อาจใช้ &&, || หรือแยก Method
         * เพื่อทำให้ Code อ่านง่ายขึ้น
         */


        // ========================================================
        // Summary
        // ========================================================
        /*
         * ========================================================
         * สรุป If Statement
         * ========================================================
         *
         * 1. if = ใช้เมื่อเราต้องการตรวจสอบเงื่อนไข
         *
         *
         * 2. else = ทำงานเมื่อ if เป็น false
         *
         *
         * 3. else if = ใช้ตรวจสอบเงื่อนไขเพิ่มเติม
         *
         *
         * 4. Nested if = if ที่อยู่ภายใน if
         *
         *
         * 5. && (AND) = ทุกเงื่อนไขต้อง true
         *
         *
         * 6. || (OR) = อย่างน้อยหนึ่งเงื่อนไขต้อง true
         *
         *
         * 7. ! (NOT) = กลับค่า true / false
         *
         *
         * 8. String ใช้ .equals() เปรียบเทียบข้อความ
         *
         *
         * 9. Ternary
         *
         *    condition ? true : false
         *
         *    = if-else แบบสั้น
         * ========================================================
         */
    }
}
