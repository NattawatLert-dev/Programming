package a01basic;

public class A5Operator {

    public static void main(String[] args) {

        // ========================================================
        // Operator
        // ========================================================
        // Operator = สัญลักษณ์ที่ใช้ในการกระทำกับข้อมูล (Operand)
        //
        // เช่น
        // - คำนวณ
        // - เปรียบเทียบ
        // - กำหนดค่า
        // - ตรวจสอบเงื่อนไข
        //
        // ตัวอย่าง
        //
        // a + b
        //
        // a และ b = Operand
        // +        = Operator


        int a = 10;
        int b = 3;


        // ========================================================
        // 1. Arithmetic Operators
        // ========================================================
        // Arithmetic Operators = Operator สำหรับการคำนวณทางคณิตศาสตร์
        //
        // +   บวก
        // -   ลบ
        // *   คูณ
        // /   หาร
        // %   หารเอาเศษ (Modulus)
        //
        // ========================================================

        System.out.println(a + b); // 13
        System.out.println(a - b); // 7
        System.out.println(a * b); // 30
        System.out.println(a / b); // 3
        System.out.println(a % b); // 1

        /*
         * ⚠️ สิ่งสำคัญเรื่อง /
         *
         * a และ b เป็น int
         *
         * 10 / 3
         *
         * ผลลัพธ์ = 3
         *
         * ไม่ใช่ 3.3333
         *
         * เพราะ Integer Division จะตัดส่วนทศนิยมทิ้ง
         *
         * ถ้าต้องการผลลัพธ์เป็นทศนิยม
         *
         * double result = (double) a / b;
         *
         * จะได้ประมาณ
         *
         * 3.3333333333333335
         */


        // ========================================================
        // 2. Modulus (%)
        // ========================================================
        // % = หารเอา "เศษ"
        //
        // ตัวอย่าง
        //
        // 10 / 3
        //
        // 3 x 3 = 9
        // เหลือ 1
        //
        // ดังนั้น
        //
        // 10 % 3 = 1
        //
        // % มีประโยชน์มาก เช่น
        // - ตรวจเลขคู่/คี่
        // - ตรวจรอบ
        // - แบ่งกลุ่มข้อมูล


        System.out.println(10 % 2); // 0
        System.out.println(11 % 2); // 1


        // ========================================================
        // 3. Comparison / Relational Operators
        // ========================================================
        // Comparison Operator = ใช้เปรียบเทียบค่า
        //
        // ผลลัพธ์จะเป็น
        //
        // true
        // หรือ
        // false
        //
        // ========================================================
        //
        // ==    เท่ากันหรือไม่
        // !=    ไม่เท่ากัน
        // <     น้อยกว่า
        // >     มากกว่า
        // <=    น้อยกว่าหรือเท่ากับ
        // >=    มากกว่าหรือเท่ากับ
        //
        // ========================================================

        System.out.println(a == b); // false
        System.out.println(a != b); // true
        System.out.println(a < b);  // false
        System.out.println(a > b);  // true
        System.out.println(a <= b); // false
        System.out.println(a >= b); // true


        // ========================================================
        // ⚠️ == กับ =
        // ========================================================
        /*
         * ต้องแยกให้ออก
         *
         * =
         * = Assignment
         * = กำหนดค่า
         *
         * int x = 10;
         *
         * หมายถึง
         * เอา 10 ไปเก็บไว้ใน x
         *
         *
         * ==
         * = Comparison
         * = เปรียบเทียบ
         *
         * x == 10
         *
         * หมายถึง x มีค่าเท่ากับ 10 หรือไม่?
         *
         * ผลลัพธ์เป็น true / false
         */


        // ========================================================
        // 4. Assignment Operators
        // ========================================================
        // Assignment Operator = ใช้กำหนดหรือเปลี่ยนค่าของ Variable
        //
        // ========================================================
        //
        // =     กำหนดค่า
        // +=    บวกแล้วเก็บ
        // -=    ลบแล้วเก็บ
        // *=    คูณแล้วเก็บ
        // /=    หารแล้วเก็บ
        // %=    หารเอาเศษแล้วเก็บ
        //
        // ========================================================

        int x = 10;

        x += 5;
        // เหมือนกับ
        // x = x + 5;

        System.out.println(x); // 15


        x -= 5;
        // เหมือนกับ
        // x = x - 5;

        System.out.println(x); // 10


        x *= 2;
        // เหมือนกับ
        // x = x * 2;

        System.out.println(x); // 20


        x /= 4;
        // เหมือนกับ
        // x = x / 4;

        System.out.println(x); // 5


        x %= 3;
        // เหมือนกับ
        // x = x % 3;

        System.out.println(x); // 2


        // ========================================================
        // 5. Logical Operators
        // ========================================================
        // Logical Operators = ใช้เชื่อมเงื่อนไขที่เป็น boolean
        //
        // && = AND
        // || = OR
        // !  = NOT
        //
        // ========================================================

        int age = 20;
        boolean hasCard = true;


        // --------------------------------------------------------
        // &&
        // --------------------------------------------------------
        // AND = ต้องเป็น true "ทั้งสองเงื่อนไข"
        //
        // age >= 18
        //     = true
        //
        // hasCard
        //     = true
        //
        // true && true
        //     = true

        System.out.println(age >= 18 && hasCard); // true


        // --------------------------------------------------------
        // ||
        // --------------------------------------------------------
        // OR = อย่างน้อย 1 เงื่อนไขเป็น true
        //
        // age < 18
        //     = false
        //
        // hasCard
        //     = true
        //
        // false || true
        //     = true

        System.out.println(age < 18 || hasCard); // true


        // --------------------------------------------------------
        // !
        // --------------------------------------------------------
        // NOT = กลับค่าจาก true -> false
        //                  false -> true
        //
        // hasCard = true
        //
        // !hasCard
        //     ↓
        // false

        System.out.println(!hasCard); // false


        // ========================================================
        // 6. Truth Table
        // ========================================================
        /*
         * AND (&&)
         *
         * true  && true  = true
         * true  && false = false
         * false && true  = false
         * false && false = false
         *
         *
         * OR (||)
         *
         * true  || true  = true
         * true  || false = true
         * false || true  = true
         * false || false = false
         *
         *
         * NOT (!)
         *
         * !true  = false
         * !false = true
         */


        // ========================================================
        // 7. Increment / Decrement Operators
        // ========================================================
        // ใช้เพิ่มหรือลดค่าทีละ 1
        //
        // ++ = เพิ่ม 1
        // -- = ลด 1
        //
        // ========================================================

        int y = 5;


        // --------------------------------------------------------
        // Post-Increment
        // --------------------------------------------------------

        y++;

        System.out.println(y); // 6

        /*
         * y++
         *
         * เหมือนกับ
         *
         * y = y + 1;
         */


        // --------------------------------------------------------
        // Pre-Increment
        // --------------------------------------------------------

        ++y;

        System.out.println(y); // 7

        /*
         * ++y
         *
         * เหมือนกับ
         *
         * y = y + 1;
         */


        // --------------------------------------------------------
        // Pre-Decrement
        // --------------------------------------------------------

        --y;

        System.out.println(y); // 6

        /*
         * --y
         *
         * เหมือนกับ
         *
         * y = y - 1;
         */


        // --------------------------------------------------------
        // Post-Decrement
        // --------------------------------------------------------

        y--;

        System.out.println(y); // 5


        // ========================================================
        // 8. Pre vs Post
        // ========================================================
        /*
         * จุดที่สำคัญมากคือ
         *
         * y++
         * ++y
         *
         * ทั้งสองแบบเพิ่มค่า 1 เหมือนกัน
         *
         * แต่จะต่างกันเมื่อเราใช้ค่า ใน Expression เดียวกัน
         *
         *
         * Post-Increment
         *
         * y++
         *
         * = ใช้ค่าก่อน แล้วค่อยเพิ่ม
         *
         *
         * Pre-Increment
         *
         * ++y
         *
         * = เพิ่มก่อน แล้วค่อยใช้ค่า
         */


        int number1 = 5;

        int result1 = number1++;

        System.out.println("number1 = " + number1); // 6
        System.out.println("result1 = " + result1); // 5


        int number2 = 5;

        int result2 = ++number2;

        System.out.println("number2 = " + number2); // 6
        System.out.println("result2 = " + result2); // 6


        // ========================================================
        // 9. Operator Precedence
        // ========================================================
        /*
         * Java มีลำดับการคำนวณ
         *
         * ตัวอย่าง
         *
         * int result = 10 + 5 * 2;
         *
         * จะไม่ได้
         *
         * (10 + 5) * 2 = 30
         *
         * แต่จะเป็น
         *
         * 10 + (5 * 2)
         * = 10 + 10
         * = 20
         *
         * เพราะ * มีลำดับสูงกว่า +
         *
         *
         * ถ้าไม่แน่ใจให้ใช้ ()
         *
         * int result = (10 + 5) * 2;
         *
         * = 30
         */


        int result = 10 + 5 * 2;

        System.out.println("10 + 5 * 2 = " + result); // 20


        int resultWithParentheses = (10 + 5) * 2;

        System.out.println(
                "(10 + 5) * 2 = " + resultWithParentheses
        ); // 30


        String status = age >= 18 ? "Adult" : "Child";

        System.out.println("Status = " + status);


        // ========================================================
        // Summary
        // ========================================================
        /*
         * ========================================================
         * สรุป Operator ที่ควรรู้
         * ========================================================
         *
         * Arithmetic
         *
         * +   บวก
         * -   ลบ
         * *   คูณ
         * /   หาร
         * %   หารเอาเศษ
         *
         *
         * Comparison
         *
         * ==  เท่ากับ
         * !=  ไม่เท่ากับ
         * <   น้อยกว่า
         * >   มากกว่า
         * <=  น้อยกว่าหรือเท่ากับ
         * >=  มากกว่าหรือเท่ากับ
         *
         *
         * Assignment
         *
         * =   กำหนดค่า
         * +=  บวกแล้วเก็บ
         * -=  ลบแล้วเก็บ
         * *=  คูณแล้วเก็บ
         * /=  หารแล้วเก็บ
         * %=  หารเอาเศษแล้วเก็บ
         *
         *
         * Logical
         *
         * &&  AND
         * ||  OR
         * !   NOT
         *
         *
         * Increment / Decrement
         *
         * ++  เพิ่ม 1
         * --  ลด 1
         *
         * ========================================================
         *
         * สิ่งที่ต้องจำเป็นพิเศษ
         *
         * 1. =  -> กำหนดค่า
         * 2. == -> เปรียบเทียบ
         * 3. %  -> หาเศษ
         * 4. && -> ทุกเงื่อนไขต้อง true
         * 5. || -> อย่างน้อยหนึ่งเงื่อนไขต้อง true
         * 6. !  -> กลับ true/false
         * 7. ++ -> เพิ่ม 1
         * 8. -- -> ลด 1
         * 9. () -> ใช้กำหนดลำดับการคำนวณ
         *
         * ========================================================
         */
    }
}
