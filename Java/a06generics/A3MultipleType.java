package a06generics;


/*
 * ============================================================
 * A3MultipleType
 * ============================================================
 *
 * Generic Multiple Type
 * ============================================================
 *
 * Generic ไม่จำเป็นต้องมีแค่ Type เดียว
 *
 * เราสามารถกำหนด Generic หลาย Type ได้ เช่น:
 *
 * <T, U>
 * <K, V>
 * <A, B, C>
 *
 *
 * ตัวอย่าง:
 *
 * Pair<String, Integer>
 *
 * T → String
 * U → Integer
 *
 *
 * หมายความว่า Pair นี้:
 *
 * key   → String
 * value → Integer
 *
 *
 * ============================================================
 */


/*
 * ============================================================
 * 1. Generic Class ที่มี 2 Type
 * ============================================================
 *
 * Pair<T, U>
 *
 * T = Type ที่ 1
 * U = Type ที่ 2
 *
 *
 * เราสามารถนำ T และ U
 * ไปใช้เป็น Type ของ Attribute
 * Parameter และ Return Type ได้
 *
 * ============================================================
 */


class Pair<T, U> {


    // ========================================================
    // Attribute
    // ========================================================
    //
    // key มี Type เป็น T
    // value มี Type เป็น U


    private T key;

    private U value;


    // ========================================================
    // Constructor
    // ========================================================


    public Pair(T key, U value) {

        this.key = key;

        this.value = value;

    }


    // ========================================================
    // Getter
    // ========================================================
    //
    // T → key
    // U → value


    public T getKey() {

        return key;

    }


    public U getValue() {

        return value;

    }
}


/*
 * ============================================================
 * Main
 * ============================================================
 */


public class A3MultipleType {

    public static void main(String[] args) {


        // ========================================================
        // 2. สร้าง Pair<String, Integer>
        // ========================================================
        //
        // T = String
        // U = Integer
        //
        //
        // ดังนั้น:
        //
        // key
        // ↓
        // String
        //
        // value
        // ↓
        // Integer


        Pair<String, Integer> student =
                new Pair<>(
                        "Hello",
                        100
                );


        System.out.println(
                student.getKey()
        );


        System.out.println(
                student.getValue()
        );


        /*
         * ผลลัพธ์:
         *
         * Hello
         * 100
         *
         */


        // ========================================================
        // 3. Pair<String, String>
        // ========================================================
        //
        // Generic แต่ละตัวสามารถเป็น Type เดียวกันก็ได้
        //
        //
        // T = String
        // U = String


        Pair<String, String> person =
                new Pair<>(
                        "Name",
                        "Tle"
                );


        System.out.println(
                person.getKey()
        );


        System.out.println(
                person.getValue()
        );


        // ========================================================
        // 4. Pair<Integer, Double>
        // ========================================================
        //
        // T = Integer
        // U = Double


        Pair<Integer, Double> product =
                new Pair<>(
                        101,
                        99.99
                );


        System.out.println(
                product.getKey()
        );


        System.out.println(
                product.getValue()
        );


        // ========================================================
        // 5. Pair<String, Boolean>
        // ========================================================
        //
        // T = String
        // U = Boolean


        Pair<String, Boolean> account =
                new Pair<>(
                        "isStudent",
                        true
                );


        System.out.println(
                account.getKey()
        );


        System.out.println(
                account.getValue()
        );


        // ========================================================
        // 6. Type Safety
        // ========================================================
        //
        // เมื่อกำหนด:
        //
        // Pair<String, Integer>
        //
        // Java จะบังคับว่า:
        //
        // key   ต้องเป็น String
        // value ต้องเป็น Integer
        //
        //
        // ดังนั้น:
        //
        // Pair<String, Integer> student =
        //     new Pair<>("Tle", 20);
        //
        // ถูกต้อง
        //
        //
        // แต่:
        //
        // new Pair<>(100, "Tle");
        //
        // ❌ ไม่ถูกต้อง
        //
        // เพราะ Type สลับกัน
        //
        // key ต้อง String
        // แต่ส่ง Integer
        //
        // value ต้อง Integer
        // แต่ส่ง String


        // ========================================================
        // 7. Generic Type ไม่จำเป็นต้องชื่อ T และ U
        // ========================================================
        //
        // T และ U เป็นเพียงชื่อ
        //
        // เราสามารถเขียน:
        //
        // Pair<K, V>
        //
        //
        // ได้เช่นกัน
        //
        // K มักหมายถึง Key
        // V มักหมายถึง Value
        //
        //
        // เช่น:
        //
        // class Pair<K, V>
        //
        //
        // จะอ่านง่ายกว่า:
        //
        // class Pair<T, U>
        //
        // ในกรณีที่เรารู้ว่า
        // Type แรกคือ Key
        // และ Type ที่สองคือ Value


        // ========================================================
        // 8. ความสัมพันธ์กับ HashMap
        // ========================================================
        //
        // สิ่งที่สำคัญมาก:
        //
        // HashMap ที่เราเรียนมาก่อนหน้านี้
        // ก็ใช้แนวคิดเดียวกัน
        //
        //
        // HashMap<K, V>
        //
        // K = Key
        // V = Value
        //
        //
        // ตัวอย่าง:
        //
        // HashMap<String, Integer>
        //
        //
        // String → Key
        // Integer → Value
        //
        //
        // เช่น:
        //
        // "Apple" → 50
        // "Banana" → 20
        // "Orange" → 30
        //
        //
        // ซึ่งมีแนวคิดคล้าย:
        //
        // Pair<String, Integer>


        // ========================================================
        // 9. Pair ไม่เหมือน HashMap
        // ========================================================
        //
        // ถึงแม้แนวคิดจะคล้ายกัน
        // แต่ Pair กับ HashMap ไม่เหมือนกัน
        //
        //
        // Pair:
        //
        // เก็บข้อมูล 1 คู่
        //
        // key → value
        //
        //
        // HashMap:
        //
        // เก็บข้อมูลหลายคู่
        //
        // key1 → value1
        // key2 → value2
        // key3 → value3
        //
        //
        // ดังนั้น:
        //
        // Pair เหมาะกับข้อมูลคู่เดียว
        //
        // HashMap เหมาะกับข้อมูลหลายคู่


        // ========================================================
        // 10. Generic มากกว่า 2 Type
        // ========================================================
        //
        // เราสามารถมีมากกว่า 2 Type ได้
        //
        // เช่น:
        //
        // <A, B, C>
        //
        // แต่ควรใช้เท่าที่จำเป็น
        //
        // ถ้ามี Type เยอะเกินไป
        // Code อาจอ่านยาก
        //
        //
        // ตัวอย่าง:
        //
        // Triple<String, Integer, Double>
        //
        // String
        // Integer
        // Double
        //
        //
        // แต่ในโปรแกรมจริง
        // ถ้าข้อมูลซับซ้อนมาก
        // อาจเหมาะกับการสร้าง Class
        // ที่มีชื่อชัดเจนมากกว่า


        // ========================================================
        // 11. Diamond Operator
        // ========================================================
        //
        // เราเขียน:
        //
        // new Pair<>(
        //     "Hello",
        //     100
        // );
        //
        //
        // แทน:
        //
        // new Pair<String, Integer>(
        //     "Hello",
        //     100
        // );
        //
        //
        // <> เรียกว่า Diamond Operator
        //
        // Java สามารถอนุมาน Type
        // จากด้านซ้ายและ Argument


        // ========================================================
        // 12. Generic Multiple Type + Method
        // ========================================================
        //
        // Generic หลาย Type
        // สามารถใช้กับ Method ได้เช่นกัน
        //
        //
        // ตัวอย่าง:
        //
        // createPair("Age", 20)
        //
        // K = String
        // V = Integer


        Pair<String, Integer> result =
                createPair(
                        "Age",
                        20
                );


        System.out.println(
                result.getKey()
        );


        System.out.println(
                result.getValue()
        );


        // ========================================================
        // Program End
        // ========================================================


        System.out.println(
                "\n========== Program End =========="
        );
    }


    // ============================================================
    // 13. Generic Method ที่มีหลาย Type
    // ============================================================
    //
    // <K, V>
    // ↓
    // ประกาศ Generic 2 ตัว
    //
    //
    // Pair<K, V>
    // ↓
    // Return Type
    //
    //
    // K key
    // ↓
    // Parameter ตัวที่ 1
    //
    //
    // V value
    // ↓
    // Parameter ตัวที่ 2


    public static <K, V> Pair<K, V> createPair(
            K key,
            V value
    ) {

        return new Pair<>(
                key,
                value
        );

    }
}


/*
 * ============================================================
 * มองภาพ Generic Multiple Type
 * ============================================================
 *
 *
 * class Pair<T, U>
 *
 *        │
 *        ├──────────────┐
 *        ↓              ↓
 *        T              U
 *        │              │
 *        ↓              ↓
 *      Key            Value
 *
 *
 * ------------------------------------------------------------
 *
 *
 * Pair<String, Integer>
 *
 *        │
 *        ├──────────────┐
 *        ↓              ↓
 *     String          Integer
 *        │              │
 *        ↓              ↓
 *      Key            Value
 *
 *
 * ============================================================
 */


/*
 * ============================================================
 * เปรียบเทียบ Generic 1 Type กับ Multiple Type
 * ============================================================
 *
 *
 * 1 Type
 *
 * Box<T>
 *
 *        ↓
 *
 * Box<String>
 *
 *
 * T → String
 *
 *
 * ------------------------------------------------------------
 *
 *
 * 2 Type
 *
 * Pair<T, U>
 *
 *        ↓
 *
 * Pair<String, Integer>
 *
 *
 * T → String
 * U → Integer
 *
 *
 * ============================================================
 */


/*
 * ============================================================
 * Generic Naming Convention
 * ============================================================
 *
 *
 * T = Type
 *
 * E = Element
 *
 * K = Key
 *
 * V = Value
 *
 * N = Number
 *
 *
 * ดังนั้นถ้าเราสร้าง:
 *
 * Pair<K, V>
 *
 * จะสื่อความหมายได้ดีว่า:
 *
 * K = Key
 * V = Value
 *
 *
 * ============================================================
 */


