package a06generics;


/*
 * ============================================================
 * A4BoundedType
 * ============================================================
 *
 * Bounded Type
 * ============================================================
 *
 * Bounded Type = การกำหนด "ขอบเขต" ให้กับ Generic
 *
 * จากเดิม:
 *
 * <T>
 *
 * T สามารถเป็น Type ได้หลากหลาย
 *
 *
 * แต่บางครั้งเราไม่ต้องการให้ T เป็นอะไรก็ได้
 *
 * เราต้องการกำหนดว่า:
 *
 * T ต้องเป็น Number
 * หรือ
 * T ต้องเป็นคลาสลูกของ Number
 *
 *
 * จึงใช้:
 *
 * <T extends Number>
 *
 *
 * ============================================================
 */


/*
 * ============================================================
 * 1. Generic แบบปกติ
 * ============================================================
 *
 * ตัวอย่าง:
 *
 * class Box<T>
 *
 *
 * T สามารถเป็น:
 *
 * String
 * Integer
 * Double
 * Boolean
 * Student
 * ฯลฯ
 *
 *
 * เพราะเราไม่ได้กำหนดขอบเขต
 *
 *
 * ============================================================
 */


/*
 * ============================================================
 * 2. Bounded Generic
 * ============================================================
 *
 *
 * class Calculator<T extends Number>
 *
 *
 * หมายความว่า:
 *
 * T ต้องเป็น Number
 * หรือ Class ที่สืบทอดจาก Number
 *
 *
 * ตัวอย่างที่ใช้ได้:
 *
 * Integer
 * Double
 * Float
 * Long
 * Short
 * Byte
 *
 *
 * เพราะทั้งหมดเป็น Subclass ของ Number
 *
 *
 * ============================================================
 */


/*
 * ============================================================
 * Class Calculator
 * ============================================================
 */


class Calculator<T extends Number> {


    // ========================================================
    // Attribute
    // ========================================================
    //
    // T มีขอบเขตเป็น Number
    //
    // ดังนั้น T จะต้องเป็น Number
    // หรือ Subclass ของ Number


    private T a;

    private T b;


    // ========================================================
    // Constructor
    // ========================================================


    public Calculator(T a, T b) {

        this.a = a;

        this.b = b;

    }


    // ========================================================
    // sum()
    // ========================================================
    //
    // Number มีเมธอด:
    //
    // doubleValue()
    //
    // ซึ่งสามารถแปลงค่า Number
    // ให้เป็น double ได้
    //
    //
    // ตัวอย่าง:
    //
    // Integer → double
    // Double  → double
    // Float   → double
    // Long    → double


    public double sum() {

        return a.doubleValue()
                + b.doubleValue();

    }
}


/*
 * ============================================================
 * Main
 * ============================================================
 */


public class A4BoundedType {

    public static void main(String[] args) {


        // ========================================================
        // 3. Calculator<Integer>
        // ========================================================
        //
        // Integer extends Number
        //
        // ดังนั้นใช้ได้


        Calculator<Integer> integerCalculator =
                new Calculator<>(
                        10,
                        14
                );


        System.out.println(
                "Integer Sum = "
                + integerCalculator.sum()
        );


        // ผลลัพธ์:
        //
        // Integer Sum = 24.0


        // ========================================================
        // 4. Calculator<Double>
        // ========================================================
        //
        // Double extends Number
        //
        // ดังนั้นใช้ได้


        Calculator<Double> doubleCalculator =
                new Calculator<>(
                        10.5,
                        14.5
                );


        System.out.println(
                "Double Sum = "
                + doubleCalculator.sum()
        );


        // ผลลัพธ์:
        //
        // Double Sum = 25.0


        // ========================================================
        // 5. Calculator<Float>
        // ========================================================


        Calculator<Float> floatCalculator =
                new Calculator<>(
                        5.5f,
                        4.5f
                );


        System.out.println(
                "Float Sum = "
                + floatCalculator.sum()
        );


        // ========================================================
        // 6. Calculator<Long>
        // ========================================================


        Calculator<Long> longCalculator =
                new Calculator<>(
                        100L,
                        200L
                );


        System.out.println(
                "Long Sum = "
                + longCalculator.sum()
        );


        // ========================================================
        // 7. ทำไม String ใช้ไม่ได้?
        // ========================================================
        //
        // String ไม่ได้ extends Number
        //
        //
        // ดังนั้น:
        //
        // Calculator<String>
        //
        // ❌ Compile Error
        //
        //
        // เพราะ:
        //
        // String
        //    ↓
        // ไม่ใช่ Number
        //
        //
        // ตัวอย่าง:
        //
        // Calculator<String> wrong =
        //     new Calculator<>("10", "20");
        //
        //
        // Java จะปฏิเสธตั้งแต่ Compile Time


        // ❌ Compile Error
        //
        // Calculator<String> wrong =
        //         new Calculator<>("10", "20");


        // ========================================================
        // 8. ทำไม Boolean ใช้ไม่ได้?
        // ========================================================
        //
        // Boolean ก็ไม่ได้ extends Number
        //
        //
        // ดังนั้น:
        //
        // Calculator<Boolean>
        //
        // ❌ Compile Error


        // ❌ Compile Error
        //
        // Calculator<Boolean> wrong =
        //         new Calculator<>(true, false);


        // ========================================================
        // 9. Type Safety
        // ========================================================
        //
        // ข้อดีของ Bounded Type คือ
        // Java สามารถตรวจสอบได้ตั้งแต่ Compile Time
        //
        //
        // เรากำหนด:
        //
        // T extends Number
        //
        //
        // ดังนั้น Java รู้ว่า:
        //
        // T ต้องมี Number เป็นขอบเขต
        //
        //
        // เราจึงสามารถเรียก:
        //
        // a.doubleValue()
        //
        // ได้อย่างปลอดภัย


        // ========================================================
        // 10. ทำไมเรียก doubleValue() ได้?
        // ========================================================
        //
        // ลองดู:
        //
        // class Calculator<T>
        //
        //
        // ถ้าเขียนแบบนี้:
        //
        // class Calculator<T>
        //
        //
        // Java ไม่รู้ว่า T มี doubleValue()
        //
        //
        // เพราะ T อาจเป็น:
        //
        // String
        // Boolean
        // Student
        // ฯลฯ
        //
        //
        // ดังนั้น:
        //
        // a.doubleValue()
        //
        // ❌ Compile Error
        //
        //
        // แต่เมื่อเขียน:
        //
        // class Calculator<T extends Number>
        //
        //
        // Java รู้ว่า:
        //
        // T อย่างน้อยต้องเป็น Number
        //
        // จึงมั่นใจได้ว่า:
        //
        // doubleValue()
        //
        // มีอยู่


        // ========================================================
        // 11. มองภาพ extends
        // ========================================================
        /*
         *
         *              Number
         *                 │
         *       ┌─────────┼─────────┐
         *       │         │         │
         *    Integer    Double    Float
         *       │
         *      ...
         *
         *
         * T extends Number
         *
         * หมายความว่า T สามารถเป็น:
         *
         * Number
         * Integer
         * Double
         * Float
         * Long
         * Short
         * Byte
         *
         *
         */


        // ========================================================
        // 12. extends ใน Generic ไม่ได้หมายถึง
        //     "ต้องเป็น Number เท่านั้น"
        // ========================================================
        //
        // จุดนี้สำคัญ
        //
        //
        // T extends Number
        //
        // ไม่ได้แปลว่า:
        //
        // T = Number เท่านั้น
        //
        //
        // แต่หมายถึง:
        //
        // T เป็น Number
        // หรือ
        // T เป็น Subclass ของ Number
        //
        //
        // เช่น:
        //
        // Integer
        // Double
        // Float
        // Long
        //
        // สามารถใช้ได้


        // ========================================================
        // 13. Bounded Type กับ Class ของเราเอง
        // ========================================================
        //
        // เราสามารถกำหนด Bound
        // เป็น Class ที่เราสร้างเองได้
        //
        //
        // เช่น:
        //
        // class Animal
        //
        //
        // class Dog extends Animal
        //
        //
        // เราสามารถสร้าง:
        //
        // class Cage<T extends Animal>
        //
        //
        // หมายความว่า:
        //
        // Cage ต้องเก็บ Animal
        // หรือ Subclass ของ Animal
        //
        //
        // เช่น:
        //
        // Cage<Dog>
        //
        // สามารถใช้ได้


        // ========================================================
        // 14. Multiple Bounds
        // ========================================================
        //
        // Generic สามารถมีหลาย Bound ได้
        //
        //
        // ตัวอย่าง:
        //
        // <T extends Number & Comparable<T>>
        //
        //
        // หมายความว่า:
        //
        // T ต้อง:
        //
        // 1. เป็น Number หรือ Subclass
        //
        // และ
        //
        // 2. Implement Comparable<T>
        //
        //
        // Syntax:
        //
        // <T extends Class & Interface1 & Interface2>
        //
        //
        // Class ต้องอยู่ตัวแรก
        // Interface อยู่หลังจากนั้น


        // ========================================================
        // 15. Generic Method ก็ใช้ Bound ได้
        // ========================================================
        //
        // Bounded Type ไม่ได้ใช้เฉพาะ Class
        //
        // Method ก็ใช้ได้
        //
        //
        // ตัวอย่าง:
        //
        // findMax()
        //
        // กำหนด:
        //
        // <T extends Number>
        //
        //
        // เพื่อให้รับเฉพาะ Number


        System.out.println(
                "Max = "
                + findMax(10, 20)
        );


        System.out.println(
                "Max = "
                + findMax(10.5, 5.5)
        );


        // ========================================================
        // Program End
        // ========================================================


        System.out.println(
                "\n========== Program End =========="
        );
    }


    // ============================================================
    // 16. Bounded Generic Method
    // ============================================================
    //
    // <T extends Number>
    //
    // T ต้องเป็น Number
    // หรือ Subclass ของ Number
    //
    //
    // Number มี doubleValue()
    // ดังนั้นเราสามารถใช้ได้


    public static <T extends Number>
    double findMax(T a, T b) {

        return Math.max(
                a.doubleValue(),
                b.doubleValue()
        );
    }
}


