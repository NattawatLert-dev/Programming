package a06generics;

/*
 * ============================================================
 * A1IntroToGeneric
 * ============================================================
 *
 * Generic
 * ============================================================
 *
 * Generic = ความสามารถของ Java ที่ทำให้เราสามารถเขียน
 *           Class / Method ที่สามารถทำงานกับข้อมูลหลายชนิด
 *           (Type) ได้
 *
 * จุดสำคัญ:
 *
 * 1. Reusable → เขียนโค้ดครั้งเดียว ใช้กับหลาย Type
 *
 * 2. Type Safety → Java ตรวจสอบชนิดข้อมูลตั้งแต่ Compile Time
 *
 * 3. ลดการเขียน Code ซ้ำ
 *
 *
 * ============================================================
 * ตัวอย่างปัญหาถ้าไม่มี Generic
 * ============================================================
 *
 * สมมติว่าเราต้องการสร้าง Box
 *
 * Box String
 * Box Integer
 * Box Double
 *
 *
 * ถ้าเขียน Class แยก:
 *
 * StringBox
 * IntegerBox
 * DoubleBox
 *
 * จะต้องเขียน Code ซ้ำกันมาก
 *
 *
 * Generic ช่วยให้เราเขียน:
 *
 * Box<T>
 *
 * เพียงครั้งเดียว
 *
 * แล้วเลือก Type ตอนสร้าง Object
 *
 *
 * Box<String>
 * Box<Integer>
 * Box<Double>
 *
 *
 * ============================================================
 */


/*
 * ============================================================
 * 1. Generic Class
 * ============================================================
 *
 * <T>
 *
 * T = Type
 *
 * T เป็นเพียงชื่อที่ใช้แทน "ชนิดข้อมูล"
 *
 *
 * เช่น:
 *
 * Box<String>
 *
 * T → String
 *
 *
 * Box<Integer>
 *
 * T → Integer
 *
 *
 * ============================================================
 */


class Box<T> {


    // ========================================================
    // Attribute
    // ========================================================
    //
    // T ยังไม่ใช่ Type ที่กำหนดจริง
    //
    // มันเป็นตัวแทนของ Type
    //
    // ตอนสร้าง Object
    // Java จะรู้ว่า T คืออะไร


    private T value;


    // ========================================================
    // Constructor
    // ========================================================


    public Box(T value) {

        this.value = value;

    }


    // ========================================================
    // Getter
    // ========================================================
    //
    // คืนค่า Type T


    public T getValue() {

        return value;

    }


    // ========================================================
    // Setter
    // ========================================================
    //
    // รับค่า Type T


    public void setValue(T value) {

        this.value = value;

    }
}


