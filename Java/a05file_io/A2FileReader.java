package a05file_io;

import java.io.BufferedReader;
import java.io.FileReader;
import java.io.IOException;


/*
 * ============================================================
 * A2FileReader
 * ============================================================
 *
 * FileReader
 * ============================================================
 *
 * FileReader = Class ที่ใช้สำหรับ "อ่านข้อมูลแบบตัวอักษร"
 *              (Character / Text)
 *              จากไฟล์
 *
 *
 * ถ้า FileWriter คือ:
 *
 *     Program
 *        ↓
 *      File
 *
 *
 * FileReader คือ:
 *
 *     File
 *        ↓
 *      Program
 *
 *
 * ดังนั้น:
 *
 * FileWriter → เขียนไฟล์
 * FileReader → อ่านไฟล์
 *
 *
 * ============================================================
 * ตัวอย่างไฟล์ hello.txt
 * ============================================================
 *
 * Name : Tle
 * Age : 20
 * Major : Computer Science
 *
 *
 * โปรแกรมจะอ่านข้อมูลจากไฟล์
 * แล้วนำมาแสดงบน Console
 *
 * ============================================================
 */

public class A2FileReader {

    public static void main(String[] args) {


        // ========================================================
        // 1. FileReader
        // ========================================================
        //
        // เปิดไฟล์ hello.txt เพื่ออ่านข้อมูล
        //
        // ถ้าไฟล์ไม่มี:
        //
        //     IOException
        //
        //
        // ตัวอย่าง:
        //
        // FileReader reader =
        //     new FileReader("hello.txt");


        try (
                FileReader reader =
                        new FileReader("hello.txt")
        ) {


            // ====================================================
            // 2. read()
            // ====================================================
            //
            // read()
            // = อ่านข้อมูลจากไฟล์ทีละ 1 ตัวอักษร
            //
            //
            // แต่ค่าที่ได้จาก read()
            // จะเป็น int
            //
            //
            // เช่น:
            //
            // File:
            //
            // ABC
            //
            //
            // reader.read()
            //
            // ครั้งที่ 1 → 65 ('A')
            // ครั้งที่ 2 → 66 ('B')
            // ครั้งที่ 3 → 67 ('C')
            //
            // เมื่ออ่านถึงจุดสิ้นสุด:
            //
            // → -1
            //
            //
            // ดังนั้นเราจึงใช้:
            //
            // while ((ch = reader.read()) != -1)


            int ch;


            // ====================================================
            // 3. อ่านจนกว่าจะถึง End Of File
            // ====================================================
            //
            // EOF = End Of File
            //
            // เมื่อไม่มีข้อมูลเหลือแล้ว
            // read() จะคืนค่า -1


            while (
                    (ch = reader.read()) != -1
            ) {

                System.out.print(
                        (char) ch
                );
            }


            /*
             * ====================================================
             * ทำไมต้อง (char) ch ?
             * ====================================================
             *
             * เพราะ read() คืนค่าเป็น int
             *
             *
             * เช่น:
             *
             * 'A'
             * → 65
             *
             *
             * read() ได้:
             *
             * 65
             *
             *
             * เราต้องการแสดง:
             *
             * A
             *
             *
             * จึงใช้:
             *
             * (char) ch
             *
             *
             * int
             * ↓
             * char
             *
             */


        }

        catch (IOException e) {

            System.out.println(
                    "ไม่สามารถอ่านไฟล์ได้"
            );

            System.out.println(
                    "รายละเอียด: "
                    + e.getMessage()
            );
        }


        // ========================================================
        // 4. try-with-resources
        // ========================================================
        //
        // ในตัวอย่างด้านบน:
        //
        // try (
        //     FileReader reader =
        //         new FileReader("hello.txt")
        // )
        //
        //
        // Java จะเรียก close()
        // ให้โดยอัตโนมัติ
        //
        //
        // จึงไม่จำเป็นต้องเขียน:
        //
        // reader.close();
        //
        //
        // เอง
        //
        //
        // นี่เป็นรูปแบบที่ควรใช้
        // เมื่อทำงานกับ Resource


        // ========================================================
        // 5. อ่านทีละตัวอักษรแบบง่าย
        // ========================================================
        //
        // ตัวอย่างนี้ใช้เพื่อให้เข้าใจ
        // การทำงานของ read()


        try (
                FileReader reader =
                        new FileReader("hello.txt")
        ) {

            int ch;

            while (
                    (ch = reader.read()) != -1
            ) {

                System.out.print(
                        (char) ch
                );
            }

        }

        catch (IOException e) {

            System.out.println(
                    "Read Error"
            );
        }


        // ========================================================
        // 6. อ่านด้วย char[]
        // ========================================================
        //
        // FileReader สามารถอ่านข้อมูล
        // หลายตัวอักษรในครั้งเดียวได้
        //
        // ซึ่งมีประสิทธิภาพกว่า
        // การเรียก read() ทีละตัว


        try (
                FileReader reader =
                        new FileReader("hello.txt")
        ) {

            char[] buffer =
                    new char[1024];

            int charsRead;


            while (
                    (charsRead =
                            reader.read(buffer))
                    != -1
            ) {

                System.out.print(
                        new String(
                                buffer,
                                0,
                                charsRead
                        )
                );
            }

        }

        catch (IOException e) {

            System.out.println(
                    "Read Error"
            );
        }


        /*
         * ========================================================
         * buffer คืออะไร?
         * ========================================================
         *
         * buffer = พื้นที่ชั่วคราวสำหรับเก็บข้อมูล
         *
         *
         * char[] buffer = new char[1024];
         *
         *
         * หมายถึง:
         *
         * เตรียมพื้นที่เก็บตัวอักษร
         * ได้สูงสุด 1024 ตัวต่อครั้ง
         *
         *
         * ข้อดี:
         *
         * ไม่ต้องอ่านทีละตัว
         *
         * สามารถอ่านเป็นกลุ่มได้
         *
         */


        // ========================================================
        // 7. BufferedReader
        // ========================================================
        //
        // ถ้าเราต้องการอ่าน Text
        // "ทีละบรรทัด"
        //
        // BufferedReader
        // จะสะดวกกว่า FileReader
        //
        //
        // BufferedReader มี:
        //
        // readLine()
        //
        // สำหรับอ่านทีละบรรทัด


        try (
                BufferedReader reader =
                        new BufferedReader(
                                new FileReader(
                                        "hello.txt"
                                )
                        )
        ) {

            String line;


            while (
                    (line = reader.readLine())
                    != null
            ) {

                System.out.println(line);
            }

        }

        catch (IOException e) {

            System.out.println(
                    "ไม่สามารถอ่านไฟล์ได้"
            );
        }


        /*
         * ========================================================
         * FileReader vs BufferedReader
         * ========================================================
         *
         *
         * FileReader
         * -----------------------------
         *
         * อ่าน Character
         *
         * read()
         *
         *
         * BufferedReader
         * -----------------------------
         *
         * อ่าน Text ได้สะดวกกว่า
         *
         * readLine()
         *
         *
         * ตัวอย่าง:
         *
         * File:
         *
         * Hello
         * Java
         * World
         *
         *
         * BufferedReader:
         *
         * readLine()
         *     ↓
         * "Hello"
         *
         * readLine()
         *     ↓
         * "Java"
         *
         * readLine()
         *     ↓
         * "World"
         *
         * readLine()
         *     ↓
         * null
         *
         */


        // ========================================================
        // 8. ทำไม readLine() ใช้ null
        // ========================================================
        //
        // readLine()
        // จะคืน:
        //
        // String
        //
        //
        // ถ้ายังมีข้อมูล:
        //
        // "Hello"
        //
        //
        // ถ้าอ่านจนหมด:
        //
        // null
        //
        //
        // จึงเขียน:
        //
        // while ((line = reader.readLine()) != null)


        // ========================================================
        // 9. FileNotFoundException
        // ========================================================
        //
        // ถ้าไฟล์ไม่มีอยู่
        //
        // FileReader
        // สามารถเกิด:
        //
        // FileNotFoundException
        //
        //
        // ซึ่งเป็น Exception ที่เกี่ยวข้องกับ IOException
        //
        //
        // เราจึงสามารถ catch:
        //
        // catch (IOException e)
        //
        // ได้


        // ========================================================
        // 10. Path
        // ========================================================
        //
        // ตัวอย่าง:
        //
        // new FileReader("hello.txt")
        //
        //
        // เป็น Relative Path
        //
        // Java จะหาไฟล์จาก
        // Working Directory
        //
        //
        // ถ้าไฟล์อยู่ใน Folder:
        //
        // data/hello.txt
        //
        //
        // สามารถเขียน:
        //
        // new FileReader("data/hello.txt")
        //
        //
        // ถ้าอยู่ใน:
        //
        // src/data/hello.txt
        //
        // ก็ต้องระบุ Path ให้ถูกตาม
        // Working Directory ของโปรแกรม


        // ========================================================
        // 11. อ่านไฟล์ภาษาไทย
        // ========================================================
        //
        // จุดนี้สำคัญมาก
        //
        // FileReader ใช้ Charset
        // ที่อิงกับ Default Charset
        // ของระบบในหลายกรณี
        //
        //
        // ถ้าไฟล์มีภาษาไทย
        // และ Encoding ของไฟล์กับระบบไม่ตรงกัน
        //
        // อาจเกิด:
        //
        //     ภาษาไทยเพี้ยน
        //
        //
        // เช่น:
        //
        // สวัสดี
        //
        // อาจกลายเป็น:
        //
        // ??????
        //
        //
        // ใน Java รุ่นใหม่
        // ถ้าต้องการควบคุม Charset อย่างชัดเจน
        // ควรใช้:
        //
        // InputStreamReader
        //
        // หรือ
        //
        // Files.newBufferedReader()
        //
        // ร่วมกับ:
        //
        // StandardCharsets.UTF_8


        // ========================================================
        // 12. FileReader ไม่ใช่ Binary Reader
        // ========================================================
        /*
         *
         * FileReader
         * ↓
         * Text
         *
         *
         * เช่น:
         *
         * .txt
         * .csv
         * .log
         *
         *
         * ไม่ควรใช้ FileReader
         * สำหรับไฟล์ Binary เช่น:
         *
         * .jpg
         * .png
         * .mp3
         * .mp4
         * .zip
         *
         *
         * ไฟล์เหล่านี้ควรใช้
         * InputStream
         *
         */


        // ========================================================
        // 13. FileWriter + FileReader
        // ========================================================
        //
        // ตอนนี้เราสามารถเห็นภาพ
        // การทำงานทั้งสองฝั่งได้แล้ว
        //
        //
        // FileWriter
        //
        // Program
        //    ↓
        // File
        //
        //
        // FileReader
        //
        // File
        //    ↓
        // Program
        //
        //
        // ดังนั้น:
        //
        // Writer = เขียน
        // Reader = อ่าน


        // ========================================================
        // 14. ตัวอย่าง Workflow จริง
        // ========================================================
        /*
         *
         * ขั้นตอน:
         *
         *
         * 1. FileWriter
         *        ↓
         * 2. สร้าง student.txt
         *        ↓
         * 3. เขียนข้อมูล
         *        ↓
         * 4. ปิดไฟล์
         *        ↓
         * 5. FileReader
         *        ↓
         * 6. อ่านข้อมูล
         *        ↓
         * 7. แสดงผล
         *
         *
         * นี่คือพื้นฐานของ File I/O
         */


        // ========================================================
        // 15. สรุป
        // ========================================================
        /*
         *
         * ========================================================
         * FileReader
         * ========================================================
         *
         * ใช้สำหรับอ่าน Text จากไฟล์
         *
         *
         * --------------------------------------------------------
         *
         * read()
         * --------------------------------------------------------
         *
         * อ่าน Character
         * ทีละตัว
         *
         * คืนค่า int
         *
         * ถ้าอ่านถึง EOF:
         *
         * -1
         *
         *
         * --------------------------------------------------------
         *
         * read(char[])
         * --------------------------------------------------------
         *
         * อ่านหลาย Character
         * ผ่าน Buffer
         *
         *
         * --------------------------------------------------------
         *
         * BufferedReader
         * --------------------------------------------------------
         *
         * ช่วยอ่าน Text ได้สะดวก
         *
         *
         * readLine()
         * → อ่านทีละบรรทัด
         *
         *
         * --------------------------------------------------------
         *
         * try-with-resources
         * --------------------------------------------------------
         *
         * ปิด Resource ให้อัตโนมัติ
         *
         *
         * --------------------------------------------------------
         *
         * IOException
         * --------------------------------------------------------
         *
         * จัดการปัญหาเกี่ยวกับ File I/O
         *
         *
         * ========================================================
         */


        System.out.println(
                "\n========== Program End =========="
        );
    }
}