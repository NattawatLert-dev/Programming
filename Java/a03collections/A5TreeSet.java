package a03collections;

import java.util.TreeSet;

/*
 * ============================================================
 * A7TreeSet
 * ============================================================
 *
 * TreeSet = Collection ที่เก็บข้อมูลแบบ "ไม่ซ้ำ" และ "เรียงลำดับอัตโนมัติ"
 *
 *
 * จุดเด่น:
 *
 * 1. ข้อมูลไม่ซ้ำ (Unique)
 * 2. ข้อมูลถูกเรียงลำดับ (Sorted)
 * 3. ไม่มี Index
 * 4. มีเมธอดสำหรับค้นหาค่าที่อยู่ใกล้เคียง
 * 5. สามารถกำหนด Comparator เพื่อเปลี่ยนวิธีเรียงได้
 *
 *
 * ============================================================
 * เปรียบเทียบ Set ทั้ง 3 ตัว
 * ============================================================
 *
 * HashSet → ไม่ซ้ำ
 *         → ไม่รับประกันลำดับ
 *
 *
 * LinkedHashSet → ไม่ซ้ำ
 *               → รักษาลำดับที่เพิ่ม
 *
 *
 * TreeSet → ไม่ซ้ำ
 *         → เรียงลำดับ
 *
 *
 * จำง่าย ๆ:
 *
 * HashSet
 *       ↓
 *     ไม่ซ้ำ
 *
 * LinkedHashSet
 *       ↓
 *  ไม่ซ้ำ + จำลำดับที่เพิ่ม
 *
 * TreeSet
 *       ↓
 *  ไม่ซ้ำ + เรียงลำดับ
 *
 * ============================================================
 */

public class A5TreeSet {

    public static void main(String[] args) {


        // ========================================================
        // 1. สร้าง TreeSet
        // ========================================================
        //
        // รูปแบบ:
        //
        // TreeSet<DataType> variable = new TreeSet<>();
        //
        //
        // ในตัวอย่างนี้เก็บ Integer


        TreeSet<Integer> numbers = new TreeSet<>();


        // ========================================================
        // 2. add()
        // ========================================================
        //
        // ลองเพิ่มข้อมูลแบบไม่ได้เรียงลำดับ


        numbers.add(50);
        numbers.add(10);
        numbers.add(40);
        numbers.add(20);
        numbers.add(30);


        System.out.println(numbers);

        /*
         * Output:
         *
         * [10, 20, 30, 40, 50]
         *
         *
         * เราเพิ่ม:
         *
         * 50 → 10 → 40 → 20 → 30
         *
         * แต่ TreeSet จัดเรียงให้อัตโนมัติ
         */


        // ========================================================
        // 3. ข้อมูลซ้ำจะไม่ถูกเก็บ
        // ========================================================


        numbers.add(20);
        numbers.add(30);
        numbers.add(50);

        System.out.println(numbers);

        /*
         * Output:
         *
         * [10, 20, 30, 40, 50]
         *
         *
         * เพราะ 20, 30 และ 50
         * มีอยู่แล้ว
         *
         * TreeSet จึงไม่เพิ่มซ้ำ
         */


        // ========================================================
        // 4. add() คืนค่า boolean
        // ========================================================
        //
        // true → เพิ่มสำเร็จ
        //
        // false → มีข้อมูลอยู่แล้ว


        TreeSet<Integer> data = new TreeSet<>();

        System.out.println(data.add(100)); // true


        System.out.println(data.add(100)); // false


        // ========================================================
        // 5. first()
        // ========================================================
        //
        // คืนค่าตัวแรก
        //
        // เพราะ TreeSet เรียงจากน้อย → มาก
        // first() จึงเป็นค่าน้อยที่สุด


        System.out.println("ค่าต่ำสุด: " + numbers.first()); // 10


        // ========================================================
        // 6. last()
        // ========================================================
        //
        // คืนค่าตัวสุดท้าย
        //
        // ในกรณีเรียงจากน้อย → มาก
        // last() คือค่ามากที่สุด


        System.out.println("ค่าสูงสุด: " + numbers.last()); // 50


        // ========================================================
        // 7. lower()
        // ========================================================
        //
        // คืนค่าที่ "น้อยกว่า" ค่าที่กำหนด
        //
        // และเลือกค่าที่ใกล้ที่สุด


        System.out.println("ค่าที่น้อยกว่า 30: " + numbers.lower(30)); // 20


        // ========================================================
        // 8. higher()
        // ========================================================
        //
        // คืนค่าที่ "มากกว่า" ค่าที่กำหนด
        //
        // และเลือกค่าที่ใกล้ที่สุด


        System.out.println("ค่าที่มากกว่า 30: " + numbers.higher(30)); // 40


        // ========================================================
        // 9. floor()
        // ========================================================
        //
        // คืนค่าที่ "น้อยกว่าหรือเท่ากับ"
        // ค่าที่กำหนด
        //
        // หรือจำง่าย ๆ:
        //
        // <= target


        System.out.println("floor(30): "+ numbers.floor(30)); // 30


        System.out.println("floor(35): " + numbers.floor(35)); // 30


        // ========================================================
        // 10. ceiling()
        // ========================================================
        //
        // คืนค่าที่ "มากกว่าหรือเท่ากับ"
        // ค่าที่กำหนด
        //
        // หรือ:
        //
        // >= target


        System.out.println("ceiling(30): " + numbers.ceiling(30)); // 30


        System.out.println("ceiling(35): " + numbers.ceiling(35)); // 40


        // ========================================================
        // 11. lower / floor / higher / ceiling
        // ========================================================
        //
        // 4 ตัวนี้สำคัญมาก
        //
        //
        // สมมติ:
        //
        // numbers = [10, 20, 30, 40, 50]
        //
        //
        // target = 30
        //
        //
        // lower(30)
        // → 20
        // → ต้อง "น้อยกว่า" เท่านั้น
        //
        //
        // floor(30)
        // → 30
        // → "น้อยกว่าหรือเท่ากับ"
        //
        //
        // higher(30)
        // → 40
        // → ต้อง "มากกว่า" เท่านั้น
        //
        //
        // ceiling(30)
        // → 30
        // → "มากกว่าหรือเท่ากับ"
        //
        //
        // จำเป็นภาพ:
        //
        //       lower       floor
        //         ↓           ↓
        //
        // 10 ─ 20 ─ 30 ─ 40 ─ 50
        //           ↑
        //
        //         target
        //
        //
        //              ↑
        //           ceiling
        //
        //              ↑
        //            higher
        //
        // ========================================================


        // ========================================================
        // 12. contains()
        // ========================================================
        //
        // ตรวจสอบว่ามีข้อมูลหรือไม่


        System.out.println("มี 30 หรือไม่: " + numbers.contains(30)); // true


        System.out.println("มี 99 หรือไม่: " + numbers.contains(99)); // false


        // ========================================================
        // 13. remove()
        // ========================================================
        //
        // ลบข้อมูลโดยระบุ "ค่า"


        numbers.remove(30);

        System.out.println("หลังลบ 30: " + numbers); // [10, 20, 40, 50]


        // ========================================================
        // 14. size()
        // ========================================================


        System.out.println("จำนวนสมาชิก: " + numbers.size());


        // ========================================================
        // 15. isEmpty()
        // ========================================================


        System.out.println("ว่างหรือไม่: " + numbers.isEmpty());


        // ========================================================
        // 16. clear()
        // ========================================================
        //
        // ลบข้อมูลทั้งหมด


        TreeSet<Integer> temp = new TreeSet<>();

        temp.add(10);
        temp.add(20);
        temp.add(30);

        System.out.println("ก่อน clear: " + temp);

        temp.clear();

        System.out.println("หลัง clear: " + temp); // []
        

        // ========================================================
        // 17. ไม่มี get(index)
        // ========================================================
        //
        // TreeSet เป็น Set
        //
        // ดังนั้นไม่มี:
        //
        // numbers.get(0);
        //
        // ❌ ใช้ไม่ได้
        //
        //
        // เพราะ TreeSet ไม่ได้เก็บข้อมูล
        // เพื่อเข้าถึงด้วย Index
        //
        //
        // ถ้าต้องการ:
        //
        // list.get(0)
        //
        // → ArrayList
        

        // ========================================================
        // 18. วนข้อมูลด้วย for-each
        // ========================================================
        //
        // TreeSet จะวนตามลำดับที่เรียงไว้


        System.out.println("\nสมาชิกใน TreeSet:");

        for (int number : numbers) {
            System.out.println(number);
        }

        /*
         * Output:
         *
         * 10
         * 20
         * 40
         * 50
         *
         * เรียงจากน้อย → มาก
         */


        // ========================================================
        // 19. descendingSet()
        // ========================================================
        //
        // ใช้ดูข้อมูลจากมาก → น้อย


        System.out.println("\nมาก → น้อย:");

        System.out.println(numbers.descendingSet()); // [50, 40, 20, 10]


        // ========================================================
        // 20. pollFirst()
        // ========================================================
        //
        // เอาตัวแรกออกจาก TreeSet
        //
        // และคืนค่าตัวที่ถูกลบ


        TreeSet<Integer> pollData = new TreeSet<>();

        pollData.add(10);
        pollData.add(20);
        pollData.add(30);


        int first = pollData.pollFirst();

        System.out.println("\npollFirst(): " + first); // 10


        System.out.println("หลัง pollFirst(): " + pollData); // [20, 30]


        // ========================================================
        // 21. pollLast()
        // ========================================================
        //
        // เอาตัวสุดท้ายออก
        // และคืนค่าที่ถูกลบ


        int last = pollData.pollLast();

        System.out.println("pollLast(): " + last); // 30


        System.out.println("หลัง pollLast(): " + pollData); // [20]


        // ========================================================
        // 22. subSet()
        // ========================================================
        //
        // ใช้เลือกข้อมูลบางช่วง
        //
        // fromElement รวม
        // toElement ไม่รวม


        TreeSet<Integer> scores = new TreeSet<>();

        scores.add(10);
        scores.add(20);
        scores.add(30);
        scores.add(40);
        scores.add(50);


        System.out.println("\nsubSet(20, 50): " + scores.subSet(20, 50)); // [20, 30, 40]


        // 50 ไม่รวม
        

        // ========================================================
        // 23. headSet()
        // ========================================================
        //
        // เอาข้อมูลที่น้อยกว่า value


        System.out.println("headSet(30): " + scores.headSet(30)); // [10, 20]


        // ========================================================
        // 24. tailSet()
        // ========================================================
        //
        // เอาข้อมูลตั้งแต่ value เป็นต้นไป


        System.out.println("tailSet(30): " + scores.tailSet(30)); // [30, 40, 50]


        // ========================================================
        // 25. TreeSet กับ String
        // ========================================================
        //
        // TreeSet สามารถเรียง String
        // ตาม Natural Ordering ได้


        TreeSet<String> names = new TreeSet<>();

        names.add("Charlie");
        names.add("Alice");
        names.add("Bob");
        names.add("David");

        System.out.println("\nString TreeSet:"+ names);

        /*
         * Output:
         *
         * [Alice, Bob, Charlie, David]
         */


        // ========================================================
        // 26. TreeSet กับ Comparator
        // ========================================================
        //
        // โดยปกติ Integer:
        //
        // น้อย → มาก
        //
        // แต่เราสามารถกำหนดวิธีเรียงเองได้
        //
        // ตัวอย่าง:
        //
        // มาก → น้อย


        TreeSet<Integer> descending =new TreeSet<>((a, b) -> b.compareTo(a));


        descending.add(10);
        descending.add(50);
        descending.add(20);
        descending.add(40);
        descending.add(30);


        System.out.println("\nCustom Order:" + descending);

        // [50, 40, 30, 20, 10]


        // ========================================================
        // 27. ตัวอย่างจริง: คะแนน
        // ========================================================
        //
        // สมมติเรามีคะแนนของนักเรียน
        //
        // ต้องการ:
        //
        // 1. คะแนนไม่ซ้ำ
        // 2. เรียงคะแนน
        // 3. หาคะแนนต่ำสุด
        // 4. หาคะแนนสูงสุด


        TreeSet<Integer> studentScores = new TreeSet<>();

        studentScores.add(85);
        studentScores.add(72);
        studentScores.add(95);
        studentScores.add(85);
        studentScores.add(60);
        studentScores.add(90);


        System.out.println("\nคะแนนทั้งหมด: " + studentScores); // [60, 72, 85, 90, 95]


        System.out.println("คะแนนต่ำสุด: " + studentScores.first()); // 60


        System.out.println("คะแนนสูงสุด: " + studentScores.last()); // 95


        // ========================================================
        // 28. TreeSet เหมาะกับงานแบบไหน?
        // ========================================================
        /*
         *
         * เหมาะเมื่อ:
         *
         * 1. ต้องการข้อมูลไม่ซ้ำ
         *
         * 2. ต้องการข้อมูลเรียงอยู่ตลอดเวลา
         *
         * 3. ต้องการหาค่าต่ำสุด / สูงสุด
         *
         * 4. ต้องการหาค่าที่ใกล้เคียงกับค่าที่กำหนด
         *
         * 5. ต้องการแบ่งข้อมูลเป็นช่วง
         *
         *
         * ตัวอย่าง:
         *
         * - คะแนนที่ไม่ซ้ำและเรียงลำดับ
         * - ราคาสินค้าที่ไม่ซ้ำ
         * - ตัวเลขที่ต้องเรียงตลอดเวลา
         * - ระบบค้นหาค่าที่ใกล้เคียง
         * - ข้อมูลที่ต้องการ min / max
         *
         */


        // ========================================================
        // 29. โครงสร้างข้อมูลภายใน
        // ========================================================
        /*
         *
         * TreeSet ใช้โครงสร้างข้อมูล
         *
         * Red-Black Tree
         *
         * ซึ่งเป็น Balanced Binary Search Tree
         *
         *
         * แนวคิดง่าย ๆ:
         *
         *              30
         *             /  \
         *           20    50
         *          /     /  \
         *        10     40   60
         *
         *
         * ข้อมูลจะถูกจัดให้อยู่ในโครงสร้าง
         * ที่ช่วยให้ค้นหา / เพิ่ม / ลบ
         * ได้อย่างมีประสิทธิภาพ
         *
         *
         * โดยทั่วไป:
         *
         * add()
         * remove()
         * contains()
         *
         * มีความซับซ้อนประมาณ O(log n)
         *
         *
         * แตกต่างจาก HashSet ที่โดยเฉลี่ย
         * มักทำงานประมาณ O(1)
         *
         */


        // ========================================================
        // 30. เปรียบเทียบ Collection ที่เรียนมา
        // ========================================================
        /*
         *
         * --------------------------------------------------------
         *                  ArrayList HashSet LinkedHashSet TreeSet
         * --------------------------------------------------------
         *
         * มี Index            ✓        ✗          ✗          ✗
         *
         * ข้อมูลซ้ำได้          ✓        ✗          ✗          ✗
         *
         * รักษาลำดับเพิ่ม       ✓        ✗          ✓          ✗
         *
         * เรียงอัตโนมัติ         ✗        ✗          ✗          ✓
         *
         * get(index)         ✓        ✗          ✗          ✗
         *
         * --------------------------------------------------------
         *
         *
         * ArrayList → มีลำดับ + ซ้ำได้
         *
         *
         * HashSet → ไม่ซ้ำ + ไม่สนลำดับ
         *
         *
         * LinkedHashSet → ไม่ซ้ำ + รักษาลำดับเพิ่ม
         *
         *
         * TreeSet → ไม่ซ้ำ + เรียงลำดับ
         *
         */


        // ========================================================
        // 31. Method สำคัญที่ควรจำ
        // ========================================================
        /*
         *
         * add() → เพิ่มข้อมูล
         *
         * contains() → ตรวจสอบข้อมูล
         *
         * remove() → ลบข้อมูล
         *
         * size() → จำนวนสมาชิก
         *
         * isEmpty() → ตรวจสอบว่าว่าง
         *
         * clear() → ลบทั้งหมด
         *
         *
         * first() → ตัวแรก / ค่าน้อยสุด
         *
         * last() → ตัวสุดท้าย / ค่ามากสุด
         *
         * lower() → ค่าที่น้อยกว่า target
         *
         * floor() → ค่าที่น้อยกว่าหรือเท่ากับ target
         *
         * higher() → ค่าที่มากกว่า target
         *
         * ceiling() → ค่าที่มากกว่าหรือเท่ากับ target
         *
         * 
         * pollFirst() → เอาตัวแรกออก
         *
         * pollLast() → เอาตัวสุดท้ายออก
         *
         * descendingSet() → มุมมองจากมากไปน้อย
         *
         * subSet() → เลือกข้อมูลเป็นช่วง
         *
         * headSet() → ข้อมูลก่อนค่าที่กำหนด
         *
         * tailSet() → ข้อมูลตั้งแต่ค่าที่กำหนด
         *
         */


        // ========================================================
        // 32. สิ่งที่ต้องจำที่สุด
        // ========================================================
        /*
         *
         * TreeSet = "ไม่ซ้ำ + เรียงลำดับ"
         *
         *
         * ถ้าโจทย์บอกว่า:
         *
         * "ต้องไม่ซ้ำ"
         *
         * → Set
         *
         *
         * "ไม่ซ้ำ + ไม่สนลำดับ"
         *
         * → HashSet
         *
         *
         * "ไม่ซ้ำ + ต้องจำลำดับที่เพิ่ม"
         *
         * → LinkedHashSet
         *
         *
         * "ไม่ซ้ำ + ต้องเรียงข้อมูล"
         *
         * → TreeSet
         *
         *
         * ========================================================
         */
    }
}
