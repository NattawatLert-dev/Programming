package a03collections;

import java.util.HashSet;

/*
 * ============================================================
 * A3HashSet
 * ============================================================
 *
 * HashSet
 * = โครงสร้างข้อมูล (Data Structure)
 *   ที่ใช้เก็บข้อมูลแบบ "ไม่ซ้ำกัน"
 *
 * จุดสำคัญ:
 *
 * 1. ไม่อนุญาตให้มีข้อมูลซ้ำ
 * 2. ไม่มี Index
 * 3. ไม่รับประกันลำดับของข้อมูล
 * 4. ค้นหา / เพิ่ม / ลบ โดยทั่วไปทำได้เร็ว
 * 5. ใช้ Hash Table อยู่เบื้องหลัง
 *
 *
 * ============================================================
 * ArrayList vs HashSet
 * ============================================================
 *
 * ArrayList
 * → เน้น "ลำดับ"
 * → มี Index
 * → มีข้อมูลซ้ำได้
 *
 *
 * HashSet
 * → เน้น "ความไม่ซ้ำ"
 * → ไม่มี Index
 * → ข้อมูลซ้ำไม่ได้
 *
 *
 * ตัวอย่าง:
 *
 * ArrayList:
 *
 * [10, 20, 10, 30]
 *
 *
 * HashSet:
 *
 * [10, 20, 30]
 *
 *
 * ============================================================
 */

public class A3HashSet {

    public static void main(String[] args) {


        // ========================================================
        // 1. สร้าง HashSet
        // ========================================================
        //
        // ต้อง import:
        //
        // import java.util.HashSet;
        //
        //
        // รูปแบบ:
        //
        // HashSet<DataType> variable =
        //         new HashSet<>();


        HashSet<Integer> set =
                new HashSet<>();


        // ========================================================
        // 2. add()
        // ========================================================
        //
        // ใช้เพิ่มข้อมูลเข้า HashSet


        set.add(5);

        System.out.println(set);

        // Output:
        // [5]


        // ========================================================
        // 3. HashSet ไม่เก็บข้อมูลซ้ำ
        // ========================================================
        //
        // ลองเพิ่ม 5 อีกหลายครั้ง


        set.add(5);
        set.add(5);
        set.add(5);

        System.out.println(set);

        // Output:
        //
        // [5]
        //
        // ถึงแม้เราจะ add(5) หลายครั้ง
        // HashSet ก็ยังมี 5 เพียงตัวเดียว


        // ========================================================
        // 4. add() จะคืนค่า boolean
        // ========================================================
        //
        // จุดนี้สำคัญ
        //
        // add() ของ Set จะคืนค่า:
        //
        // true
        // → เพิ่มข้อมูลสำเร็จ
        //
        // false
        // → ข้อมูลนั้นมีอยู่แล้ว


        HashSet<Integer> numbers =
                new HashSet<>();

        System.out.println(
                numbers.add(10)
        );

        // true


        System.out.println(
                numbers.add(10)
        );

        // false
        //
        // เพราะ 10 มีอยู่แล้ว


        // ========================================================
        // 5. เพิ่มข้อมูลหลายตัว
        // ========================================================


        HashSet<Integer> data =
                new HashSet<>();

        data.add(10);
        data.add(20);
        data.add(30);
        data.add(40);
        data.add(50);

        System.out.println(data);


        // ========================================================
        // 6. เพิ่มข้อมูลซ้ำ
        // ========================================================


        data.add(20);
        data.add(30);
        data.add(30);
        data.add(40);

        System.out.println(data);

        // ผลลัพธ์ยังมีข้อมูลแต่ละค่าเพียงครั้งเดียว


        // ========================================================
        // 7. HashSet ไม่มี Index
        // ========================================================
        //
        // ArrayList:
        //
        // list.get(0)
        //
        //
        // HashSet:
        //
        // ❌ set.get(0)
        //
        // ไม่สามารถทำได้
        //
        // เพราะ HashSet ไม่มีแนวคิดเรื่อง Index
        //
        //
        // ดังนั้น:
        //
        // set[0]
        //
        // ❌ ใช้ไม่ได้
        //
        // set.get(0)
        //
        // ❌ ใช้ไม่ได้


        // ========================================================
        // 8. contains()
        // ========================================================
        //
        // ใช้ตรวจสอบว่ามีข้อมูลอยู่ใน HashSet หรือไม่
        //
        // คืนค่า:
        //
        // true / false


        System.out.println(
                "มี 30 หรือไม่: "
                + data.contains(30)
        );

        // true


        System.out.println(
                "มี 100 หรือไม่: "
                + data.contains(100)
        );

        // false


        // ========================================================
        // 9. remove()
        // ========================================================
        //
        // ลบข้อมูลโดยระบุ "ค่า"
        //
        // HashSet ไม่มี Index
        // ดังนั้น remove() จึงใช้ค่าที่ต้องการลบ


        data.remove(30);

        System.out.println(
                "หลังลบ 30: " + data
        );


        // ========================================================
        // 10. size()
        // ========================================================
        //
        // จำนวนสมาชิก
        //
        // เหมือน ArrayList
        //
        // ใช้:
        //
        // size()


        System.out.println(
                "จำนวนสมาชิก: " + data.size()
        );


        // ========================================================
        // 11. isEmpty()
        // ========================================================
        //
        // ตรวจสอบว่า HashSet ว่างหรือไม่


        System.out.println(
                "ว่างหรือไม่: " + data.isEmpty()
        );

        // false


        // ========================================================
        // 12. clear()
        // ========================================================
        //
        // ลบข้อมูลทั้งหมด


        HashSet<Integer> temp =
                new HashSet<>();

        temp.add(10);
        temp.add(20);
        temp.add(30);

        System.out.println(
                "ก่อน clear: " + temp
        );

        temp.clear();

        System.out.println(
                "หลัง clear: " + temp
        );

        // Output:
        //
        // ก่อน clear: [10, 20, 30]
        // หลัง clear: []


        // ========================================================
        // 13. for-each
        // ========================================================
        //
        // เพราะ HashSet ไม่มี Index
        // เราจึงนิยมใช้ for-each
        // เพื่ออ่านสมาชิก


        System.out.println("\nสมาชิกใน HashSet:");

        for (int number : data) {

            System.out.println(number);
        }


        // ========================================================
        // 14. forEach()
        // ========================================================
        //
        // สามารถใช้ forEach() ได้เช่นกัน


        System.out.println("\nใช้ forEach():");

        data.forEach(
                System.out::println
        );


        // ========================================================
        // 15. HashSet ไม่รับประกันลำดับ
        // ========================================================
        //
        // อย่าคิดว่า HashSet จะเรียงข้อมูล
        //
        // เช่น:
        //
        // data.add(50);
        // data.add(10);
        // data.add(30);
        //
        // ตอน println()
        // อาจไม่ได้ออกมาเป็น:
        //
        // [10, 30, 50]
        //
        // และอาจไม่ได้ออกตามลำดับที่ add()
        //
        // เพราะ HashSet ไม่ได้ออกแบบมาเพื่อรักษาลำดับ
        //
        // ดังนั้นอย่าพึ่งพาลำดับของ HashSet


        HashSet<Integer> unordered =
                new HashSet<>();

        unordered.add(50);
        unordered.add(10);
        unordered.add(30);
        unordered.add(20);
        unordered.add(40);

        System.out.println(
                "\nHashSet: " + unordered
        );


        // ========================================================
        // 16. addAll()
        // ========================================================
        //
        // ใช้รวมข้อมูลจาก Collection อีกตัว
        //
        // ข้อมูลซ้ำจะถูกตัดออกโดยอัตโนมัติ


        HashSet<Integer> setA =
                new HashSet<>();

        HashSet<Integer> setB =
                new HashSet<>();

        setA.add(1);
        setA.add(2);
        setA.add(3);

        setB.add(3);
        setB.add(4);
        setB.add(5);

        setA.addAll(setB);

        System.out.println(
                "addAll(): " + setA
        );

        // Output:
        //
        // [1, 2, 3, 4, 5]


        // ========================================================
        // 17. removeAll()
        // ========================================================
        //
        // ลบสมาชิกที่มีอยู่ในอีก Set


        HashSet<Integer> removeA =
                new HashSet<>();

        HashSet<Integer> removeB =
                new HashSet<>();

        removeA.add(1);
        removeA.add(2);
        removeA.add(3);
        removeA.add(4);

        removeB.add(2);
        removeB.add(4);

        removeA.removeAll(removeB);

        System.out.println(
                "removeAll(): " + removeA
        );

        // Output:
        //
        // [1, 3]


        // ========================================================
        // 18. retainAll()
        // ========================================================
        //
        // เก็บเฉพาะสมาชิก
        // ที่มีอยู่ในอีก Set
        //
        // มองง่าย ๆ:
        //
        // "เอาเฉพาะส่วนที่เหมือนกัน"


        HashSet<Integer> retainA =
                new HashSet<>();

        HashSet<Integer> retainB =
                new HashSet<>();

        retainA.add(1);
        retainA.add(2);
        retainA.add(3);
        retainA.add(4);

        retainB.add(3);
        retainB.add(4);
        retainB.add(5);

        retainA.retainAll(retainB);

        System.out.println(
                "retainAll(): " + retainA
        );

        // Output:
        //
        // [3, 4]


        // ========================================================
        // 19. containsAll()
        // ========================================================
        //
        // ตรวจสอบว่า Set มีข้อมูล
        // ครบทุกตัวในอีก Collection หรือไม่


        HashSet<Integer> all =
                new HashSet<>();

        all.add(10);
        all.add(20);
        all.add(30);
        all.add(40);

        HashSet<Integer> check =
                new HashSet<>();

        check.add(10);
        check.add(30);

        System.out.println(
                "containsAll(): "
                + all.containsAll(check)
        );

        // true


        // ========================================================
        // 20. เปรียบเทียบ HashSet ด้วย equals()
        // ========================================================
        //
        // Set สนใจว่า "มีสมาชิกอะไรบ้าง"
        // ไม่ได้สนใจลำดับ
        //
        // ดังนั้น:
        //
        // [10, 20, 30]
        //
        // กับ
        //
        // [30, 10, 20]
        //
        // ถ้าเป็น Set จะถือว่าเท่ากัน


        HashSet<Integer> first =
                new HashSet<>();

        HashSet<Integer> second =
                new HashSet<>();

        first.add(10);
        first.add(20);
        first.add(30);

        second.add(30);
        second.add(10);
        second.add(20);

        System.out.println(
                "equals(): "
                + first.equals(second)
        );

        // true


        // ========================================================
        // 21. HashSet กับ String
        // ========================================================
        //
        // HashSet สามารถเก็บ String ได้


        HashSet<String> names =
                new HashSet<>();

        names.add("Tle");
        names.add("Java");
        names.add("Python");
        names.add("Tle");

        System.out.println(
                "\nString HashSet: " + names
        );

        // "Tle" จะมีเพียงครั้งเดียว


        // ========================================================
        // 22. HashSet กับ null
        // ========================================================
        //
        // HashSet สามารถเก็บ null ได้
        // และโดยทั่วไปเก็บ null ได้เพียงหนึ่งค่า


        HashSet<String> values =
                new HashSet<>();

        values.add("A");
        values.add(null);
        values.add(null);

        System.out.println(
                "HashSet + null: " + values
        );

        // null จะมีเพียงหนึ่งตัว


        // ========================================================
        // 23. ทำไม HashSet ถึงค้นหาเร็ว?
        // ========================================================
        /*
         *
         * HashSet ใช้แนวคิดของ Hash Table
         *
         *
         * สมมติเรามี:
         *
         * 100
         *
         * HashSet จะนำข้อมูลไปผ่านกระบวนการ Hash
         *
         *        100
         *          ↓
         *       hash()
         *          ↓
         *     ตำแหน่งที่เหมาะสม
         *
         *
         * เมื่อค้นหา 100
         * Java สามารถใช้ Hash
         * เพื่อช่วยหาตำแหน่งได้อย่างรวดเร็ว
         *
         *
         * จึงทำให้:
         *
         * contains()
         * add()
         * remove()
         *
         * โดยทั่วไปมีประสิทธิภาพประมาณ O(1)
         * ในกรณีเฉลี่ย
         *
         *
         * หมายเหตุ:
         *
         * O(1) ไม่ได้หมายความว่าเร็วที่สุดเสมอไป
         * และไม่ได้รับประกันทุกสถานการณ์
         *
         */


        // ========================================================
        // 24. HashSet เหมาะกับงานแบบไหน?
        // ========================================================
        /*
         *
         * เหมาะเมื่อ:
         *
         * 1. ต้องการข้อมูลไม่ซ้ำ
         *
         * 2. ต้องการตรวจสอบว่า
         *    "มีข้อมูลนี้อยู่หรือไม่"
         *    บ่อย ๆ
         *
         * 3. ไม่สนใจลำดับข้อมูล
         *
         *
         * ตัวอย่าง:
         *
         * - รายชื่อ Username ที่ไม่ซ้ำ
         * - ID ที่ไม่ซ้ำ
         * - Tag ของบทความ
         * - รายการคำที่ไม่ซ้ำ
         * - ตรวจสอบข้อมูลซ้ำ
         *
         */


        // ========================================================
        // 25. ตัวอย่างการกำจัดข้อมูลซ้ำ
        // ========================================================
        //
        // นี่เป็น Use Case ที่สำคัญมากของ HashSet


        HashSet<String> uniqueNames =
                new HashSet<>();

        uniqueNames.add("Alice");
        uniqueNames.add("Bob");
        uniqueNames.add("Alice");
        uniqueNames.add("Charlie");
        uniqueNames.add("Bob");

        System.out.println(
                "\nข้อมูลไม่ซ้ำ: "
                + uniqueNames
        );

        // ผล:
        //
        // Alice
        // Bob
        // Charlie
        //
        // แต่ลำดับไม่ควรนำไปใช้อ้างอิง


        // ========================================================
        // 26. สรุป ArrayList vs HashSet
        // ========================================================
        /*
         *
         * ========================================================
         * ArrayList
         * ========================================================
         *
         * - มี Index
         * - รักษาลำดับการเพิ่ม
         * - มีข้อมูลซ้ำได้
         * - ใช้ get(index)
         *
         *
         * ตัวอย่าง:
         *
         * [A, B, A, C]
         *
         *
         * ========================================================
         * HashSet
         * ========================================================
         *
         * - ไม่มี Index
         * - ไม่รับประกันลำดับ
         * - ข้อมูลซ้ำไม่ได้
         * - ใช้ contains() ตรวจสอบข้อมูล
         *
         *
         * ตัวอย่าง:
         *
         * [A, B, C]
         *
         *
         * ========================================================
         */


        // ========================================================
        // 27. Method สำคัญที่ควรจำ
        // ========================================================
        /*
         *
         * --------------------------------------------------------
         * Method             หน้าที่
         * --------------------------------------------------------
         *
         * add()               เพิ่มข้อมูล
         *
         * contains()          ตรวจสอบว่ามีข้อมูลหรือไม่
         *
         * remove()            ลบข้อมูล
         *
         * size()              จำนวนสมาชิก
         *
         * isEmpty()           ตรวจสอบว่าว่างหรือไม่
         *
         * clear()             ลบข้อมูลทั้งหมด
         *
         * addAll()            รวม Collection
         *
         * removeAll()         ลบสมาชิกที่ซ้ำกับอีก Collection
         *
         * retainAll()         เก็บเฉพาะสมาชิกที่เหมือนกัน
         *
         * containsAll()       ตรวจสอบว่ามีสมาชิกครบหรือไม่
         *
         * equals()            เปรียบเทียบ Set
         *
         * forEach()           วนข้อมูลทุกตัว
         *
         * --------------------------------------------------------
         */


        // ========================================================
        // 28. สิ่งที่ต้องจำที่สุด
        // ========================================================
        /*
         *
         * HashSet = "ไม่ซ้ำ + ไม่สนลำดับ"
         *
         *
         * ถ้าต้องการ:
         *
         * "ข้อมูลมีลำดับ และเข้าถึงด้วย Index"
         *
         * → ArrayList
         *
         *
         * ถ้าต้องการ:
         *
         * "ข้อมูลไม่ซ้ำ และไม่สนลำดับ"
         *
         * → HashSet
         *
         *
         * ========================================================
         */
    }
}