package a02array_string;

public class A4String {
    public static void main(String[] args) {
        
        // String คือ ชนิดข้อมูลที่ใช้เก็บข้อความ (text)

        // สร้าง String
        String a = "Hello";
        System.out.println(a); // Hello

        // ต่อ String (Concatenation)
        String first = "Hello";
        String last = "Java";

        String full = first + " " + last;
        System.out.println(full); // Hello Java
        
    }
}
