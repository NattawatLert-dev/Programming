package a02array_string;

public class A3Array2D {

    public static void main(String[] args) {

        // ========================================================
        // 2D Array
        // ========================================================
        // Array 2D = Array ที่มี 2 มิติ
        //
        // พูดง่าย ๆ คือ
        //
        // "Array ที่เก็บ Array อีกทีหนึ่ง"
        //
        //
        // เหมาะกับข้อมูลที่มีลักษณะเป็น "ตาราง"
        //
        // ตัวอย่าง
        //
        // - คะแนนนักเรียนหลายวิชา
        // - ตารางหมากรุก 8 x 8
        // - Matrix ทางคณิตศาสตร์
        // - ตารางที่นั่ง
        // - Sudoku
        // - Tic-Tac-Toe
        // - แผนที่ในเกม
        //
        //
        // ========================================================
        // มอง 2D Array เป็นตาราง
        // ========================================================
        //
        // ตัวอย่าง
        //
        // int[][] matrix = {
        //     {10, 20, 30},
        //     {40, 50, 60}
        // };
        //
        //
        // สามารถมองเป็น
        //
        //             Column
        //             0    1    2
        //
        // Row 0       10   20   30
        // Row 1       40   50   60
        //
        //
        // มี
        //
        // 2 Rows
        // 3 Columns
        //
        // จึงเรียกว่า
        //
        // 2 x 3
        //
        //
        // ========================================================
        // จำให้แม่น
        // ========================================================
        //
        // matrix[row][column]
        //
        //
        // ตัวแรก
        // = Row
        //
        // ตัวที่สอง
        // = Column
        //
        //
        // เช่น
        //
        // matrix[1][2]
        //
        // = Row 1
        // = Column 2
        //
        // จากตัวอย่าง
        //
        // 40  50  60
        //          ↑
        //       Column 2
        //
        // ดังนั้น
        //
        // matrix[1][2] = 60


        // ========================================================
        // 1. การสร้าง 2D Array แบบกำหนดขนาด
        // ========================================================
        // รูปแบบ
        //
        // DataType[][] name = new DataType[rows][columns];
        //
        //
        // ตัวอย่าง
        //
        // int[2][3]
        //
        // หมายถึง
        //
        // 2 Rows
        // 3 Columns


        int[][] matrix = new int[2][3];


        // ========================================================
        // 2. ใส่ข้อมูลลงใน 2D Array
        // ========================================================
        // ใช้
        //
        // matrix[row][column]
        //
        //
        // Row 0
        //
        // matrix[0][0] = 10
        // matrix[0][1] = 20
        // matrix[0][2] = 30
        //
        //
        // Row 1
        //
        // matrix[1][0] = 40
        // matrix[1][1] = 50
        // matrix[1][2] = 60


        matrix[0][0] = 10;
        matrix[0][1] = 20;
        matrix[0][2] = 30;

        matrix[1][0] = 40;
        matrix[1][1] = 50;
        matrix[1][2] = 60;


        // ========================================================
        // 3. อ่านข้อมูล
        // ========================================================
        // ตัวอย่าง
        //
        // matrix[1][1]
        //
        // = Row 1
        // = Column 1
        //
        // = 50


        System.out.println(
                matrix[1][1]
        );

        // Output:
        // 50


        // ========================================================
        // 4. สร้าง 2D Array พร้อมข้อมูล
        // ========================================================
        // ถ้ารู้ข้อมูลตั้งแต่แรก
        // สามารถกำหนดค่าได้ทันที
        //
        //
        // รูปแบบ
        //
        // int[][] matrix = {
        //     {value, value, value},
        //     {value, value, value}
        // };


        int[][] matrix1 = {
                {10, 20, 30},
                {40, 50, 60},
                {70, 80, 90}
        };


        // ตาราง
        //
        //             Column
        //             0    1    2
        //
        // Row 0       10   20   30
        // Row 1       40   50   60
        // Row 2       70   80   90


        // ========================================================
        // 5. เข้าถึงข้อมูลด้วย Index
        // ========================================================

        System.out.println(
                matrix1[0][0]
        );
        // 10

        System.out.println(
                matrix1[2][1]
        );
        // 80

        System.out.println(
                matrix1[1][2]
        );
        // 60


        // ========================================================
        // 6. แก้ไขข้อมูล
        // ========================================================
        // สามารถเปลี่ยนค่าของสมาชิกได้
        //
        //
        // matrix1[0][0]
        // จาก 10
        // เป็น 100


        matrix1[0][0] = 100;

        System.out.println(
                matrix1[0][0]
        );

        // 100


        // ========================================================
        // 7. matrix.length
        // ========================================================
        // สำหรับ 2D Array
        //
        // matrix.length
        //
        // = จำนวน Row
        //
        //
        // matrix1 มี 3 Row
        //
        // ดังนั้น
        //
        // matrix1.length = 3


        System.out.println(
                "Rows = " + matrix1.length
        );

        // Rows = 3


        // ========================================================
        // 8. matrix[row].length
        // ========================================================
        // ถ้าต้องการดูจำนวน Column
        //
        // ต้องดู length ของแต่ละ Row
        //
        //
        // matrix1[0].length
        //
        // = จำนวน Column ของ Row 0
        //
        // = 3
        //
        //
        // matrix1[1].length
        // = 3
        //
        // matrix1[2].length
        // = 3


        System.out.println(
                "Columns = " + matrix1[0].length
        );

        // Columns = 3


        // ========================================================
        // สำคัญมาก!
        // ========================================================
        //
        // 1D Array
        //
        // arr.length
        // = จำนวนสมาชิก
        //
        //
        // 2D Array
        //
        // matrix.length
        // = จำนวน Row
        //
        //
        // matrix[row].length
        // = จำนวน Column ของ Row นั้น
        //
        //
        // จำเป็นภาพ
        //
        // matrix.length
        //       ↓
        //     Rows
        //
        //
        // matrix[i].length
        //       ↓
        //    Columns


        // ========================================================
        // 9. ใช้ for Loop อ่านข้อมูล
        // ========================================================
        // เนื่องจากมี 2 มิติ
        // เราจึงต้องใช้ Loop 2 ชั้น
        //
        //
        // Loop ชั้นนอก
        // = จัดการ Row
        //
        //
        // Loop ชั้นใน
        // = จัดการ Column
        //
        //
        // รูปแบบ
        //
        // for (int i = 0; i < matrix.length; i++) {
        //
        //     for (int j = 0;
        //          j < matrix[i].length;
        //          j++) {
        //
        //         System.out.println(
        //             matrix[i][j]
        //         );
        //     }
        // }


        System.out.println();
        System.out.println("Matrix:");

        for (int i = 0; i < matrix1.length; i++) {

            for (int j = 0;
                 j < matrix1[i].length;
                 j++) {

                System.out.print(
                        matrix1[i][j] + " "
                );
            }

            // ขึ้นบรรทัดใหม่
            // เมื่อจบแต่ละ Row

            System.out.println();
        }


        // Output:
        //
        // 100 20 30
        // 40 50 60
        // 70 80 90


        // ========================================================
        // 10. ทำไมต้องมี Loop 2 ชั้น?
        // ========================================================
        //
        // เพราะเราต้องเดินทาง 2 มิติ
        //
        //
        // Loop ชั้นนอก
        //
        // Row 0
        // Row 1
        // Row 2
        //
        //
        // Loop ชั้นใน
        //
        // Column 0
        // Column 1
        // Column 2
        //
        //
        // จึงได้
        //
        // Row 0 → Column 0, 1, 2
        // Row 1 → Column 0, 1, 2
        // Row 2 → Column 0, 1, 2


        // ========================================================
        // 11. for-each กับ 2D Array
        // ========================================================
        // 2D Array จริง ๆ แล้วคือ
        //
        // Array ที่เก็บ Array
        //
        //
        // ดังนั้น
        //
        // for (int[] row : matrix1)
        //
        // จะได้ Array แต่ละ Row
        //
        //
        // จากนั้น
        //
        // for (int value : row)
        //
        // จะได้ค่าของแต่ละสมาชิก


        System.out.println();
        System.out.println("Using for-each:");

        for (int[] row : matrix1) {

            for (int value : row) {

                System.out.print(
                        value + " "
                );
            }

            System.out.println();
        }


        // Output:
        //
        // 100 20 30
        // 40 50 60
        // 70 80 90


        // ========================================================
        // 12. Jagged Array
        // ========================================================
        // Jagged Array
        // = 2D Array ที่แต่ละ Row
        //   มีจำนวน Column ไม่เท่ากัน
        //
        //
        // ไม่จำเป็นว่า 2D Array
        // จะต้องเป็นตารางสี่เหลี่ยมเสมอไป
        //
        //
        // ตัวอย่าง
        //
        // Row 0 → 2 ตัว
        // Row 1 → 3 ตัว
        // Row 2 → 1 ตัว


        int[][] jagged = {
                {1, 2},
                {3, 4, 5},
                {6}
        };


        // มองเป็น
        //
        // Row 0
        // 1  2
        //
        // Row 1
        // 3  4  5
        //
        // Row 2
        // 6


        // ========================================================
        // 13. เข้าถึง Jagged Array
        // ========================================================

        System.out.println(
                jagged[2][0]
        );

        // 6


        // ========================================================
        // 14. Jagged Array กับ length
        // ========================================================
        //
        // jagged.length
        // = 3
        //
        // เพราะมี 3 Row
        //
        //
        // jagged[0].length
        // = 2
        //
        // jagged[1].length
        // = 3
        //
        // jagged[2].length
        // = 1
        //
        //
        // ดังนั้นเวลาใช้ Loop
        // ต้องใช้
        //
        // jagged[i].length
        //
        // ไม่ใช่ใช้จำนวน Column เดียวกันทุก Row


        System.out.println(
                "Jagged rows = "
                + jagged.length
        );

        for (int i = 0;
             i < jagged.length;
             i++) {

            System.out.println(
                    "Row " + i
                    + " has "
                    + jagged[i].length
                    + " columns"
            );
        }


        // ========================================================
        // 15. Loop Jagged Array
        // ========================================================
        // เนื่องจากแต่ละ Row
        // ยาวไม่เท่ากัน
        //
        // เราจึงต้องใช้
        //
        // jagged[i].length
        //
        // เพื่อให้แต่ละ Row
        // ตรวจสอบขนาดของตัวเอง


        System.out.println();
        System.out.println("Jagged Array:");

        for (int i = 0;
             i < jagged.length;
             i++) {

            for (int j = 0;
                 j < jagged[i].length;
                 j++) {

                System.out.print(
                        jagged[i][j] + " "
                );
            }

            System.out.println();
        }


        // Output:
        //
        // 1 2
        // 3 4 5
        // 6


        // ========================================================
        // 16. สร้าง Jagged Array แบบกำหนดขนาด
        // ========================================================
        // สามารถสร้างโดยกำหนดจำนวน Row ก่อน
        //
        // แล้วกำหนดจำนวน Column
        // ของแต่ละ Row แยกกันได้
        //
        //
        // ตัวอย่าง
        //
        // int[][] data = new int[3][];
        //
        // หมายถึง
        //
        // มี 3 Row
        // แต่ยังไม่กำหนดจำนวน Column
        //
        //
        // จากนั้นกำหนดทีละ Row


        int[][] data = new int[3][];

        data[0] = new int[2];
        data[1] = new int[4];
        data[2] = new int[1];


        // จะได้
        //
        // Row 0 → 2 ช่อง
        // Row 1 → 4 ช่อง
        // Row 2 → 1 ช่อง


        // ========================================================
        // 17. ค่าเริ่มต้นของ 2D Array
        // ========================================================
        // เช่น
        //
        // int[][] numbers = new int[2][3];
        //
        // ทุกช่องจะเริ่มต้นเป็น 0
        //
        //
        // เพราะ int มี Default Value = 0


        int[][] numbers = new int[2][3];

        System.out.println();
        System.out.println(
                "Default 2D Array:"
        );

        for (int[] row : numbers) {

            for (int value : row) {

                System.out.print(
                        value + " "
                );
            }

            System.out.println();
        }


        // Output:
        //
        // 0 0 0
        // 0 0 0


        // ========================================================
        // 18. Error ที่ต้องระวัง
        // ========================================================
        // ถ้าเข้าถึง Index ที่ไม่มี
        // จะเกิด
        //
        // ArrayIndexOutOfBoundsException
        //
        //
        // เช่น
        //
        // matrix1 มี 3 Row
        //
        // Index Row ที่ใช้ได้คือ
        //
        // 0, 1, 2
        //
        //
        // ดังนั้น
        //
        // matrix1[3][0]
        //
        // ❌ ผิด
        //
        //
        // เพราะ Row 3 ไม่มี
        //
        //
        // และ
        //
        // matrix1[0][3]
        //
        // ❌ ผิด
        //
        //
        // เพราะ Column 3 ไม่มี
        //
        //
        // จำว่า
        //
        // Index สูงสุด
        // = length - 1


        // ========================================================
        // 19. เปรียบเทียบ 1D กับ 2D Array
        // ========================================================
        /*
         *
         * ========================================================
         * 1D Array
         * ========================================================
         *
         * int[] arr = {
         *     10, 20, 30
         * };
         *
         *
         * เข้าถึง
         *
         * arr[0]
         *
         *
         * length
         *
         * arr.length
         *
         *
         * ========================================================
         * 2D Array
         * ========================================================
         *
         * int[][] matrix = {
         *     {10, 20},
         *     {30, 40}
         * };
         *
         *
         * เข้าถึง
         *
         * matrix[row][column]
         *
         *
         * จำนวน Row
         *
         * matrix.length
         *
         *
         * จำนวน Column
         *
         * matrix[row].length
         *
         *
         * ========================================================
         */


        // ========================================================
        // 20. สรุป
        // ========================================================
        /*
         * ========================================================
         * 2D ARRAY
         * ========================================================
         *
         * 2D Array
         * = Array ที่เก็บ Array
         *
         *
         * เหมาะกับข้อมูลแบบตาราง
         *
         *
         * ========================================================
         *
         * การสร้าง
         * ========================================================
         *
         * int[][] matrix = new int[2][3];
         *
         *
         * 2
         * = จำนวน Row
         *
         * 3
         * = จำนวน Column
         *
         *
         * ========================================================
         *
         * การเข้าถึง
         * ========================================================
         *
         * matrix[row][column]
         *
         *
         * ========================================================
         *
         * จำนวน Row
         * ========================================================
         *
         * matrix.length
         *
         *
         * ========================================================
         *
         * จำนวน Column
         * ========================================================
         *
         * matrix[row].length
         *
         *
         * ========================================================
         *
         * Loop
         * ========================================================
         *
         * for (int i = 0;
         *      i < matrix.length;
         *      i++) {
         *
         *     for (int j = 0;
         *          j < matrix[i].length;
         *          j++) {
         *
         *         System.out.println(
         *             matrix[i][j]
         *         );
         *     }
         * }
         *
         *
         * ========================================================
         *
         * for-each
         * ========================================================
         *
         * for (int[] row : matrix) {
         *
         *     for (int value : row) {
         *
         *         System.out.println(value);
         *     }
         * }
         *
         *
         * ========================================================
         *
         * Jagged Array
         * ========================================================
         *
         * แต่ละ Row
         * มีจำนวน Column ไม่เท่ากัน
         *
         *
         * int[][] jagged = {
         *     {1, 2},
         *     {3, 4, 5},
         *     {6}
         * };
         *
         *
         * ========================================================
         * สิ่งที่ต้องจำ
         * ========================================================
         *
         * matrix.length
         *     = จำนวน Row
         *
         *
         * matrix[i].length
         *     = จำนวน Column ของ Row i
         *
         *
         * matrix[i][j]
         *     = สมาชิกตำแหน่ง Row i
         *       และ Column j
         *
         *
         * Index เริ่มจาก 0
         *
         *
         * Index สูงสุด
         *     = length - 1
         *
         */
    }
}