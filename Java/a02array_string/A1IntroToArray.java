package a02array_string;

public class A1IntroToArray {

    public static void main(String[] args) {

        // ========================================================
        // Array
        // ========================================================
        // Array = โครงสร้างข้อมูล (Data Structure) ที่ใช้เก็บข้อมูลหลายค่า
        //
        // จุดสำคัญของ Array
        //
        // 1. เก็บข้อมูลได้หลายค่า
        // 2. สมาชิกใน Array ต้องเป็น Data Type เดียวกัน
        // 3. สมาชิกแต่ละตัวมี Index
        // 4. Index เริ่มต้นที่ 0
        // 5. ขนาดของ Array ถูกกำหนดตอนสร้าง
        //    และไม่สามารถเพิ่ม/ลดขนาดได้โดยตรง
        //
        // ตัวอย่าง
        //
        // int[] arr = {10, 20, 30, 40};
        //
        // Index
        //
        //    0    1    2    3
        //    ↓    ↓    ↓    ↓
        //  ┌────┬────┬────┬────┐
        //  │ 10 │ 20 │ 30 │ 40 │
        //  └────┴────┴────┴────┘
        //
        // จำให้แม่น!
        //
        // จำนวนสมาชิก = 4
        //
        // แต่ Index สูงสุด = 3
        //
        // เพราะ Index เริ่มจาก 0
        //
        // ========================================================
        // จำนวนสมาชิก กับ Index ไม่เหมือนกัน
        // ========================================================
        //
        // Array 4 ตัว
        //
        // length = 4
        //
        // Index:
        //
        // 0, 1, 2, 3
        //
        // Index สูงสุด = length - 1
        //
        // = 4 - 1
        // = 3


        // ========================================================
        // 1. การสร้าง Array แบบกำหนดขนาด
        // ========================================================
        // รูปแบบ
        //
        // DataType[] ชื่อตัวแปร = new DataType[ขนาด];
        //
        // ตัวอย่าง
        //
        // int[] arr = new int[4];
        //
        // หมายถึง
        //
        // สร้าง Array ชื่อ arr
        // สามารถเก็บ int ได้ 4 ตัว
        //
        // ตอนสร้างใหม่
        //
        // int[] arr = new int[4];
        //
        // Java จะกำหนดค่าเริ่มต้นให้อัตโนมัติ
        //
        // int -> 0
        //
        // double -> 0.0
        //
        // boolean -> false
        //
        // Object / String -> null


        int[] arr = new int[4];


        // ========================================================
        // 2. ใส่ข้อมูลลงใน Array
        // ========================================================
        // ใช้ Index ในการกำหนดค่า
        //
        // arr[0] = 10;
        //
        // หมายถึง
        //
        // สมาชิกตำแหน่งที่ 0
        // มีค่าเป็น 10


        arr[0] = 10;
        arr[1] = 20;
        arr[2] = 30;
        arr[3] = 40;


        // ตอนนี้ Array เป็น
        //
        // Index
        //   0    1    2    3
        //
        //  10   20   30   40


        // ========================================================
        // 3. อ่านข้อมูลจาก Array
        // ========================================================
        // ใช้
        // arr[index]
        //
        //
        // ตัวอย่าง
        //
        // arr[0] -> 10
        //
        // arr[2] -> 30

        System.out.println(arr[0]); // 10

        System.out.println(arr[2]); // 30


        // ========================================================
        // 4. เปลี่ยนค่าใน Array
        // ========================================================
        // เราสามารถเปลี่ยนค่าของสมาชิกได้
        //
        // ตัวอย่าง
        //
        // arr[0] = 100;
        //
        // ค่าเดิม
        //
        // 10
        //
        // จะถูกเปลี่ยนเป็น
        //
        // 100


        arr[0] = 100;

        System.out.println(arr[0]); // 100


        // ========================================================
        // 5. การสร้าง Array แบบกำหนดค่าเลย
        // ========================================================
        // ถ้าเรารู้ข้อมูลอยู่แล้ว
        // สามารถสร้าง Array พร้อมข้อมูลได้เลย
        //
        //
        // รูปแบบ
        //
        // DataType[] name = {value1, value2, value3};
        //
        // ตัวอย่าง


        String[] fruits = {"Apple", "Banana", "Orange"};


        // Array จะเป็น
        //
        // Index
        //   0          1          2
        //
        // Apple     Banana     Orange


        // ========================================================
        // 6. เข้าถึงสมาชิกของ Array
        // ========================================================
        // ใช้ Index
        //
        // fruits[0] -> Apple
        //
        // fruits[1] -> Banana
        //
        // fruits[2] -> Orange


        System.out.println(fruits[2]); // Orange


        // ========================================================
        // 7. length
        // ========================================================
        // length = จำนวนสมาชิกใน Array
        //
        //
        // fruits มี
        //
        // Apple
        // Banana
        // Orange
        //
        // รวม 3 ตัว
        //
        //
        // ดังนั้น
        //
        // fruits.length = 3


        System.out.println("Number of fruits = " + fruits.length); // 3


        // ========================================================
        // ⚠️ length ไม่ใช่ Index
        // ========================================================
        //
        // fruits.length = 3
        //
        //
        // แต่ Index คือ
        //
        // 0
        // 1
        // 2
        //
        //
        // ดังนั้นสมาชิกตัวสุดท้ายคือ
        //
        // fruits[fruits.length - 1]
        //
        // = fruits[2]
        //
        // = Orange


        System.out.println(fruits[fruits.length - 1]); // Orange


        // ========================================================
        // 8. for Loop กับ Array
        // ========================================================
        // เราสามารถใช้ for Loop เพื่อเข้าถึงสมาชิกทุกตัว
        //
        //
        // รูปแบบที่นิยม
        //
        // for (int i = 0; i < arr.length; i++) {
        //
        //     System.out.println(arr[i]);
        //
        // }
        //
        //
        // ทำไมต้อง
        //
        // i < arr.length
        //
        // ?
        //
        //
        // เพราะถ้า Array มี 4 ตัว
        //
        // length = 4
        //
        // Index ที่ใช้ได้คือ
        //
        // 0, 1, 2, 3
        //
        // ดังนั้นต้องใช้
        //
        // i < 4
        //
        // ไม่ใช่
        //
        // i <= 4
        //
        //
        // เพราะ i = 4 ไม่มีอยู่จริง


        System.out.println();
        System.out.println("Array arr:");

        for (int i = 0; i < arr.length; i++) {

            System.out.println( "Index " + i + " = " + arr[i]);
        }


        // ผลลัพธ์
        //
        // Index 0 = 100
        // Index 1 = 20
        // Index 2 = 30
        // Index 3 = 40


        // ========================================================
        // 9. Enhanced for loop / for-each
        // ========================================================
        // ถ้าเราไม่สนใจ Index และต้องการเพียงค่าของสมาชิก
        //
        // สามารถใช้ for-each
        //
        //
        // รูปแบบ
        //
        // for (DataType variable : array) {
        //
        //     // ใช้ variable
        //
        // }
        //
        //
        // อ่านว่า
        //
        // "นำสมาชิกแต่ละตัวใน Array มาเก็บไว้ใน variable"


        System.out.println();
        System.out.println("Fruits:");

        for (String item : fruits) {

            System.out.println(item);
        }


        // ผลลัพธ์
        //
        // Apple
        // Banana
        // Orange


        // ========================================================
        // 10. for กับ for-each ต่างกันอย่างไร?
        // ========================================================
        /*
         * ========================================================
         * for
         * ========================================================
         *
         * for (int i = 0; i < arr.length; i++) {
         *
         *     System.out.println(arr[i]);
         *
         * }
         *
         *
         * ข้อดี
         *
         * - รู้ Index
         * - เปลี่ยนค่าเฉพาะตำแหน่งได้
         * - สามารถเริ่มจาก Index ที่ต้องการได้
         * - สามารถวิ่งย้อนกลับได้
         *
         *
         * ========================================================
         * for-each
         * ========================================================
         *
         * for (String item : fruits) {
         *
         *     System.out.println(item);
         *
         * }
         *
         *
         * ข้อดี
         *
         * - เขียนง่าย
         * - อ่านง่าย
         * - เหมาะกับการอ่านข้อมูลทุกตัว
         *
         *
         * ข้อจำกัด
         *
         * - ไม่ได้ Index โดยตรง
         *
         * ========================================================
         */


        // ========================================================
        // 11. ค่าเริ่มต้นของ Array
        // ========================================================
        // ถ้าเราสร้าง Array แต่ยังไม่ได้ใส่ค่า Java จะกำหนดค่าเริ่มต้นให้
        //
        //
        // int[] numbers = new int[3];
        //
        // จะได้
        //
        // 0
        // 0
        // 0


        int[] numbers = new int[3];

        System.out.println();
        System.out.println("Default values:");

        for (int number : numbers) {

            System.out.println(number);
        }


        // ========================================================
        // 12. Array ของ double
        // ========================================================
        // ค่าเริ่มต้นของ double คือ 0.0


        double[] prices = new double[3];

        System.out.println();
        System.out.println("Double array:");

        for (double price : prices) {

            System.out.println(price);
        }


        // ========================================================
        // 13. Array ของ boolean
        // ========================================================
        // ค่าเริ่มต้นของ boolean คือ false


        boolean[] status = new boolean[3];

        System.out.println();
        System.out.println("Boolean array:");

        for (boolean value : status) {

            System.out.println(value);
        }


        // ========================================================
        // 14. Array ของ String
        // ========================================================
        // String เป็น Reference Type
        //
        // ค่าเริ่มต้นของ Array String
        // คือ null


        String[] names = new String[3];

        System.out.println();
        System.out.println("String array:");

        for (String name : names) {

            System.out.println(name);
        }


        // ========================================================
        // 15. Array ไม่สามารถเพิ่มขนาดโดยตรง
        // ========================================================
        // เมื่อสร้าง
        //
        // int[] arr = new int[4];
        //
        // ขนาดจะเป็น 4
        //
        // ไม่สามารถทำ
        //
        // arr.length = 5;
        //
        // ได้
        //
        //
        // ถ้าต้องการโครงสร้างข้อมูล ที่สามารถเพิ่ม/ลดขนาดได้
        //
        //
        // ArrayList
        //
        //
        // Array = ขนาดคงที่
        //
        // ArrayList = ขนาดยืดหยุ่น


        // ========================================================
        // 16. Array หลายมิติ
        // ========================================================
        // Array สามารถมีหลายมิติได้
        //
        // เช่น 2D Array
        //
        // int[][] matrix
        //
        //
        // มองง่าย ๆ เหมือนตาราง
        //
        //        Column
        //        0   1   2
        //
        // Row 0  1   2   3
        // Row 1  4   5   6
        //
        //
        // การเข้าถึง
        //
        // matrix[row][column]


        int[][] matrix = {
                {1, 2, 3},
                {4, 5, 6}
        };


        System.out.println();
        System.out.println("matrix[1][2] = " + matrix[1][2]); // 6


        // ========================================================
        // 17. Nested Loop กับ 2D Array
        // ========================================================
        // ถ้าต้องการอ่านข้อมูลทั้งหมด
        // ใน 2D Array
        // มักใช้ Loop ซ้อน Loop


        System.out.println();
        System.out.println("2D Array:");

        for (int row = 0; row < matrix.length; row++) {

            for (int column = 0;column < matrix[row].length;column++) {
                
                System.out.print(matrix[row][column] + " ");
            }

            System.out.println();
        }


        // ผลลัพธ์
        //
        // 1 2 3
        // 4 5 6


        // ========================================================
        // 18. ArrayIndexOutOfBoundsException
        // ========================================================
        // ถ้าเราเข้าถึง Index ที่ไม่มีอยู่ Java จะเกิด Error
        //
        //
        // ตัวอย่าง
        //
        // fruits มี 3 ตัว
        //
        // Index:
        //
        // 0
        // 1
        // 2
        //
        //
        // ดังนั้น
        //
        // fruits[3]
        //
        // ❌ ผิด
        //
        //
        // เพราะ Index 3 ไม่มี
        //
        //
        // จะเกิด
        //
        // ArrayIndexOutOfBoundsException
        //
        //
        // ดังนั้นจำว่า
        //
        // Index สูงสุด = length - 1

    }
}
