package a02array_string;

/*
 * ============================================================
 * A5MethodsOfString
 * ============================================================
 *
 * String Methods = เมธอดที่ใช้จัดการและตรวจสอบข้อความ (String)
 *
 * String เป็น Reference Type และเป็น Class
 * ดังนั้นเราสามารถเรียก Method ผ่านตัวแปร String ได้
 *
 * ตัวอย่าง:
 *
 * String name = "Nattawat";
 *
 * name.length();
 * name.toUpperCase();
 * name.equals("Nattawat");
 *
 * ============================================================
 */

public class A5MethodsOfString {

    public static void main(String[] args) {


        // ========================================================
        // 1. length()
        // ========================================================
        //
        // ใช้หาความยาวของ String
        //
        // นับจำนวนตัวอักษร
        //
        // "abc"
        //
        // a b c
        // 0 1 2
        //
        // มีทั้งหมด 3 ตัว


        String a = "abc";

        System.out.println(a.length()); // 3


        // ========================================================
        // 2. isEmpty()
        // ========================================================
        //
        // ตรวจสอบว่า String มีความยาวเป็น 0 หรือไม่
        //
        // "" → true
        //
        // "Hello" → false
        //
        // ระวัง!
        //
        // "   "
        //
        // ไม่ถือว่า Empty
        // เพราะยังมีช่องว่างอยู่


        System.out.println("".isEmpty()); // true

        System.out.println("Hello".isEmpty()); // false

        System.out.println("   ".isEmpty()); // false


        // ========================================================
        // 3. isBlank()
        // ========================================================
        //
        // ใช้ตรวจสอบว่า String
        // ว่าง หรือมีแต่ whitespace หรือไม่
        //
        // Java 11+
        //
        // ""       → true
        // "   "    → true
        // "Hello"  → false


        System.out.println("   ".isBlank()); // true

        System.out.println("Hello".isBlank()); // false


        // ========================================================
        // 4. charAt(int index)
        // ========================================================
        //
        // ใช้เอาตัวอักษรตามตำแหน่ง Index
        //
        //
        // String:
        //
        // H e l l o
        // 0 1 2 3 4
        //
        //
        // charAt(0) → H
        // charAt(1) → e
        // charAt(4) → o


        String word = "Hello";

        System.out.println(word.charAt(1)); // e


        // ========================================================
        // 5. equals(String)
        // ========================================================
        //
        // ใช้เปรียบเทียบ "เนื้อหา" ของ String
        //
        // Case-sensitive
        //
        // หมายถึงตัวพิมพ์เล็ก/ใหญ่มีผล
        //
        //
        // "Java" กับ "Java" → true
        //
        // "Java" กับ "java" → false


        String name1 = "Tle";
        String name2 = "Tle";

        System.out.println(name1.equals(name2)); // true


        System.out.println("Java".equals("java")); // false


        // ========================================================
        // 6. equalsIgnoreCase(String)
        // ========================================================
        //
        // เปรียบเทียบ String โดยไม่สนใจตัวพิมพ์เล็ก/ใหญ่
        //
        //
        // "Java"
        // "JAVA"
        // "java"
        //
        // ถือว่าเท่ากัน


        System.out.println("a".equalsIgnoreCase("A")); // true


        System.out.println("Java".equalsIgnoreCase("JAVA")); // true


        // ========================================================
        // 7. contains()
        // ========================================================
        //
        // ตรวจสอบว่า String มีข้อความที่ต้องการอยู่หรือไม่
        //
        // ผลลัพธ์:
        //
        // true / false


        String w = "Hello";

        System.out.println(w.contains("ell")); // true


        System.out.println(w.contains("Java")); // false


        // ========================================================
        // 8. indexOf()
        // ========================================================
        //
        // ใช้ค้นหาตำแหน่งของข้อความ
        //
        // ถ้าพบ → คืนค่า Index
        //
        // ถ้าไม่พบ → คืนค่า -1


        String name3 = "Natt";

        System.out.println(name3.indexOf("at")); // 1


        System.out.println(name3.indexOf("Java")); // -1


        // ========================================================
        // 9. startsWith()
        // ========================================================
        //
        // ตรวจสอบว่า String เริ่มต้นด้วยข้อความที่กำหนดหรือไม่
        //
        //
        // startsWith() W ต้องเป็นตัวใหญ่
        //
        //
        // "Mr.Tle" เริ่มต้นด้วย "Mr" → true


        String name4 = "Mr.Tle";

        if (name4.startsWith("Mr")) {
            System.out.println("Man");
        }

        // Output:
        // Man


        // ========================================================
        // 10. endsWith()
        // ========================================================
        //
        // ตรวจสอบว่า String ลงท้ายด้วยข้อความที่กำหนดหรือไม่


        String name5 = "Mr.Tle";

        if (name5.endsWith("Tle")) {
            System.out.println("This is a name");
        }

        // Output:
        // This is a name


        // ========================================================
        // 11. replace()
        // ========================================================
        //
        // ใช้แทนที่ข้อความ
        //
        // replace() สามารถแทนที่ทุกส่วนที่ตรงกัน
        //
        //
        // String เดิม:
        //
        // August 2025
        //
        // แทน 2025 ด้วย 2026


        String date = "August 2025";

        System.out.println(date.replace("2025", "2026")); // August 2026


        // --------------------------------------------------------
        // replaceFirst()
        // --------------------------------------------------------
        //
        // เปลี่ยนเฉพาะส่วนแรกที่ตรงกับ Regular Expression
        //
        // ไม่ได้หมายความว่า
        // "ถ้ามีตัวซ้ำเยอะ ให้เปลี่ยนตัวแรก"
        // แบบตรง ๆ เสมอไป
        //
        // เพราะ replaceFirst() ใช้ Regex
        //
        // ตัวอย่างง่าย:


        String numbers = "100 100 100";

        System.out.println(
                numbers.replaceFirst("100", "200")
        );

        // Output:
        // 200 100 100


        // ========================================================
        // 12. trim()
        // ========================================================
        //
        // ลบ whitespace
        // ด้านหน้าและด้านหลัง
        //
        // ไม่ได้ลบช่องว่างตรงกลาง


        String h = "   Hi   ";

        System.out.println(
                h.trim()
        );

        // Output:
        // Hi


        // ========================================================
        // 13. split()
        // ========================================================
        //
        // ใช้แบ่ง String ออกเป็นส่วน ๆ
        //
        // ผลลัพธ์จะเป็น Array
        //
        //
        // ตัวอย่าง:
        //
        // "Apple Banana"
        //
        // split(" ")
        //
        // ↓
        //
        // ["Apple", "Banana"]


        String fruits = "Apple Banana";

        String[] data = fruits.split(" ");

        System.out.println(data[0]);
        System.out.println(data[1]);

        // Output:
        //
        // Apple
        // Banana


        // ========================================================
        // 14. substring()
        // ========================================================
        //
        // ใช้ตัดเอาข้อความบางส่วน
        //
        // substring(start, end)
        //
        // start = ตำแหน่งเริ่มต้น
        // end   = ตำแหน่งสิ้นสุด
        //
        // สำคัญ:
        //
        // end "ไม่ถูกรวม"


        String name = "Nattawat";

        System.out.println(name.substring(0, 4)); // Natt


        // N a t t a w a t
        // 0 1 2 3 4 5 6 7
        //
        // substring(0, 4)
        //
        // เอา Index
        // 0, 1, 2, 3
        //
        // ไม่เอา Index 4


        // ========================================================
        // 15. toCharArray()
        // ========================================================
        //
        // แปลง String → char[]
        //
        //
        // "Nattawat"
        //
        // ↓
        //
        // ['N', 'a', 't', 't', 'a', 'w', 'a', 't']


        char[] alphabet = name.toCharArray();

        System.out.println(alphabet[0]); // N

        System.out.println(alphabet[1]); // a


        // สามารถใช้ Loop
        // อ่านตัวอักษรทีละตัวได้


        for (char c : alphabet) {
            System.out.println(c);
        }

        // Output:
        //
        // N
        // a
        // t
        // t
        // a
        // w
        // a
        // t


        // ========================================================
        // 16. String.copyValueOf()
        // ========================================================
        //
        // แปลง char[] → String
        //
        //
        // char[]:
        //
        // {'T', 'l', 'E'}
        //
        // ↓
        //
        // "TlE"


        char[] alphabet1 = {'T', 'l', 'E'};

        String name6 = String.copyValueOf(alphabet1);

        System.out.println(name6);

        // Output:
        // TlE


        // --------------------------------------------------------
        // หมายเหตุ
        // --------------------------------------------------------
        //
        // ในชีวิตจริงมักเห็นการเขียนแบบนี้ด้วย:
        //
        // String name = new String(charArray);
        //
        // หรือ
        //
        // String.valueOf(charArray)
        //
        // แต่ copyValueOf() ก็สามารถใช้งานได้


        // ========================================================
        // 17. toLowerCase()
        // ========================================================
        //
        // เปลี่ยน String ให้เป็นตัวพิมพ์เล็ก


        System.out.println("NATTAWAT".toLowerCase()); // nattawat


        // ========================================================
        // 18. toUpperCase()
        // ========================================================
        //
        // เปลี่ยน String
        // ให้เป็นตัวพิมพ์ใหญ่


        System.out.println("nattawat".toUpperCase()); // NATTAWAT


        // ========================================================
        // 19. String.valueOf()
        // ========================================================
        //
        // ใช้แปลงค่าประเภทต่าง ๆ
        // ให้กลายเป็น String
        //
        //
        // int → String
        // double → String
        // boolean → String
        // char → String


        int num = 100;

        String strNum = String.valueOf(num);

        System.out.println(strNum);

        // Output:
        // 100


        // ตอนนี้ strNum เป็น String
        //
        // ไม่ใช่ int


        System.out.println(strNum.getClass().getSimpleName());

        // Output:
        // String


        // ========================================================
        // 20. parseInt()
        // ========================================================
        //
        // แปลง String → int
        //
        //
        // "123"
        //   ↓
        //  123
        //
        // ต้องใช้ Integer.parseInt()


        String str = "123";

        int m = Integer.parseInt(str);

        System.out.println(m); // 123


        // ตอนนี้ m เป็น int
        //
        // ดังนั้นสามารถนำไปคำนวณได้


        System.out.println(m + 10); // 133


        // ========================================================
        // 21. parseDouble()
        // ========================================================
        //
        // String → double


        String priceText = "99.99";

        double price = Double.parseDouble(priceText);

        System.out.println(price + 10); // 109.99


        // ========================================================
        // 22. parseBoolean()
        // ========================================================
        //
        // String → boolean
        //
        // "true" → true
        // "false" → false


        String status = "true";

        boolean isOnline =Boolean.parseBoolean(status);

        System.out.println(isOnline); // true


        // ========================================================
        // 23. การแปลงข้อมูลที่ควรรู้
        // ========================================================
        /*
         *
         * --------------------------------------------------------
         * จาก String → ตัวเลข
         * --------------------------------------------------------
         *
         * String → int
         *
         * Integer.parseInt()
         *
         *
         * String → double
         *
         * Double.parseDouble()
         *
         *
         * String → long
         *
         * Long.parseLong()
         *
         *
         * String → float
         *
         * Float.parseFloat()
         *
         *
         * --------------------------------------------------------
         * จากตัวเลข → String
         * --------------------------------------------------------
         *
         * String.valueOf()
         *
         *
         * ตัวอย่าง:
         *
         * int number = 100;
         *
         * String text = String.valueOf(number);
         *
         *
         * --------------------------------------------------------
         */


        // ========================================================
        // 24. String กับ null
        // ========================================================
        //
        // String สามารถเก็บ null ได้
        //
        // null หมายถึง
        // ไม่มี Object String อยู่
        //
        //
        // ต้องระวังเวลาสั่ง Method
        //
        // เช่น:


        String value = null;

        // ถ้าเขียน
        //
        // value.length();
        //
        // จะเกิด NullPointerException
        //
        // เพราะ value ไม่มี String Object


        if (value != null) {
            System.out.println(value.length());
        }


        // ========================================================
        // 25. String ไม่เปลี่ยนค่าเดิม (Immutable)
        // ========================================================
        //
        // String ใน Java เป็น Immutable
        //
        // หมายความว่าเมื่อสร้าง String แล้ว
        // เราไม่สามารถแก้ข้อความใน Object เดิมได้
        //
        //
        // ตัวอย่าง:


        String original = "hello";

        original.toUpperCase();

        System.out.println(original);

        // Output:
        // hello
        //
        //
        // เพราะ toUpperCase()
        // สร้าง String ใหม่
        //
        // ถ้าต้องการเก็บผลลัพธ์
        // ต้องรับค่ากลับ


        original = original.toUpperCase();

        System.out.println(original);

        // Output:
        // HELLO


        // ========================================================
        // 26. Method ที่ควรจำ
        // ========================================================
        /*
         *
         * ========================================================
         * ตรวจสอบ / อ่านข้อมูล
         * ========================================================
         *
         * length()
         *     → ความยาว
         *
         * charAt()
         *     → ตัวอักษรตาม Index
         *
         * isEmpty()
         *     → ว่างจริง ๆ หรือไม่
         *
         * isBlank()
         *     → ว่างหรือมีแต่ whitespace
         *
         *
         * ========================================================
         * เปรียบเทียบ
         * ========================================================
         *
         * equals() → เทียบข้อความแบบสนใจตัวใหญ่/เล็ก
         *
         * equalsIgnoreCase() → เทียบข้อความโดยไม่สนตัวใหญ่/เล็ก
         *
         *
         * ========================================================
         * ค้นหา
         * ========================================================
         *
         * contains() → มีข้อความนี้อยู่หรือไม่
         *
         * indexOf() → หาตำแหน่ง
         *
         * startsWith() → เริ่มต้นด้วยอะไร
         *
         * endsWith() → ลงท้ายด้วยอะไร
         *
         *
         * ========================================================
         * แก้ไข / จัดการข้อความ
         * ========================================================
         *
         * replace() → แทนที่ข้อความ
         *
         * replaceFirst() → แทนที่ครั้งแรกที่ตรงกับ Regex
         *
         * trim() → ตัด whitespace หน้า/หลัง
         *
         * substring() → ตัดข้อความบางส่วน
         *
         * toLowerCase() → ตัวพิมพ์เล็ก
         *
         * toUpperCase() → ตัวพิมพ์ใหญ่
         *
         *
         * ========================================================
         * แปลงข้อมูล
         * ========================================================
         *
         * split() → String → String[]
         *
         * toCharArray() → String → char[]
         *
         * String.valueOf() → ข้อมูล → String
         *
         * Integer.parseInt() → String → int
         *
         * Double.parseDouble() → String → double
         *
         *
         * ========================================================
         */


        // ========================================================
        // 27. จำเรื่อง Index ให้แม่น
        // ========================================================
        //
        // String:
        //
        // N a t t a w a t
        // 0 1 2 3 4 5 6 7
        //
        //
        // length()
        // → 8
        //
        //
        // charAt(0)
        // → N
        //
        //
        // charAt(7)
        // → t
        //
        //
        // charAt(8)
        // → Error!
        //
        // เพราะ Index สูงสุดคือ 7
        //
        //
        // หลักจำง่าย:
        //
        // Index เริ่มที่ 0
        //
        // Index สูงสุด
        // = length() - 1
        //
        //
        // ========================================================
    }
}