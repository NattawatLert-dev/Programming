package a02array_string;

import java.util.Arrays;

public class A2MethodsOfArrays {

    public static void main(String[] args) {

        // ========================================================
        // Methods of Arrays
        // ========================================================
        // Array ใน Java ไม่มี Method เช่น
        //
        // numbers.toString()
        // numbers.sort()
        //
        // แบบที่ String มี Method ของตัวเอง
        //
        //
        // Java จึงมี Class ชื่อ
        //
        // Arrays
        //
        // อยู่ใน package
        //
        // java.util
        //
        //
        // ดังนั้นต้อง import ก่อน
        //
        // import java.util.Arrays;
        //
        //
        // จำง่าย ๆ
        //
        // Array
        //     ↓
        // Arrays
        //     ↓
        // ใช้ Method ช่วยจัดการ Array
        //
        //
        // ========================================================
        // Method สำคัญที่ควรรู้
        // ========================================================
        //
        // Arrays.toString()
        // Arrays.sort()
        // Arrays.binarySearch()
        // Arrays.equals()
        // Arrays.fill()
        // Arrays.copyOf()
        // Arrays.copyOfRange()
        // Arrays.stream()
        // Arrays.deepToString()
        // Arrays.deepEquals()


        // ========================================================
        // 1. Arrays.toString()
        // ========================================================
        // ใช้แปลง Array เป็น String เพื่อให้แสดงผลออกมาดูง่าย
        //
        // ถ้าเขียน
        //
        // System.out.println(numbers1);
        //
        // จะไม่ได้ผลลัพธ์แบบ
        //
        // [10, 20, 30]
        //
        // ดังนั้นใช้
        //
        // Arrays.toString(numbers1)


        int[] numbers1 = {10, 20, 30};

        System.out.println(Arrays.toString(numbers1)); // [10, 20, 30]


        // ========================================================
        // 2. Arrays.sort()
        // ========================================================
        // ใช้เรียงข้อมูลจาก "น้อย → มาก"
        //
        // ⚠️ sort() จะเปลี่ยน Array เดิม
        //
        // ไม่ได้สร้าง Array ใหม่


        int[] numbers2 = {40, 10, 30, 20};

        System.out.println("Before sort: " + Arrays.toString(numbers2)); // Before sort: [40, 10, 30, 20]

        Arrays.sort(numbers2);

        System.out.println("After sort:  " + Arrays.toString(numbers2)); // After sort:  [10, 20, 30, 40]


        // ========================================================
        // 3. Arrays.binarySearch()
        // ========================================================
        // ใช้ค้นหาข้อมูลใน Array ด้วย Binary Search
        //
        //
        // ⚠️ สำคัญมาก
        //
        // Array ต้องเรียงลำดับก่อน
        //
        // จึงควรใช้
        //
        // Arrays.sort()
        //
        // ก่อน binarySearch()
        //
        // binarySearch() จะคืนค่าเป็น "Index"
        //
        // ถ้าพบ -> คืน Index
        //
        // ถ้าไม่พบ -> คืนค่าติดลบ


        int[] numbers3 = {40, 10, 30, 20};

        Arrays.sort(numbers3);

        int index = Arrays.binarySearch(numbers3,30);

        System.out.println("Index of 30 = " + index);

        // Array หลัง sort:
        //
        // [10, 20, 30, 40]
        //
        // Index:
        //   0   1   2   3
        //
        // 30 อยู่ Index 2
        //
        // Output:
        // Index of 30 = 2


        // ========================================================
        // binarySearch() เมื่อหาไม่เจอ
        // ========================================================

        int notFound = Arrays.binarySearch(numbers3,99);

        System.out.println("Search 99 = " + notFound);

        // จะได้ค่าติดลบ
        //
        // ไม่ควรจำเป็นตัวเลขตายตัว แต่ให้จำว่า
        //
        // < 0
        // = ไม่พบข้อมูล


        // ========================================================
        // 4. Arrays.equals()
        // ========================================================
        // ใช้ตรวจสอบว่า Array 1 และ Array 2 มีข้อมูลเหมือนกันหรือไม่
        //
        // ผลลัพธ์เป็น
        // true / false
        //
        // ต้องเหมือนกันทั้ง
        //
        // - จำนวนสมาชิก
        // - ค่า
        // - ลำดับ


        int[] a = {1, 2, 3};

        int[] b = {1, 2, 3};

        int[] c = {3, 2, 1};

        System.out.println(Arrays.equals(a, b)); // true

        System.out.println(Arrays.equals(a, c)); // false


        // ========================================================
        // ⚠️ Arrays.equals() กับ ==
        // ========================================================
        // สำหรับ Array
        //
        // == ไม่ได้ใช้ตรวจว่า "ข้อมูลข้างในเหมือนกันหรือไม่"
        //
        // == ใช้ตรวจว่า เป็น Object / Array ตัวเดียวกันหรือไม่
        //
        //
        // ดังนั้น
        //
        // a == b
        //
        // จะเป็น false
        //
        // แม้ข้อมูลจะเหมือนกัน
        //
        //
        // ถ้าต้องการเปรียบเทียบข้อมูล ให้ใช้
        //
        // Arrays.equals(a, b)


        System.out.println("a == b : " + (a == b)); // false

        System.out.println("Arrays.equals(a, b) : " + Arrays.equals(a, b)); // true


        // ========================================================
        // 5. Arrays.fill()
        // ========================================================
        // ใช้เติมค่าเดียวกัน ลงในทุกช่องของ Array
        //
        //
        // เช่น
        //
        // [0, 0, 0, 0, 0]
        //
        // fill ด้วย 100
        //
        // จะกลายเป็น
        //
        // [100, 100, 100, 100, 100]


        int[] numbers = new int[5];

        Arrays.fill(numbers,100);

        System.out.println(Arrays.toString(numbers));

        // [100, 100, 100, 100, 100]


        // ========================================================
        // fill() เฉพาะบางช่วง
        // ========================================================
        // สามารถกำหนด
        //
        // fromIndex
        // toIndex
        //
        // โดย toIndex "ไม่รวม"


        int[] values = {1, 2, 3, 4, 5};

        Arrays.fill(values,1,4,99);

        System.out.println(Arrays.toString(values));

        // [1, 99, 99, 99, 5]
        //
        // Index 1, 2, 3 ถูกเปลี่ยน
        //
        // Index 4 ไม่ถูกเปลี่ยน


        // ========================================================
        // 6. Arrays.copyOf()
        // ========================================================
        // ใช้สร้าง Array ใหม่ โดยคัดลอกข้อมูลจาก Array เดิม
        //
        // ตัวอย่าง


        int[] numbers4 = {11, 22, 33};

        int[] copy = Arrays.copyOf(numbers4, numbers4.length);

        System.out.println(Arrays.toString(copy)); // [11, 22, 33]


        // ========================================================
        // copyOf() สามารถเปลี่ยนขนาดได้
        // ========================================================
        // ถ้าขนาดใหม่มากกว่าเดิม ช่องที่เพิ่มจะได้ค่า Default
        //
        // int -> 0


        int[] bigger = Arrays.copyOf(numbers4,5);

        System.out.println(Arrays.toString(bigger));

        // [11, 22, 33, 0, 0]

        // ถ้าขนาดใหม่เล็กกว่าเดิม ข้อมูลส่วนเกินจะถูกตัดออก


        int[] smaller = Arrays.copyOf(numbers4,2);

        System.out.println(Arrays.toString(smaller)); // [11, 22]


        // ========================================================
        // 7. Arrays.copyOfRange()
        // ========================================================
        // ใช้คัดลอกเฉพาะบางช่วงของ Array
        //
        //
        // รูปแบบ
        //
        // Arrays.copyOfRange(
        //     array,
        //     from,
        //     to
        // );
        //
        //
        // ⚠️ to ไม่รวม
        //
        //
        // ตัวอย่าง
        //
        // Index
        //
        //   0   1   2   3   4
        //  10  20  30  40  50
        //
        //
        // copyOfRange(numbers5, 1, 3)
        //
        // จะเอา
        //
        // Index 1
        // Index 2
        //
        // ไม่เอา Index 3


        int[] numbers5 = {10, 20, 30, 40, 50};

        int[] copyRange = Arrays.copyOfRange(
                numbers5,
                1,
                3
        );

        System.out.println(Arrays.toString(copyRange));

        // [20, 30]


        // ========================================================
        // 8. Arrays.stream()
        // ========================================================
        // Stream = วิธีหนึ่งในการประมวลผลข้อมูล แบบเป็นลำดับ
        //
        // Arrays.stream(array)
        //
        // ใช้เปลี่ยน Array ให้เป็น Stream
        //
        // จากนั้นสามารถใช้ Method เช่น
        //
        // sum()
        // average()
        // max()
        // min()
        // count()
        // filter()
        // map()
        //
        // เพื่อประมวลผลข้อมูลได้


        int[] numbers6 = {10, 20, 30};


        // ========================================================
        // 8.1 sum()
        // ========================================================
        // หาผลรวม


        int sum = Arrays
                .stream(numbers6)
                .sum();

        System.out.println("Sum = " + sum); // Sum = 60


        // ========================================================
        // 8.2 average()
        // ========================================================
        // หาค่าเฉลี่ย
        //
        // average() คืนค่า OptionalDouble
        //
        // จึงมักใช้
        //
        // .orElse(0)
        //
        // เพื่อกำหนดค่า ถ้าไม่มีข้อมูล


        double avg = Arrays
                .stream(numbers6)
                .average()
                .orElse(0);

        System.out.println("Average = " + avg); // Average = 20.0


        // ========================================================
        // 8.3 max()
        // ========================================================
        // หาค่าสูงสุด


        int max = Arrays
                .stream(numbers6)
                .max()
                .orElse(0);

        System.out.println("Max = " + max); // Max = 30


        // ========================================================
        // 8.4 min()
        // ========================================================
        // หาค่าต่ำสุด


        int min = Arrays
                .stream(numbers6)
                .min()
                .orElse(0);

        System.out.println("Min = " + min); // Min = 10


        // ========================================================
        // 8.5 count()
        // ========================================================
        // นับจำนวนสมาชิก


        long count = Arrays
                .stream(numbers6)
                .count();

        System.out.println("Count = " + count); // Count = 3


        // ========================================================
        // 8.6 filter()
        // ========================================================
        // filter = กรองข้อมูล
        //
        // ตัวอย่าง
        // เอาเฉพาะเลขที่มากกว่า 15


        long filteredCount = Arrays
                .stream(numbers6)
                .filter(number -> number > 15)
                .count();

        System.out.println("Numbers > 15 = " + filteredCount); // Numbers > 15 = 2


        // ========================================================
        // 9. Arrays.deepToString()
        // ========================================================
        // ใช้แสดงผล Array หลายมิติ
        //
        // เช่น
        //
        // int[][]


        int[][] matrix = {
                {1, 2},
                {3, 4}
        };

        System.out.println( Arrays.deepToString(matrix));

        // [[1, 2], [3, 4]]


        // ========================================================
        // ทำไมต้อง deepToString()?
        // ========================================================
        // ถ้าใช้
        //
        // Arrays.toString(matrix)
        //
        // จะไม่ได้แสดงข้อมูลด้านใน
        // ของ Array หลายมิติอย่างที่เราต้องการ
        //
        // ดังนั้น
        //
        // 1D Array -> Arrays.toString()
        //
        //
        // Multi-dimensional Array -> Arrays.deepToString()


        // ========================================================
        // 10. Arrays.deepEquals()
        // ========================================================
        // ใช้เปรียบเทียบข้อมูล ของ Array หลายมิติ
        //
        // คล้าย Arrays.equals() แต่รองรับ Nested Array


        int[][] matrixA = {
                {1, 2},
                {3, 4}
        };

        int[][] matrixB = {
                {1, 2},
                {3, 4}
        };

        System.out.println(
                Arrays.deepEquals(
                        matrixA,
                        matrixB
                )
        );

        // true


        // ========================================================
        // 11. เรียงจากมาก → น้อย
        // ========================================================
        // Arrays.sort() สำหรับ int[]
        // จะเรียงจากน้อย → มาก
        //
        //
        // ถ้าต้องการมาก → น้อย สามารถใช้ Integer[]
        // และ Comparator.reverseOrder()
        //
        // เรื่องนี้สำคัญเพราะ
        //
        // int[]
        //
        // เป็น Primitive Array
        //
        // ส่วน
        //
        // Integer[]
        //
        // เป็น Reference Type Array


        Integer[] scores = {80, 95, 70, 100};

        Arrays.sort(
                scores,
                java.util.Comparator.reverseOrder()
        );

        System.out.println(Arrays.toString(scores)); // [100, 95, 80, 70]


        // ========================================================
        // 12. สรุป Method สำคัญ
        // ========================================================
        /*
         * ========================================================
         * Arrays Methods
         * ========================================================
         *
         * toString()
         * --------------------------------------------------------
         * แปลง Array เป็น String
         *
         * Arrays.toString(arr)
         *
         *
         * ========================================================
         *
         * sort()
         * --------------------------------------------------------
         * เรียงจากน้อย → มาก
         *
         * Arrays.sort(arr)
         *
         * ⚠️ เปลี่ยน Array เดิม
         *
         *
         * ========================================================
         *
         * binarySearch()
         * --------------------------------------------------------
         * ค้นหาโดย Binary Search
         *
         * ต้อง sort ก่อน
         *
         * Arrays.binarySearch(arr, target)
         *
         *
         * พบ
         * -> คืน Index
         *
         * ไม่พบ
         * -> ค่าติดลบ
         *
         *
         * ========================================================
         *
         * equals()
         * --------------------------------------------------------
         * เปรียบเทียบ Array 1 มิติ
         *
         * Arrays.equals(a, b)
         *
         *
         * ========================================================
         *
         * fill()
         * --------------------------------------------------------
         * เติมค่าลงใน Array
         *
         * Arrays.fill(arr, value)
         *
         *
         * ========================================================
         *
         * copyOf()
         * --------------------------------------------------------
         * คัดลอก Array
         * และกำหนดขนาดใหม่ได้
         *
         *
         * ========================================================
         *
         * copyOfRange()
         * --------------------------------------------------------
         * คัดลอกเฉพาะบางช่วง
         *
         * from = รวม
         * to   = ไม่รวม
         *
         *
         * ========================================================
         *
         * stream()
         * --------------------------------------------------------
         * ประมวลผลข้อมูลใน Array
         *
         * sum()
         * average()
         * max()
         * min()
         * count()
         * filter()
         * map()
         *
         *
         * ========================================================
         *
         * deepToString()
         * --------------------------------------------------------
         * แสดงผล Array หลายมิติ
         *
         *
         * ========================================================
         *
         * deepEquals()
         * --------------------------------------------------------
         * เปรียบเทียบ Array หลายมิติ
         *
         *
         * ========================================================
         */


        // ========================================================
        // สิ่งที่ควรจำมากที่สุด
        // ========================================================
        /*
         *
         * 1. Array มี Method จัดการผ่าน Class Arrays
         *
         *
         * 2. ต้อง import
         *
         *    import java.util.Arrays;
         *
         *
         * 3. sort() เปลี่ยน Array เดิม
         *
         *
         * 4. binarySearch()
         *    ต้อง sort ก่อน
         *
         *
         * 5. equals()
         *    ใช้เปรียบเทียบ "ข้อมูล"
         *
         *
         * 6. == สำหรับ Array
         *    ใช้เปรียบเทียบ Reference
         *
         *
         * 7. copyOf()
         *    คัดลอกทั้ง Array และกำหนดขนาดใหม่ได้
         *
         *
         * 8. copyOfRange()
         *    ตัวท้ายไม่รวม
         *
         *
         * 9. toString()
         *    ใช้กับ Array 1 มิติ
         *
         *
         * 10. deepToString()
         *     ใช้กับ Array หลายมิติ
         *
         *
         * 11. equals()
         *     ใช้กับ Array 1 มิติ
         *
         *
         * 12. deepEquals()
         *     ใช้กับ Array หลายมิติ
         *
         *
         * 13. Arrays.stream()
         *     ช่วยประมวลผลข้อมูลโดยไม่ต้องเขียน Loop เอง
         *
         */
    }
}